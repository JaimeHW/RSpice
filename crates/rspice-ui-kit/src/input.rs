//! Ordered input transfer when a command changes the focused surface.

use egui::{Context, Event, Id, InputState, Key, KeyboardShortcut, Modifiers};

/// Input on either side of an activating command, excluding its key strokes.
pub struct InputTransition {
    before: Vec<Event>,
    following: Vec<Event>,
}

impl InputTransition {
    pub fn after_keys(input: &InputState, keys: &[(Key, Modifiers)]) -> Option<Self> {
        Self::after_keys_with_order(input, keys, TextEventOrder::infer(&input.events))
    }

    fn after_keys_with_order(
        input: &InputState,
        keys: &[(Key, Modifiers)],
        order: TextEventOrder,
    ) -> Option<Self> {
        let indices = command_event_indices(&input.events, keys, keys.len(), order)?;
        let end = indices.last().map_or(0, |index| index + 1);
        let mut before = input.events[..end].to_vec();
        remove_events_at_indices(&mut before, indices);
        Some(Self {
            before,
            following: input.events[end..].to_vec(),
        })
    }

    pub fn after_shortcut(input: &InputState, shortcut: KeyboardShortcut) -> Option<Self> {
        let modifiers = input.events.iter().find_map(|event| match event {
            Event::Key {
                key,
                modifiers,
                pressed: true,
                repeat: false,
                ..
            } if *key == shortcut.logical_key
                && modifiers.matches_logically(shortcut.modifiers) =>
            {
                Some(*modifiers)
            }
            _ => None,
        })?;
        Self::after_keys(input, &[(shortcut.logical_key, modifiers)])
    }

    /// A request already accepted by a menu owns the remaining input.
    pub fn remaining(input: &InputState) -> Self {
        Self {
            before: Vec::new(),
            following: input.events.clone(),
        }
    }

    /// The continuation of an accepted pointer or keyboard button activation.
    pub fn after_activation(input: &InputState) -> Self {
        Self::after_activation_with_order(input, TextEventOrder::infer(&input.events))
    }

    fn after_activation_with_order(input: &InputState, order: TextEventOrder) -> Self {
        let Some(index) = input.events.iter().position(|event| {
            matches!(
                event,
                Event::PointerButton {
                    button: egui::PointerButton::Primary,
                    pressed: false,
                    ..
                } | Event::Key {
                    key: Key::Enter | Key::Space,
                    pressed: true,
                    repeat: false,
                    ..
                }
            )
        }) else {
            return Self::remaining(input);
        };
        if let Event::Key { key, modifiers, .. } = input.events[index]
            && let Some(transition) = Self::after_keys_with_order(input, &[(key, modifiers)], order)
        {
            return transition;
        }
        let end = index + 1;
        Self {
            before: input.events[..end].to_vec(),
            following: input.events[end..].to_vec(),
        }
    }

    /// Render and commit preceding edits before binding the new surface's state.
    pub fn preceding_scope(&self, ctx: &Context) -> InputScope {
        InputScope::replace(ctx, Some(self.before.clone()))
    }

    pub fn route(self, ctx: &Context, owner: Id) {
        ctx.input_mut(|input| input.events = self.before);
        hand_opening_input(ctx, owner, self.following);
    }
}

/// Give a surface the input that follows the command opening it, when the
/// caller already holds those events instead of splitting them out of the
/// current batch. The surface collects them with [`InputScope::enter`].
pub fn hand_opening_input(ctx: &Context, owner: Id, events: Vec<Event>) {
    ctx.data_mut(|data| data.insert_temp(owner.with("opening-input"), events));
}

/// Give one surface its continuation without replaying it into later controls.
pub struct InputScope {
    ctx: Context,
    previous: Option<Vec<Event>>,
}

impl InputScope {
    pub fn enter(ctx: &Context, owner: Id) -> Self {
        let following =
            ctx.data_mut(|data| data.remove_temp::<Vec<Event>>(owner.with("opening-input")));
        Self::replace(ctx, following)
    }

    pub fn discard(ctx: &Context, owner: Id) {
        ctx.data_mut(|data| data.remove_temp::<Vec<Event>>(owner.with("opening-input")));
    }

    fn replace(ctx: &Context, events: Option<Vec<Event>>) -> Self {
        Self {
            ctx: ctx.clone(),
            previous: events
                .map(|events| ctx.input_mut(|input| std::mem::replace(&mut input.events, events))),
        }
    }
}

impl Drop for InputScope {
    fn drop(&mut self) {
        if let Some(previous) = self.previous.take() {
            self.ctx.input_mut(|input| input.events = previous);
        }
    }
}

/// Remove exact presses atomically, including text generated by the command's
/// prefix. Deferred presses retain their text for the newly focused surface.
pub fn consume_keys(
    input: &mut InputState,
    keys: &[(Key, Modifiers)],
    command_key_count: usize,
) -> bool {
    let order = TextEventOrder::infer(&input.events);
    let Some(indices) = command_event_indices(&input.events, keys, command_key_count, order) else {
        return false;
    };
    remove_events_at_indices(&mut input.events, indices);
    true
}

/// Which side of its [`Event::Key`] a keystroke's generated text sits on.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum TextEventOrder {
    BeforeKey,
    AfterKey,
}

impl TextEventOrder {
    /// Read the order off the batch itself, because the host does not answer
    /// it once and for all.
    ///
    /// egui-winit always emits the key before its text. eframe's web keydown
    /// callback emits the text first, but only while the canvas holds DOM
    /// focus: with the hidden text agent focused — which is exactly while a
    /// text field is being edited — keydown pushes the key alone and the
    /// character arrives afterwards from the agent's own `input` event. So on
    /// the web both orders occur, and the build target cannot decide.
    ///
    /// The first printable key whose own character sits on exactly one side
    /// settles the whole batch. A key whose character sits on neither side
    /// (`ab`: the text before `Key(b)` is the previous key's) and one whose
    /// character sits on both (`aa` typed in one frame) are skipped, so an
    /// ambiguous key never decides the order and a later unambiguous one
    /// still can.
    fn infer(events: &[Event]) -> Self {
        for (index, event) in events.iter().enumerate() {
            let Event::Key {
                key,
                modifiers,
                pressed: true,
                ..
            } = event
            else {
                continue;
            };
            if !owns_generated_text(*key, *modifiers) {
                continue;
            }
            let generated_at = |index: Option<usize>| {
                index.and_then(|index| events.get(index)).is_some_and(
                    |event| matches!(event, Event::Text(text) if is_generated_text(text, *key)),
                )
            };
            match (
                generated_at(index.checked_sub(1)),
                generated_at(index.checked_add(1)),
            ) {
                (true, false) => return Self::BeforeKey,
                (false, true) => return Self::AfterKey,
                _ => {}
            }
        }
        Self::host_default()
    }

    /// A batch with no key-generated text to claim makes both answers
    /// equivalent, so keep the host's usual order rather than invent a third
    /// state.
    fn host_default() -> Self {
        if cfg!(target_arch = "wasm32") {
            Self::BeforeKey
        } else {
            Self::AfterKey
        }
    }
}

/// Whether this keystroke generates text of its own: a command chord does
/// not, and neither does a key that is not a single character or Space.
fn owns_generated_text(key: Key, modifiers: Modifiers) -> bool {
    !modifiers.command
        && !modifiers.ctrl
        && !modifiers.mac_cmd
        && (key.name().chars().count() == 1 || key == Key::Space)
}

/// Whether `text` is the character this key generates. [`Key::name`] is the
/// character itself for the letters and digits, in upper case, and shift
/// decides the case of what the host sends.
fn is_generated_text(text: &str, key: Key) -> bool {
    let mut characters = text.chars();
    let Some(character) = characters.next() else {
        return false;
    };
    if characters.next().is_some() {
        return false;
    }
    if key == Key::Space {
        return character == ' ';
    }
    let mut name = key.name().chars();
    name.next()
        .is_some_and(|named| name.next().is_none() && named.eq_ignore_ascii_case(&character))
}

fn command_event_indices(
    events: &[Event],
    keys: &[(Key, Modifiers)],
    command_key_count: usize,
    order: TextEventOrder,
) -> Option<Vec<usize>> {
    let command_keys = keys.get(..command_key_count)?;
    let mut indices = matching_key_indices(events, keys)?;
    for (position, (key, modifiers)) in command_keys.iter().enumerate() {
        if !owns_generated_text(*key, *modifiers) {
            continue;
        }
        let text_index = match order {
            TextEventOrder::BeforeKey => indices[position].checked_sub(1),
            TextEventOrder::AfterKey => indices[position].checked_add(1),
        };
        if let Some(index) = text_index
            && matches!(events.get(index), Some(Event::Text(_)))
        {
            indices.push(index);
        }
    }
    indices.sort_unstable();
    Some(indices)
}

fn matching_key_indices(events: &[Event], keys: &[(Key, Modifiers)]) -> Option<Vec<usize>> {
    let mut events = events.iter().enumerate();
    let mut indices = Vec::with_capacity(keys.len());
    for (key, modifiers) in keys {
        let (index, _) = events.find(|(_, event)| {
            matches!(event, Event::Key {
                key: event_key, modifiers: event_modifiers, pressed: true, repeat: false, ..
            } if event_key == key && event_modifiers == modifiers)
        })?;
        indices.push(index);
    }
    Some(indices)
}

fn remove_events_at_indices(events: &mut Vec<Event>, indices: Vec<usize>) {
    let mut indices = indices.into_iter().peekable();
    let mut index = 0;
    events.retain(|_| {
        let consume = indices.peek() == Some(&index);
        if consume {
            indices.next();
        }
        index += 1;
        !consume
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    fn press(key: Key, modifiers: Modifiers) -> Event {
        Event::Key {
            key,
            physical_key: None,
            pressed: true,
            repeat: false,
            modifiers,
        }
    }

    fn typed(key: Key, text: &str, modifiers: Modifiers, order: TextEventOrder) -> Vec<Event> {
        let key = press(key, modifiers);
        let text = Event::Text(text.to_owned());
        match order {
            TextEventOrder::BeforeKey => vec![text, key],
            TextEventOrder::AfterKey => vec![key, text],
        }
    }

    #[test]
    fn the_inferred_order_is_the_order_the_batch_was_built_in() {
        for order in [TextEventOrder::BeforeKey, TextEventOrder::AfterKey] {
            for (key, text, modifiers) in [
                (Key::R, "r", Modifiers::NONE),
                (Key::I, "I", Modifiers::SHIFT),
                (Key::Space, " ", Modifiers::NONE),
            ] {
                assert_eq!(
                    TextEventOrder::infer(&typed(key, text, modifiers, order)),
                    order
                );
            }
        }
    }

    /// The web emits both orders: the text first while the canvas has DOM
    /// focus, the key first while the hidden text agent is focused for a text
    /// field. Neither is the build target's business.
    #[test]
    fn both_web_orders_are_recognised_whatever_the_build_target() {
        let text_agent_focused = vec![press(Key::X, Modifiers::NONE), Event::Text("x".to_owned())];
        assert_eq!(
            TextEventOrder::infer(&text_agent_focused),
            TextEventOrder::AfterKey
        );
        let canvas_focused = vec![Event::Text("x".to_owned()), press(Key::X, Modifiers::NONE)];
        assert_eq!(
            TextEventOrder::infer(&canvas_focused),
            TextEventOrder::BeforeKey
        );
    }

    /// `ab`: the text beside the command key on one side is its own and on the
    /// other side the previous keystroke's. Taking either neighbour would
    /// swallow the earlier character.
    #[test]
    fn a_command_key_takes_its_own_text_and_leaves_the_previous_keystrokes() {
        for order in [TextEventOrder::BeforeKey, TextEventOrder::AfterKey] {
            let preceding = typed(Key::A, "a", Modifiers::NONE, order);
            let mut input = InputState::default();
            input.events = preceding.clone();
            input
                .events
                .extend(typed(Key::B, "b", Modifiers::NONE, order));
            assert!(consume_keys(&mut input, &[(Key::B, Modifiers::NONE)], 1));
            assert_eq!(input.events, preceding);
        }
    }

    /// `aa`: both neighbours of the second key hold the same character, so
    /// only the batch as a whole says which one it generated.
    #[test]
    fn a_repeated_character_consumes_its_own_text_in_both_orders() {
        for order in [TextEventOrder::BeforeKey, TextEventOrder::AfterKey] {
            let mut input = InputState::default();
            input.events = typed(Key::A, "a", Modifiers::NONE, order);
            input
                .events
                .extend(typed(Key::A, "a", Modifiers::NONE, order));
            assert!(consume_keys(
                &mut input,
                &[(Key::A, Modifiers::NONE), (Key::A, Modifiers::NONE)],
                2,
            ));
            assert!(input.events.is_empty());
        }
    }

    #[test]
    fn a_batch_that_generates_no_text_keeps_the_hosts_order_and_its_events() {
        let escape = vec![press(Key::Escape, Modifiers::NONE)];
        assert_eq!(
            TextEventOrder::infer(&escape),
            TextEventOrder::host_default()
        );
        for order in [TextEventOrder::BeforeKey, TextEventOrder::AfterKey] {
            let chord = typed(Key::K, "k", Modifiers::CTRL, order);
            assert_eq!(
                TextEventOrder::infer(&chord),
                TextEventOrder::host_default()
            );
            let mut input = InputState::default();
            input.events = chord.clone();
            assert!(consume_keys(&mut input, &[(Key::K, Modifiers::CTRL)], 1));
            assert_eq!(input.events, vec![Event::Text("k".to_owned())]);
        }
        let mut input = InputState::default();
        input.events = escape;
        assert!(consume_keys(
            &mut input,
            &[(Key::Escape, Modifiers::NONE)],
            1
        ));
        assert!(input.events.is_empty());
    }

    #[test]
    fn button_activation_owns_space_but_preserves_surrounding_edits() {
        for order in [TextEventOrder::BeforeKey, TextEventOrder::AfterKey] {
            for key in [Key::Space, Key::Enter] {
                let preceding = vec![Event::Paste("earlier edit".to_owned())];
                let following = vec![Event::Text("configuration".to_owned())];
                let mut input = InputState::default();
                input.events = preceding.clone();
                if key == Key::Space {
                    input.events.extend(typed(key, " ", Modifiers::NONE, order));
                } else {
                    input.events.push(press(key, Modifiers::NONE));
                }
                input.events.extend(following.clone());
                let transition = InputTransition::after_activation_with_order(&input, order);
                assert_eq!(transition.before, preceding);
                assert_eq!(transition.following, following);
            }
        }
    }

    #[test]
    fn pointer_activation_preserves_following_space_and_missing_activation_preserves_input() {
        let mut input = InputState::default();
        input.events = vec![Event::Text(" ".to_owned())];
        let transition = InputTransition::after_activation(&input);
        assert!(transition.before.is_empty());
        assert_eq!(transition.following, input.events);

        let pointer = Event::PointerButton {
            pos: egui::Pos2::ZERO,
            button: egui::PointerButton::Primary,
            pressed: false,
            modifiers: Modifiers::NONE,
        };
        input.events.insert(0, pointer.clone());
        let transition = InputTransition::after_activation(&input);
        assert_eq!(transition.before, vec![pointer]);
        assert_eq!(transition.following, vec![Event::Text(" ".to_owned())]);
    }

    #[test]
    fn command_text_is_consumed_in_both_host_orders_without_eating_continuation() {
        for order in [TextEventOrder::BeforeKey, TextEventOrder::AfterKey] {
            let mut events = typed(Key::I, "I", Modifiers::SHIFT, order);
            events.extend(typed(Key::R, "r", Modifiers::NONE, order));
            events.push(Event::Paste("esistor".to_owned()));
            let indices = command_event_indices(
                &events,
                &[(Key::I, Modifiers::SHIFT), (Key::R, Modifiers::NONE)],
                1,
                order,
            )
            .unwrap();
            remove_events_at_indices(&mut events, indices);
            assert_eq!(
                events,
                vec![
                    Event::Text("r".to_owned()),
                    Event::Paste("esistor".to_owned())
                ]
            );
        }
    }

    #[test]
    fn printable_palette_chord_preserves_preceding_edits_and_following_input() {
        for order in [TextEventOrder::BeforeKey, TextEventOrder::AfterKey] {
            let preceding = typed(Key::I, "i", Modifiers::NONE, order);
            let following = typed(Key::R, "r", Modifiers::NONE, order);
            let mut input = InputState::default();
            input.events = preceding.clone();
            input
                .events
                .extend(typed(Key::I, "I", Modifiers::SHIFT, order));
            input
                .events
                .extend(typed(Key::K, "K", Modifiers::SHIFT, order));
            input.events.extend(following.clone());
            let transition = InputTransition::after_keys_with_order(
                &input,
                &[(Key::I, Modifiers::SHIFT), (Key::K, Modifiers::SHIFT)],
                order,
            )
            .unwrap();
            assert_eq!(transition.before, preceding);
            assert_eq!(transition.following, following);
        }
    }

    #[test]
    fn native_shortcut_without_text_preserves_the_previous_keystrokes_text() {
        let events = vec![
            press(Key::I, Modifiers::NONE),
            Event::Text("i".to_owned()),
            press(Key::I, Modifiers::SHIFT),
        ];
        assert_eq!(
            command_event_indices(
                &events,
                &[(Key::I, Modifiers::SHIFT)],
                1,
                TextEventOrder::AfterKey,
            ),
            Some(vec![2])
        );
    }

    #[test]
    fn command_modifiers_and_nonprintable_keys_do_not_own_adjacent_text() {
        for order in [TextEventOrder::BeforeKey, TextEventOrder::AfterKey] {
            for (key, modifiers) in [
                (Key::K, Modifiers::COMMAND),
                (Key::K, Modifiers::CTRL),
                (Key::K, Modifiers::MAC_CMD),
                (Key::F1, Modifiers::NONE),
            ] {
                let mut events = typed(key, "query", modifiers, order);
                let indices =
                    command_event_indices(&events, &[(key, modifiers)], 1, order).unwrap();
                remove_events_at_indices(&mut events, indices);
                assert_eq!(events, vec![Event::Text("query".to_owned())]);
            }
        }
    }

    #[test]
    fn incomplete_printable_chords_do_not_consume_any_input() {
        for order in [TextEventOrder::BeforeKey, TextEventOrder::AfterKey] {
            let events = typed(Key::I, "I", Modifiers::SHIFT, order);
            assert!(
                command_event_indices(
                    &events,
                    &[(Key::I, Modifiers::SHIFT), (Key::K, Modifiers::SHIFT)],
                    2,
                    order,
                )
                .is_none()
            );
        }
    }
}
