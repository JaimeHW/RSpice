//! The two clocked circuits of the scale suite.
//!
//! The rest of the suite is combinational, which is the blind spot of a
//! gate-level benchmark family: nothing in it has state, so nothing in it
//! exercises an event scheduler across a clock edge at scale. These two do,
//! and they are written behaviourally because that is where a scheduler's
//! non-blocking semantics live.
//!
//! The sources are assembled here rather than vendored by hand so the
//! determinism test covers them the same way it covers the netlists.

/// Feedback taps of [`lfsr32`], as bit positions of the state word.
///
/// The polynomial is `x^32 + x^22 + x^2 + x + 1`, whose exponents 32, 22, 2
/// and 1 name state bits 31, 21, 1 and 0 in the zero-based spelling below. It
/// is primitive over GF(2), so the recurrence walks all 2^32 - 1 non-zero
/// states before repeating; zero is a fixed point, which is a property of
/// every Fibonacci LFSR and is covered deliberately by one vector rather than
/// worked around in the design.
pub const LFSR32_TAPS: [u32; 4] = [31, 21, 1, 0];

/// The pipeline depth of [`pipe_mac8`]: operands, product, accumulate.
pub const PIPE_MAC8_STAGES: usize = 3;

/// The Verilog source of one behavioural circuit.
pub fn source(name: &str) -> Option<String> {
    Some(match name {
        "lfsr32" => lfsr32(),
        "pipe_mac8" => pipe_mac8(),
        _ => return None,
    })
}

fn header(what: &str) -> String {
    let mut out = String::new();
    for line in [
        what,
        "",
        "Generated by rspice-conformance's Verilog scale-suite generator; edit",
        "the generator, not this file. Designed from the recurrence and the",
        "pipeline description in the generator's own documentation.",
    ] {
        if line.is_empty() {
            out.push_str("//\n");
        } else {
            out.push_str("// ");
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// A 32-bit Fibonacci linear feedback shift register.
///
/// One `always @(posedge clk)` block and non-blocking updates: the feedback
/// term reads the state the edge started with, so a scheduler that lets the
/// shift see its own result produces a different sequence from the first edge
/// onward.
fn lfsr32() -> String {
    let taps = LFSR32_TAPS
        .iter()
        .map(|bit| format!("q[{bit}]"))
        .collect::<Vec<_>>()
        .join(" ^ ");
    let mut out = header("lfsr32 -- 32-bit Fibonacci linear feedback shift register.");
    out.push_str(&format!(
        "//\n\
         // The feedback polynomial is x^32 + x^22 + x^2 + x + 1, a primitive\n\
         // polynomial over GF(2), so the state walks every one of the 2^32 - 1\n\
         // non-zero words before it repeats. Zero is a fixed point: a Fibonacci\n\
         // LFSR loaded with zero stays there, and one vector loads it to say so.\n\
         \n\
         module lfsr32 (clk, rst, ld, seed, q, fb, msb);\n\
         \x20 input             clk;\n\
         \x20 input             rst;\n\
         \x20 input             ld;\n\
         \x20 input      [31:0] seed;\n\
         \x20 output reg [31:0] q;\n\
         \x20 output            fb;\n\
         \x20 output            msb;\n\
         \n\
         \x20 assign fb  = {taps};\n\
         \x20 assign msb = q[31];\n\
         \n\
         \x20 always @(posedge clk) begin\n\
         \x20   if (rst)     q <= 32'h00000001;\n\
         \x20   else if (ld) q <= seed;\n\
         \x20   else         q <= {{q[30:0], fb}};\n\
         \x20 end\n\
         endmodule\n"
    ));
    out
}

/// A three-stage pipelined 8-bit multiply-accumulate.
///
/// Stage one registers the operands, stage two their product, stage three the
/// running total. Every write is non-blocking, so each stage reads what the
/// stage before it held *entering* the edge; a scheduler that updates in
/// source order instead would collapse the pipeline and let an operand reach
/// the accumulator two clocks early.
///
/// The operand registers are declared at the *product's* width rather than the
/// operands'. That is deliberate and it is what makes this case about the
/// scheduler and nothing else: written the other way the multiply's width
/// would be fixed by the assignment context — the rule of IEEE 1364-2005
/// section 5.4.1, under which the left-hand side of an assignment widens the
/// operation — and this case would be testing that rule as much as the
/// pipeline. Widening first states the intent locally and reads the same on
/// every simulator.
fn pipe_mac8() -> String {
    let mut out = header("pipe_mac8 -- three-stage pipelined 8-bit multiply-accumulate.");
    out.push_str(
        "//\n\
         // Latency is three clocks: operands in on the first edge, their\n\
         // product on the second, the accumulate on the third. `vld` follows\n\
         // `en` down the same three stages, so it says which accumulate the\n\
         // outputs belong to. `clr` zeroes the accumulator and outranks the\n\
         // accumulate on the same edge.\n\
         //\n\
         // The stage-one registers are as wide as the product, so the width\n\
         // of the multiply is fixed by its own operands rather than by the\n\
         // assignment it appears in.\n\
         \n\
         module pipe_mac8 (clk, rst, en, clr, a, b, prod, acc, vld);\n\
         \x20 input             clk;\n\
         \x20 input             rst;\n\
         \x20 input             en;\n\
         \x20 input             clr;\n\
         \x20 input      [7:0]  a;\n\
         \x20 input      [7:0]  b;\n\
         \x20 output reg [15:0] prod;\n\
         \x20 output reg [23:0] acc;\n\
         \x20 output reg        vld;\n\
         \n\
         \x20 reg [15:0] a1;\n\
         \x20 reg [15:0] b1;\n\
         \x20 reg        v1;\n\
         \x20 reg        v2;\n\
         \n\
         \x20 always @(posedge clk) begin\n\
         \x20   if (rst) begin\n\
         \x20     a1   <= 16'd0;\n\
         \x20     b1   <= 16'd0;\n\
         \x20     v1   <= 1'b0;\n\
         \x20     v2   <= 1'b0;\n\
         \x20     prod <= 16'd0;\n\
         \x20     acc  <= 24'd0;\n\
         \x20     vld  <= 1'b0;\n\
         \x20   end else begin\n\
         \x20     a1   <= a;\n\
         \x20     b1   <= b;\n\
         \x20     v1   <= en;\n\
         \x20     prod <= a1 * b1;\n\
         \x20     v2   <= v1;\n\
         \x20     vld  <= v2;\n\
         \x20     if (clr)     acc <= 24'd0;\n\
         \x20     else if (v2) acc <= acc + prod;\n\
         \x20   end\n\
         \x20 end\n\
         endmodule\n",
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn both_sources_regenerate_identically_and_report_nothing() {
        for name in ["lfsr32", "pipe_mac8"] {
            let text = source(name).expect("the circuit is in the suite");
            assert_eq!(text, source(name).unwrap(), "{name} is not deterministic");
            assert!(text.contains(&format!("module {name} (")), "{text}");
            assert!(text.ends_with("endmodule\n"), "{text}");
            for forbidden in ["$display", "$monitor", "$write", "initial"] {
                assert!(!text.contains(forbidden), "{name} uses {forbidden}");
            }
            assert!(!text.contains('\r'), "{name} carries a carriage return");
        }
    }

    #[test]
    fn the_taps_spell_the_documented_polynomial() {
        // Exponents 32, 22, 2, 1 of x^32 + x^22 + x^2 + x + 1, less one for
        // the zero-based state index.
        assert_eq!(LFSR32_TAPS, [31, 21, 1, 0]);
        assert_eq!(PIPE_MAC8_STAGES, 3);
    }
}
