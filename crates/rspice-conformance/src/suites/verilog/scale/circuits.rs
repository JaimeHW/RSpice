/// A 27-channel priority interrupt controller.
///
/// Twenty-seven request lines, a per-channel enable mask, and one global
/// enable, resolved to the five-bit index of the highest-numbered enabled
/// request, a valid flag, and an any-pending flag.
///
/// * `arm[i] = req[i] & msk[i]`
/// * `any    = |arm` — pending after masking, whatever the global enable says
/// * `a[i]   = arm[i] & gen`
/// * `vld    = any & gen`
/// * `hi[i]  = |{a[j] : j > i}`, a suffix-OR chain
/// * `sel[i] = a[i] & ~hi[i]`, one-hot on the highest set channel
/// * `id[k]  = |{sel[i] : bit k of i is set}`
///
/// The suffix-OR chain is the depth here: channel 0 can only win once every
/// higher channel has been ruled out, so the priority decision is 26 levels
/// from the request that loses it. The any-pending detector is the suite's
/// first deliberately wide cell — a 27-input reduction built from `or` gates
/// of eight inputs, because a controller's "anything at all?" output is not on
/// a critical path and a mapper would use the widest cell it had.
///
/// Unlike the arithmetic circuits of this suite, the controller is mapped onto
/// a library with true `and` and `or` cells rather than NAND, NOR and
/// inverters. That is the whole of the difference between its gate count and
/// what the same equations cost in [`alu8`], and it is deliberate: a suite in
/// which every circuit is mapped the same way would not exercise the
/// primitives it never reached for.
pub fn intc27() -> Design {
    const CHANNELS: usize = 27;
    let mut n = Builder::new("intc27");
    n.doc("A 27-channel priority interrupt controller: request lines, a");
    n.doc("per-channel enable mask, and a global enable resolved to the index");
    n.doc("of the highest-numbered enabled request. Mapped onto true `and` and");
    n.doc("`or` cells.");
    ports(
        &mut n,
        &[
            ("req", 27, true),
            ("msk", 27, true),
            ("gen", 1, true),
            ("id", 5, false),
            ("vld", 1, false),
            ("any", 1, false),
        ],
    );

    let req = bits("req", 27);
    let msk = bits("msk", 27);

    let arm: Vec<String> = (0..CHANNELS)
        .map(|i| n.two(Gate::And, "arm", &req[i], &msk[i]))
        .collect();

    // Wide cells, deliberately: eight-input `or` reductions feeding one more.
    let any_stage: Vec<String> = arm
        .chunks(8)
        .map(|chunk| n.gate(Gate::Or, "anyw", chunk))
        .collect();
    n.drive(Gate::Or, "any", &any_stage);

    let armed: Vec<String> = (0..CHANNELS)
        .map(|i| n.two(Gate::And, "en", &arm[i], "gen"))
        .collect();
    n.drive(Gate::And, "vld", &["any".to_string(), "gen".to_string()]);

    // Suffix OR: `hi[i]` is the OR of every channel above `i`.
    let mut hi = vec![String::new(); CHANNELS];
    hi[CHANNELS - 2] = armed[CHANNELS - 1].clone();
    for i in (0..CHANNELS - 2).rev() {
        hi[i] = n.two(Gate::Or, "hi", &armed[i + 1], &hi[i + 1]);
    }

    let mut sel = vec![String::new(); CHANNELS];
    sel[CHANNELS - 1] = armed[CHANNELS - 1].clone();
    for i in 0..CHANNELS - 1 {
        let clear = inv(&mut n, "nhi", &hi[i]);
        sel[i] = n.two(Gate::And, "sel", &armed[i], &clear);
    }

    for k in 0..5u32 {
        let terms: Vec<String> = (0..CHANNELS)
            .filter(|i| (*i as u32) >> k & 1 == 1)
            .map(|i| sel[i].clone())
            .collect();
        let value = n.reduce(Gate::Or, "enc", &terms, 2);
        n.drive(Gate::Buf, &format!("id[{k}]"), &[value]);
    }

    n.limit_fanout(4, &[]);
    design(
        "intc27",
        &provenance("intc27 -- 27-channel priority interrupt controller."),
        vec![n.finish()],
    )
}

