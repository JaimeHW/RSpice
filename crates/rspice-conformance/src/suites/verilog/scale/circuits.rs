/// A single-error-correcting, double-error-detecting decoder over a 16-bit
/// data word.
///
/// The codeword is the 21-bit Hamming(21,16) word plus one overall parity bit
/// covering all 21, which is what turns single-error correction into
/// double-error *detection*: a syndrome that names a position is trustworthy
/// only when the overall parity also disagrees.
///
/// * `syn[m]` — received check bit `m` XOR the data bits it covers
/// * `pchk`   — the overall parity of the whole received codeword
/// * `sec`    — `|syn & pchk`: one bit flipped, and it is corrected
/// * `ded`    — `|syn & ~pchk`: two bits flipped, and nothing is corrected
/// * `q`,`kc` — the corrected data and check bits
/// * `re`     — check bits recomputed from the corrected data, which a caller
///   compares against `kc` to watch the correction land
///
/// Mapped onto NAND gates apart from the wide decoder cells, so the XOR-heavy
/// syndrome, parity and re-encode trees carry four gates per XOR. The
/// re-encode trees sit downstream of the entire correction network, which is
/// what makes this circuit deep for its size.
pub fn secded16() -> Design {
    const DATA: usize = 16;
    const PARITY: u32 = 5;
    let mut n = Builder::new("secded16");
    n.doc("Single-error-correcting, double-error-detecting decoder over a");
    n.doc("16-bit data word: Hamming(21,16) plus one overall parity bit.");
    ports(
        &mut n,
        &[
            ("d", 16, true),
            ("c", 5, true),
            ("p", 1, true),
            ("q", 16, false),
            ("kc", 5, false),
            ("re", 5, false),
            ("syn", 5, false),
            ("sec", 1, false),
            ("ded", 1, false),
        ],
    );

    let d = bits("d", 16);
    let c = bits("c", 5);
    let positions = hamming_data_positions(PARITY, DATA);

    let syndrome: Vec<String> = (0..PARITY)
        .map(|m| {
            let mut terms = vec![c[m as usize].clone()];
            terms.extend(
                positions
                    .iter()
                    .enumerate()
                    .filter(|(_, position)| *position >> m & 1 == 1)
                    .map(|(index, _)| d[index].clone()),
            );
            let value = xor_tree_n(&mut n, "syn", &terms);
            n.drive(Gate::Buf, &format!("syn[{m}]"), &[value.clone()]);
            value
        })
        .collect();
    let complement: Vec<String> = syndrome
        .iter()
        .map(|net| inv(&mut n, "nsyn", net))
        .collect();

    // The overall parity of the received codeword: every data bit, every
    // check bit, and the overall parity bit itself.
    let mut overall = vec!["p".to_string()];
    overall.extend(d.iter().cloned());
    overall.extend(c.iter().cloned());
    let pchk = xor_tree_n(&mut n, "pchk", &overall);

    let nonzero = or_tree(&mut n, "nz", &syndrome);
    let clean = inv(&mut n, "npchk", &pchk);
    let correct = and2(&mut n, "sec", &nonzero, &pchk);
    n.drive(Gate::Buf, "sec", &[correct.clone()]);
    n.drive(Gate::And, "ded", &[nonzero, clean]);

    let mut corrected = Vec::with_capacity(DATA);
    for (index, position) in positions.iter().enumerate() {
        let literals: Vec<String> = (0..PARITY)
            .map(|m| {
                if position >> m & 1 == 1 {
                    syndrome[m as usize].clone()
                } else {
                    complement[m as usize].clone()
                }
            })
            .collect();
        let hit = n.gate(Gate::And, "hit", &literals);
        let flip = and2(&mut n, "flip", &hit, &correct);
        let value = xor2n(&mut n, "q", &d[index], &flip);
        n.drive(Gate::Buf, &format!("q[{index}]"), &[value.clone()]);
        corrected.push(value);
    }

    // The check bits are corrected too, so a single error anywhere in the
    // codeword leaves a consistent codeword behind.
    for m in 0..PARITY {
        let literals: Vec<String> = (0..PARITY)
            .map(|other| {
                if other == m {
                    syndrome[other as usize].clone()
                } else {
                    complement[other as usize].clone()
                }
            })
            .collect();
        let hit = n.gate(Gate::And, "khit", &literals);
        let flip = and2(&mut n, "kflip", &hit, &correct);
        let value = xor2n(&mut n, "kc", &c[m as usize], &flip);
        n.drive(Gate::Buf, &format!("kc[{m}]"), &[value]);
    }

    for m in 0..PARITY {
        let terms: Vec<String> = positions
            .iter()
            .enumerate()
            .filter(|(_, position)| *position >> m & 1 == 1)
            .map(|(index, _)| corrected[index].clone())
            .collect();
        let value = xor_tree_n(&mut n, "re", &terms);
        n.drive(Gate::Buf, &format!("re[{m}]"), &[value]);
    }

    n.limit_fanout(4, &[]);
    design(
        "secded16",
        &provenance("secded16 -- 16-bit single-error-correcting, double-error-detecting decoder."),
        vec![n.finish()],
    )
}

