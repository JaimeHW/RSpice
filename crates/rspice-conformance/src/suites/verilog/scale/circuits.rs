/// Whether a `sec32`-family circuit is mapped onto `xor` primitives or onto
/// NAND gates only.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EccStyle {
    /// `xor` primitives and wide `and` cells in the position decoder.
    Primitive,
    /// Every gate a `nand`, inverters included (`nand g (y, a, a);`).
    NandOnly,
}

impl EccStyle {
    fn module(self) -> &'static str {
        match self {
            EccStyle::Primitive => "sec32",
            EccStyle::NandOnly => "sec32n",
        }
    }
}

/// A single-error-correcting Hamming decoder over a 32-bit data word.
///
/// The codeword is 38 bits: check bits at positions 1, 2, 4, 8, 16 and 32, and
/// the 32 data bits at every other position from 1 upward. For check bit `k`
/// the syndrome is the received check bit XORed with every data bit whose
/// codeword position has bit `k` set; a non-zero syndrome names the codeword
/// position that flipped, and the data bit at that position is inverted.
///
/// `sec32` and `sec32n` are the same function in two structures: the first uses
/// `xor` primitives and six-input `and` cells in the position decoder, the
/// second is NAND-only down to its inverters, which a NAND-only library
/// spells `nand g (y, a, a);`. They must agree on every vector, which is a
/// third oracle that needs no simulator installed to arbitrate it.
pub fn sec32(style: EccStyle) -> Design {
    const DATA: usize = 32;
    const PARITY: u32 = 6;
    let mut n = Builder::new(style.module());
    n.doc("Single-error-correcting Hamming decoder over a 32-bit data word,");
    n.doc("with six check bits at codeword positions 1, 2, 4, 8, 16 and 32.");
    match style {
        EccStyle::Primitive => n.doc("Mapped onto `xor` primitives and wide `and` decoder cells."),
        EccStyle::NandOnly => {
            n.doc("Mapped onto `nand` gates alone -- inverters included, spelled");
            n.doc("`nand g (y, a, a);` -- so this is sec32's function in a");
            n.doc("structurally different netlist.");
        }
    }
    ports(
        &mut n,
        &[
            ("d", 32, true),
            ("c", 6, true),
            ("q", 32, false),
            ("syn", 6, false),
            ("err", 1, false),
        ],
    );

    let d = bits("d", 32);
    let c = bits("c", 6);
    let positions = hamming_data_positions(PARITY, DATA);

    let syndrome: Vec<String> = (0..PARITY)
        .map(|k| {
            let mut terms = vec![c[k as usize].clone()];
            terms.extend(
                positions
                    .iter()
                    .enumerate()
                    .filter(|(_, position)| *position >> k & 1 == 1)
                    .map(|(index, _)| d[index].clone()),
            );
            let value = match style {
                EccStyle::Primitive => xor_tree(&mut n, "syn", &terms),
                EccStyle::NandOnly => xor_tree_n(&mut n, "syn", &terms),
            };
            emit_through(&mut n, style, &format!("syn[{k}]"), &value);
            value
        })
        .collect();

    let complement: Vec<String> = syndrome
        .iter()
        .map(|net| inv_styled(&mut n, style, "nsyn", net))
        .collect();

    // `err` is the OR of the syndrome. In NAND-only form that is the NAND of
    // the complements, which is why the complements are computed first.
    match style {
        EccStyle::Primitive => {
            let value = or_tree(&mut n, "err", &syndrome);
            n.drive(Gate::Buf, "err", &[value]);
        }
        EccStyle::NandOnly => n.drive(Gate::Nand, "err", &complement),
    }

    for (index, position) in positions.iter().enumerate() {
        // One wide cell per data position, reading the syndrome bit or its
        // complement according to that position's binary spelling.
        let literals: Vec<String> = (0..PARITY)
            .map(|k| {
                if position >> k & 1 == 1 {
                    syndrome[k as usize].clone()
                } else {
                    complement[k as usize].clone()
                }
            })
            .collect();
        match style {
            EccStyle::Primitive => {
                // The decoder cell is a wide NAND and the correction the
                // matching XNOR: `d ^ hit` is `d ^ ~miss`, which is
                // `~(d ^ miss)`. Spelling it this way rather than with an AND
                // and an XOR costs nothing and is what puts the `xnor`
                // primitive into the suite.
                let miss = n.gate(Gate::Nand, "hit", &literals);
                n.drive(
                    Gate::Xnor,
                    &format!("q[{index}]"),
                    &[d[index].clone(), miss],
                );
            }
            EccStyle::NandOnly => {
                let miss = n.gate(Gate::Nand, "hit", &literals);
                // `d ^ hit` is `d ^ ~miss`, which is `~(d ^ miss)`: the
                // correction is the XOR against the decoder's inverted output,
                // inverted once more on its way to the port.
                let value = xor2n(&mut n, "cor", &d[index], &miss);
                n.drive(
                    Gate::Nand,
                    &format!("q[{index}]"),
                    &[value.clone(), value.clone()],
                );
            }
        }
    }

    if style == EccStyle::Primitive {
        n.limit_fanout(4, &[]);
    }
    let what = match style {
        EccStyle::Primitive => "sec32 -- single-error-correcting Hamming decoder, 32-bit word.",
        EccStyle::NandOnly => "sec32n -- sec32's function, in NAND gates only.",
    };
    design(style.module(), &provenance(what), vec![n.finish()])
}

fn inv_styled(n: &mut Builder, style: EccStyle, prefix: &str, net: &str) -> String {
    match style {
        EccStyle::Primitive => inv(n, prefix, net),
        // A NAND with both inputs tied is the inverter of a NAND-only library.
        EccStyle::NandOnly => n.two(Gate::Nand, prefix, net, net),
    }
}

/// Drive `port` with the value of `net`, in the style's own vocabulary: one
/// `buf`, or the two NANDs a NAND-only library buffers with.
fn emit_through(n: &mut Builder, style: EccStyle, port: &str, net: &str) {
    match style {
        EccStyle::Primitive => n.drive(Gate::Buf, port, &[net.to_string()]),
        EccStyle::NandOnly => {
            let once = n.two(Gate::Nand, "buf", net, net);
            n.drive(Gate::Nand, port, &[once.clone(), once]);
        }
    }
}

