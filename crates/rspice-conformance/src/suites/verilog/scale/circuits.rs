/// The eight functions of [`alu8`], in `f` order.
pub const ALU8_FUNCTIONS: [&str; 8] =
    ["add", "sub", "and", "or", "xor", "xnor", "pass_a", "pass_b"];

/// An 8-bit arithmetic and logic unit.
///
/// `f` selects one of eight functions; the carry chain runs on every one of
/// them, so `cout` and `ovf` describe `a + (b ^ sub) + cin` whatever `f` says,
/// and a caller reads them when the function is arithmetic.
///
/// * `f = 0` `a + b + cin`
/// * `f = 1` `a + ~b + cin`
/// * `f = 2..5` `a & b`, `a | b`, `a ^ b`, `~(a ^ b)`
/// * `f = 6, 7` `a`, `b`
///
/// The overflow flag carries a **deliberately redundant cone**, marked at its
/// site below: an AND of the top bit's carry-kill and carry-generate terms,
/// which cannot both be true, ORed into the overflow. Its output is zero for
/// every input and no vector can distinguish this circuit from the one without
/// it. It is here because the published benchmark family contains redundant
/// logic of exactly this kind, and a simulator has to evaluate it without
/// being confused by it.
pub fn alu8() -> Design {
    const WIDTH: usize = 8;
    let mut n = Builder::new("alu8");
    n.doc("An 8-bit arithmetic and logic unit: add, subtract, and, or, xor,");
    n.doc("xnor, and the two operand passes, with carry, overflow and zero.");
    ports(
        &mut n,
        &[
            ("a", 8, true),
            ("b", 8, true),
            ("f", 3, true),
            ("cin", 1, true),
            ("y", 8, false),
            ("cout", 1, false),
            ("ovf", 1, false),
            ("zero", 1, false),
        ],
    );

    let a = bits("a", 8);
    let operand = bits("b", 8);
    let f = bits("f", 3);

    // 3-to-8 decode, fan-in 2 throughout.
    let nf: Vec<String> = (0..3).map(|k| inv(&mut n, "nf", &f[k])).collect();
    let sel: Vec<String> = (0..8)
        .map(|code| {
            let literal = |k: usize| {
                if code >> k & 1 == 1 {
                    f[k].clone()
                } else {
                    nf[k].clone()
                }
            };
            let low = and2(&mut n, "dec", &literal(0), &literal(1));
            and2(&mut n, "dec", &low, &literal(2))
        })
        .collect();

    let sub = n.buffer("sub", &sel[1]);
    let beff: Vec<String> = (0..WIDTH)
        .map(|i| xor2n(&mut n, "beff", &operand[i], &sub))
        .collect();
    let (sum, carries) = ripple_add(&mut n, "add", &a, &beff, "cin");

    let and_unit: Vec<String> = (0..WIDTH)
        .map(|i| and2(&mut n, "u_and", &a[i], &operand[i]))
        .collect();
    let or_unit: Vec<String> = (0..WIDTH)
        .map(|i| or2(&mut n, "u_or", &a[i], &operand[i]))
        .collect();
    let xor_unit: Vec<String> = (0..WIDTH)
        .map(|i| xor2n(&mut n, "u_xor", &a[i], &operand[i]))
        .collect();
    let xnor_unit: Vec<String> = (0..WIDTH)
        .map(|i| xnor2n(&mut n, "u_xnor", &a[i], &operand[i]))
        .collect();

    let mut result = Vec::with_capacity(WIDTH);
    for i in 0..WIDTH {
        let sources = vec![
            sum[i].clone(),
            sum[i].clone(),
            and_unit[i].clone(),
            or_unit[i].clone(),
            xor_unit[i].clone(),
            xnor_unit[i].clone(),
            a[i].clone(),
            operand[i].clone(),
        ];
        let value = mux_onehot(&mut n, "mux", &sel, &sources, 2);
        n.drive(Gate::Buf, &format!("y[{i}]"), &[value.clone()]);
        result.push(value);
    }

    n.drive(Gate::Buf, "cout", &[carries[WIDTH - 1].clone()]);

    let raw_ovf = xor2n(&mut n, "ovf", &carries[WIDTH - 1], &carries[WIDTH - 2]);
    // --- redundant cone, deliberate and documented -------------------------
    // `kill` is true when neither top-bit operand is set and `generate` when
    // both are; no assignment satisfies both, so `dead` is zero for every
    // input and ORing it into the overflow changes nothing. This is the
    // suite's stand-in for the redundant logic the published family is known
    // for: a cone whose stuck-at-0 fault no test vector can detect.
    let kill = n.two(Gate::Nor, "red", &a[WIDTH - 1], &beff[WIDTH - 1]);
    let generate = and2(&mut n, "red", &a[WIDTH - 1], &beff[WIDTH - 1]);
    let dead = and2(&mut n, "red", &kill, &generate);
    let ovf = or2(&mut n, "ovf", &raw_ovf, &dead);
    // -----------------------------------------------------------------------
    n.drive(Gate::Buf, "ovf", &[ovf]);

    let any = or_tree(&mut n, "zero", &result);
    n.drive(Gate::Not, "zero", &[any]);

    n.limit_fanout(4, &[]);
    design(
        "alu8",
        &provenance("alu8 -- 8-bit arithmetic and logic unit."),
        vec![n.finish()],
    )
}
