//! The five smaller circuits of the scale suite.
//!
//! Every one is designed from the published *function* named in its doc
//! comment and from nothing else; see the module documentation of
//! [`super`](crate::suites::verilog::scale) for the provenance rule that makes
//! that the load-bearing property of this file.

use super::cells::*;
use super::netlist::{Builder, Design, Gate, Module};

/// Codeword positions carrying data, for a Hamming code of `parity` check
/// bits: every position from 1 upward that is not a power of two.
///
/// Index `j` of the result is the codeword position of data bit `j`.
pub fn hamming_data_positions(parity: u32, data: usize) -> Vec<u32> {
    let mut positions = Vec::with_capacity(data);
    let mut position = 1u32;
    while positions.len() < data {
        if !position.is_power_of_two() {
            positions.push(position);
        }
        position += 1;
    }
    assert!(
        position <= (1 << parity),
        "{parity} check bits cannot cover {data} data bits"
    );
    positions
}

pub(super) fn ports(n: &mut Builder, spec: &[(&str, u32, bool)]) {
    for (name, width, is_input) in spec {
        if *is_input {
            n.input(name, *width);
        } else {
            n.output(name, *width);
        }
    }
}

pub(super) fn bits(port: &str, width: u32) -> Vec<String> {
    (0..width).map(|bit| format!("{port}[{bit}]")).collect()
}

pub(super) fn design(top: &str, header: &[&str], modules: Vec<Module>) -> Design {
    Design {
        top: top.to_string(),
        header: header.iter().map(|line| (*line).to_string()).collect(),
        modules,
    }
}

/// The four provenance lines every generated file carries.
pub(super) fn provenance(what: &str) -> Vec<&str> {
    vec![
        what,
        "",
        "Generated by rspice-conformance's Verilog scale-suite generator; edit",
        "the generator, not this file. Designed from the function described",
        "above and from nothing else -- see the generator's module documentation",
        "for the clean-room rule this file was written under.",
    ]
}

