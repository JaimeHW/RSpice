//! Synthesising the testbench both oracles are given.
//!
//! # Why generate it
//!
//! The alternative is a checked-in testbench per case, and it fails for a
//! reason that only shows up once two simulators are involved: whoever writes
//! the testbench chooses the output format, and if that is a person writing
//! Verilog by hand then the format drifts case by case and the comparator has
//! to be tolerant of the drift. Every tolerance in a comparator is a place a
//! real disagreement can hide.
//!
//! Generating it inverts that. There is exactly one output format, RSpice owns
//! it, and both simulators are asked to emit byte-identical text. The
//! comparator can then be exact, which is the only kind of comparator worth
//! having.
//!
//! # What the generated bench does
//!
//! Declares a `reg` per input and a `wire` per output at the widths the
//! stimulus states, instantiates the design by named port connection, and walks
//! the vectors on the timing rule documented in [`super`]: apply at
//! `k * step`, sample at `k * step + settle`. A declared clock is driven by its
//! own `always` block rather than from the vector columns.
//!
//! Output goes through `$write` rather than `$display`, and every value through
//! `%b`. `$display` appends a newline whose presence is one more thing two
//! tools could differ about, and `%b` on a sized operand prints exactly as many
//! characters as the operand is wide, in both tools, with `x` and `z` surviving
//! literally.

use super::corpus::{CaseDirection, CasePort, Stimulus};
use std::fmt::Write;

/// Name of the generated top-level module.
///
/// Prefixed so it cannot collide with a module inside a case, which would
/// otherwise be a confusing elaboration error rather than an obvious one.
pub const TOP_MODULE: &str = "rspice_verilog_tb";

/// File name the generated bench is written to inside a case's scratch
/// directory.
pub const FILE_NAME: &str = "rspice_verilog_tb.v";

/// The first line of a trace, written by the generated bench.
pub const TRACE_HEADER: &str = "# RSPICE-VERILOG-TRACE 1";

/// Render the testbench for one case.
///
/// Deterministic: the same stimulus always yields byte-identical Verilog, so a
/// build can be cached and a diff between two runs means the stimulus changed.
pub fn render(stimulus: &Stimulus, case_name: &str) -> String {
    let driven = stimulus.driven_inputs();
    let observed = stimulus.observed_outputs();

    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by the RSpice Verilog oracle harness from {case_name}.stim."
    );
    let _ = writeln!(
        out,
        "// Do not edit and do not check in: this file is rebuilt"
    );
    let _ = writeln!(out, "// from the stimulus every time the suite runs.");
    let _ = writeln!(out, "`timescale 1ns/1ns");
    let _ = writeln!(out);
    let _ = writeln!(out, "module {TOP_MODULE};");

    for port in &stimulus.ports {
        let keyword = match port.direction {
            CaseDirection::Input => "reg ",
            CaseDirection::Output => "wire",
        };
        let _ = writeln!(out, "  {keyword} {}{};", width_prefix(port), port.name);
    }
    let _ = writeln!(out, "  integer rspice_step;");
    let _ = writeln!(out);

    // Named port connection throughout. Positional connection would make the
    // bench depend on the order ports appear in the design's header, which is
    // exactly the thing the corpus check deliberately does not pin.
    let _ = writeln!(out, "  {} rspice_dut (", stimulus.module);
    let connections = stimulus
        .ports
        .iter()
        .map(|port| format!("    .{}({})", port.name, port.name))
        .collect::<Vec<_>>();
    let _ = writeln!(out, "{}", connections.join(",\n"));
    let _ = writeln!(out, "  );");
    let _ = writeln!(out);

    let _ = writeln!(out, "  task rspice_sample;");
    let _ = writeln!(out, "    begin");
    let _ = writeln!(out, "      $write(\"@%0d\", rspice_step);");
    for port in &observed {
        let _ = writeln!(out, "      $write(\" {}=%b\", {});", port.name, port.name);
    }
    let _ = writeln!(out, "      $write(\"\\n\");");
    let _ = writeln!(out, "    end");
    let _ = writeln!(out, "  endtask");
    let _ = writeln!(out);

    if let Some(clock) = &stimulus.clock {
        let _ = writeln!(out, "  initial {} = 1'b0;", clock.port);
        let _ = writeln!(
            out,
            "  always #{} {} = ~{};",
            clock.half_period, clock.port, clock.port
        );
        let _ = writeln!(out);
    }

    let _ = writeln!(out, "  initial begin");
    let _ = writeln!(out, "    $write(\"{TRACE_HEADER}\\n\");");
    let hold = stimulus.step - stimulus.settle;
    for (index, vector) in stimulus.vectors.iter().enumerate() {
        let _ = writeln!(out, "    rspice_step = {index};");
        for (value, port) in vector.iter().zip(&driven) {
            let _ = writeln!(out, "    {} = {};", port.name, literal(port, value));
        }
        let _ = writeln!(out, "    #{} rspice_sample;", stimulus.settle);
        let _ = writeln!(out, "    #{hold};");
    }
    let _ = writeln!(out, "    $finish;");
    let _ = writeln!(out, "  end");
    let _ = writeln!(out, "endmodule");
    out
}

/// `[3:0] ` for a vector port, empty for a scalar one.
///
/// Scalars are left undimensioned rather than written `[0:0]`: the two are not
/// interchangeable in every tool, and a scalar port is what the corpus's
/// designs actually declare.
fn width_prefix(port: &CasePort) -> String {
    if port.width == 1 {
        String::new()
    } else {
        format!("[{}:0] ", port.width - 1)
    }
}

/// A sized four-state literal: `1'b0`, `4'b10x1`.
fn literal(port: &CasePort, value: &str) -> String {
    format!("{}'b{value}", port.width)
}

#[cfg(test)]
mod tests {
    use super::super::corpus::parse_stimulus;
    use super::*;

    const COMBINATIONAL: &str = "# RSPICE-VERILOG-STIMULUS 1\n\
        module demo\n\
        input a 1\n\
        input b 2\n\
        output y 1\n\
        output w 4\n\
        step 10\n\
        settle 4\n\
        vector 0 01\n\
        vector 1 xz\n";

    const CLOCKED: &str = "# RSPICE-VERILOG-STIMULUS 1\n\
        module reg4\n\
        input clk 1\n\
        input d 4\n\
        output q 4\n\
        clock clk 5\n\
        step 10\n\
        settle 8\n\
        vector 1010\n";

    fn render_text(source: &str, name: &str) -> String {
        render(&parse_stimulus(source).expect("stimulus parses"), name)
    }

    #[test]
    fn declarations_take_their_direction_and_width_from_the_stimulus() {
        let bench = render_text(COMBINATIONAL, "demo");

        assert!(bench.contains("  reg  a;"), "{bench}");
        assert!(bench.contains("  reg  [1:0] b;"), "{bench}");
        assert!(bench.contains("  wire y;"), "{bench}");
        assert!(bench.contains("  wire [3:0] w;"), "{bench}");
        // Scalars stay undimensioned rather than becoming [0:0].
        assert!(!bench.contains("[0:0]"), "{bench}");
    }

    #[test]
    fn the_design_is_instantiated_by_name_not_by_position() {
        let bench = render_text(COMBINATIONAL, "demo");

        assert!(bench.contains("demo rspice_dut ("), "{bench}");
        for port in ["a", "b", "y", "w"] {
            assert!(bench.contains(&format!(".{port}({port})")), "{bench}");
        }
    }

    #[test]
    fn vectors_apply_at_the_step_and_sample_after_the_settle() {
        let bench = render_text(COMBINATIONAL, "demo");

        // settle 4, step 10, so the hold is 6.
        assert!(bench.contains("    #4 rspice_sample;"), "{bench}");
        assert!(bench.contains("    #6;"), "{bench}");
        assert_eq!(bench.matches("rspice_sample;").count(), 3, "{bench}");
    }

    #[test]
    fn four_state_vector_values_become_sized_literals() {
        let bench = render_text(COMBINATIONAL, "demo");

        assert!(bench.contains("    a = 1'b0;"), "{bench}");
        assert!(bench.contains("    b = 2'b01;"), "{bench}");
        assert!(bench.contains("    a = 1'b1;"), "{bench}");
        assert!(bench.contains("    b = 2'bxz;"), "{bench}");
    }

    #[test]
    fn only_outputs_reach_the_trace_and_the_header_precedes_them() {
        let bench = render_text(COMBINATIONAL, "demo");

        assert!(bench.contains("$write(\" y=%b\", y);"), "{bench}");
        assert!(bench.contains("$write(\" w=%b\", w);"), "{bench}");
        // Inputs are driven, never sampled: an input in the trace would let a
        // case pass by agreeing about what the harness itself wrote.
        assert!(!bench.contains("$write(\" a=%b\""), "{bench}");
        assert!(!bench.contains("$write(\" b=%b\""), "{bench}");

        let header = bench.find(TRACE_HEADER).expect("header is written");
        let first_sample = bench.find("rspice_step = 0;").expect("first vector");
        assert!(header < first_sample, "{bench}");
    }

    #[test]
    fn a_declared_clock_is_free_running_and_never_driven_by_a_vector() {
        let bench = render_text(CLOCKED, "reg4");

        assert!(bench.contains("initial clk = 1'b0;"), "{bench}");
        assert!(bench.contains("always #5 clk = ~clk;"), "{bench}");
        // The vector column drives `d` only.
        assert!(bench.contains("    d = 4'b1010;"), "{bench}");
        assert!(!bench.contains("    clk = 4'b"), "{bench}");
        assert!(!bench.contains("    clk = 1'b1;"), "{bench}");
    }

    #[test]
    fn a_case_without_a_clock_generates_no_clock_machinery() {
        let bench = render_text(COMBINATIONAL, "demo");

        assert!(!bench.contains("always #"), "{bench}");
        assert!(!bench.contains("initial clk"), "{bench}");
    }

    #[test]
    fn rendering_is_deterministic() {
        assert_eq!(
            render_text(COMBINATIONAL, "demo"),
            render_text(COMBINATIONAL, "demo")
        );
    }

    #[test]
    fn the_run_terminates_itself() {
        let bench = render_text(COMBINATIONAL, "demo");

        // Without `$finish` the free-running clock in a clocked case would run
        // forever and the only thing stopping it would be the harness timeout,
        // which reports a hang rather than a result.
        assert!(bench.contains("    $finish;"), "{bench}");
        assert!(bench.trim_end().ends_with("endmodule"), "{bench}");
    }
}
