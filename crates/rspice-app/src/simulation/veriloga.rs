/// Verified secondary-module payload transferred only inside the browser
/// worker. Generated bytes never become project/editor state.
///
/// Gated to match the worker protocol module that carries it, so a native
/// build does not compile a message type it has no transport for.
#[cfg(any(target_arch = "wasm32", test))]
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct WasmJitWorkerArtifact {
    pub(crate) abi_version: u32,
    pub(crate) emitter_version: u32,
    pub(crate) cache_key: String,
    pub(crate) digest: String,
    pub(crate) module_bytes: Vec<u8>,
    pub(crate) value_exports: Vec<String>,
    /// The module assignment pass, when it has steps to run. A module whose
    /// pass is empty exports no kernel for it, so the absence has to survive
    /// the wire: the worker then runs no assignment step, which is exactly
    /// what the native executable does.
    pub(crate) assignment_export: Option<String>,
    pub(crate) post_assignment_export: Option<String>,
    /// Whole-model drivers. Present only when the model is eligible to fuse;
    /// the worker keeps the per-entry table either way.
    #[serde(default)]
    pub(crate) evaluation_kernel_export: Option<String>,
    #[serde(default)]
    pub(crate) stamp_kernel_export: Option<String>,
}

/// Available to a host test as well as to the worker build, so the wire shape
/// of an artifact can be pinned without a browser.
#[cfg(all(feature = "browser-worker", any(target_arch = "wasm32", test)))]
impl WasmJitWorkerArtifact {
    pub(crate) fn from_compiled(
        artifact: &rspice_veriloga::wasm_jit::WasmJitModelArtifact,
    ) -> Self {
        Self {
            abi_version: artifact.module().abi_version(),
            emitter_version: artifact.module().emitter_version(),
            cache_key: artifact.cache_key().to_owned(),
            digest: artifact.module().digest().to_owned(),
            module_bytes: artifact.module().bytes().to_vec(),
            value_exports: artifact
                .entries()
                .iter()
                .map(|entry| entry.export_name().to_owned())
                .collect(),
            assignment_export: artifact.assignment_export().map(str::to_owned),
            post_assignment_export: artifact.post_assignment_export().map(str::to_owned),
            evaluation_kernel_export: artifact.evaluation_kernel_export().map(str::to_owned),
            stamp_kernel_export: artifact.stamp_kernel_export().map(str::to_owned),
        }
    }
}

/// Exact project-owned Verilog-A closure captured when compilation starts.
///
/// Unlike automation's single-document token, this identity includes the
/// stable bundle owner and the digest of every file in its sealed dependency
/// closure. A result can therefore never cross-publish between two cell views
/// that happen to contain identical root text.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct VerilogASourceOperationToken {
    pub project_id: crate::product::ProjectId,
    pub bundle_id: crate::state::ProjectSourceId,
    pub revision: u64,
    pub closure_digest: crate::product::ContentDigest,
    /// Exact explicit module selection requested by a cell-view contract.
    /// `None` preserves the Code Workspace's compiler-selected module mode.
    pub requested_module_digest: Option<crate::product::ContentDigest>,
}

/// Bind a compile report only after checking its current project source token.
pub fn prepare_project_runtime(
    project_id: crate::product::ProjectId,
    bundle: &crate::state::ProjectSourceBundle,
    token: &VerilogASourceOperationToken,
    module_name: &str,
    report: &rspice_veriloga::RuntimeCompileReport,
    netlist_alias: impl Into<String>,
) -> Result<PreparedVerilogARuntime, PreparedRuntimeError> {
    if token.project_id != project_id
        || token.bundle_id != bundle.id()
        || token.revision != bundle.revision().get()
        || token.closure_digest != bundle.closure_digest()
        || token
            .requested_module_digest
            .is_some_and(|expected| expected != veriloga_selected_module_digest(module_name))
    {
        return Err(PreparedRuntimeError::SourceIdentity(
            "The retained Verilog-A runtime does not identify the exact current project source"
                .to_owned(),
        ));
    }
    let source_key =
        crate::state::project_veriloga_bundle_source_key(project_id, bundle, module_name)
            .map_err(|error| PreparedRuntimeError::SourceIdentity(error.to_string()))?;
    PreparedVerilogARuntime::try_from_runtime_report(
        source_key,
        bundle.closure_digest(),
        module_name,
        report,
        netlist_alias,
    )
}

pub(crate) fn veriloga_selected_module_digest(module_name: &str) -> crate::product::ContentDigest {
    let mut hasher = Sha256::new();
    let domain = b"rspice.veriloga-selected-module/v1";
    hasher.update((domain.len() as u64).to_be_bytes());
    hasher.update(domain);
    hasher.update((module_name.len() as u64).to_be_bytes());
    hasher.update(module_name.as_bytes());
    crate::product::ContentDigest::from_bytes(hasher.finalize().into())
}

pub(crate) fn compile_model_library_source_runtimes(
    authority: &crate::state::model_library::SealedModelLibraryVerilogAAuthority,
) -> Result<PreparedVerilogARuntimeSet, PreparedRuntimeError> {
    rspice_simulation::veriloga::compile_model_library_source_runtimes(
        authority,
        model_library_virtual_compile_limits(),
    )
}

/// Insert one sealed Verilog-A directive before the terminal `.end` card.
/// The exact same helper is used by the retained generated artifact and the
/// immutable prepared-run source, preventing display/execution drift.
pub fn project_veriloga_directive(source_key: &str, netlist_alias: &str) -> String {
    format!(".veriloga \"{source_key}\" {netlist_alias}")
}

pub fn append_project_veriloga_directive(
    source: &mut String,
    source_key: &str,
    netlist_alias: &str,
) {
    let directive = project_veriloga_directive(source_key, netlist_alias);
    let end = crate::services::simulation_runner::terminal_end_card_offset(source)
        .unwrap_or(source.len());
    if source[..end]
        .lines()
        .skip(1)
        .any(|line| line.trim().eq_ignore_ascii_case(&directive))
    {
        return;
    }
    *source =
        crate::services::simulation_runner::splice_before_terminal_end_card(source, &directive);
}

fn model_library_virtual_compile_limits() -> rspice_veriloga::VirtualCompileLimits {
    rspice_veriloga::VirtualCompileLimits {
        max_files: crate::state::MAX_PROJECT_SOURCE_FILES,
        max_path_bytes: crate::state::MAX_PROJECT_SOURCE_LOGICAL_PATH_BYTES,
        max_file_bytes: crate::state::MAX_PROJECT_CODE_SOURCE_BYTES,
        max_total_source_bytes: crate::state::MAX_PROJECT_SOURCE_BUNDLE_BYTES,
        max_include_depth: crate::state::MAX_PROJECT_SOURCE_DEPENDENCY_DEPTH,
        max_expanded_bytes: crate::state::MAX_PROJECT_SOURCE_BUNDLE_BYTES.saturating_mul(2),
        max_module_name_bytes: 128,
    }
}

