//! Every public path rustdoc documents for `rspice_core` before the split.
//!
//! Transient. The engine is being split into the `rspice-core-*` family, with
//! `rspice-core` re-exporting every module at its old path so that moved files
//! compile unchanged and no downstream import changes. This file proves it:
//! each line names one path rustdoc listed for `rspice-core` before the first
//! move, and a path the split loses fails to compile here. It is deleted when
//! the split completes.
//!
//! The list was measured once from `cargo doc -p rspice-core --no-deps`, not
//! regenerated: `all.html`, which lists every documented item at the path it
//! is documented under, plus each module page's re-exports, with a glob
//! re-export expanded to the names it brings in. Items only; methods, fields
//! and variants are reached through their type. Default features first, then
//! each feature-gated path under the feature that gates its definition: what
//! `--no-default-features` lacks, and what `--features veriloga-native` and
//! `--features veriloga-builtins` add. Under `device::veriloga_builtins::builtins`
//! only the registry's own items are listed. Its per-model modules are the
//! generated surface of `rspice-veriloga-models`, reached through that one
//! re-export, named by content hash and gated model by model.
//!
//! A path removed on purpose is deleted from here in the same change.

