fn rust_string(value: &str) -> String {
    format!("{value:?}")
}

fn rust_string_slice(values: &[serde_json::Value], field: &str) -> String {
    let values = values
        .iter()
        .map(|value| {
            value
                .as_str()
                .unwrap_or_else(|| panic!("Results contract {field} entries must be strings"))
        })
        .map(rust_string)
        .collect::<Vec<_>>()
        .join(", ");
    format!("&[{values}]")
}

fn generate_results_contract(manifest_dir: &std::path::Path, out_dir: &std::path::Path) {
    // The canonical contract is tracked inside the crate. It used to be read
    // out of `mockups/`, which is a separately versioned prototype tree and is
    // gitignored here — every fresh clone therefore failed this build before
    // the file moved in. A shipped crate's build inputs live in the shipped
    // tree.
    let contract_path = manifest_dir
        .join("contracts")
        .join("result-data-contract.json");
    println!("cargo:rerun-if-changed={}", contract_path.display());
    let bytes = fs::read(&contract_path).unwrap_or_else(|error| {
        panic!(
            "canonical Results contract {} must be readable: {error}",
            contract_path.display()
        )
    });
    let contract: serde_json::Value = serde_json::from_slice(&bytes).unwrap_or_else(|error| {
        panic!(
            "canonical Results contract {} must be valid JSON: {error}",
            contract_path.display()
        )
    });
    let document_types = contract
        .get("documentTypes")
        .and_then(serde_json::Value::as_array)
        .expect("Results contract documentTypes must be an array");
    let declared_count = contract
        .pointer("/counts/viewerDocuments")
        .and_then(serde_json::Value::as_u64)
        .expect("Results contract counts.viewerDocuments must be an integer");
    assert_eq!(
        usize::try_from(declared_count).expect("viewer count must fit usize"),
        document_types.len(),
        "Results contract viewer count does not match documentTypes"
    );

    let mut generated = String::from(
        "// @generated by crates/rspice-ui/build.rs from result-data-contract.json.\n\
         // Do not hand-edit.\n\n",
    );
    generated.push_str(&format!(
        "pub const CANONICAL_VIEWER_COUNT: usize = {};\n\n",
        document_types.len()
    ));
    generated.push_str("pub const VIEWER_DOCUMENTS: &[ViewerDocumentDefinition] = &[\n");
    for document in document_types {
        let id = contract_string(document, "id");
        let canonical = document
            .get("canonical")
            .and_then(serde_json::Value::as_object)
            .expect("Results document canonical metadata must be an object");
        let capability = document
            .get("capability")
            .and_then(serde_json::Value::as_object)
            .expect("Results document capability metadata must be an object");
        let input_authority = document
            .get("inputAuthority")
            .and_then(serde_json::Value::as_object)
            .expect("Results document inputAuthority must be an object");
        let analysis_ids = input_authority
            .get("analysisIds")
            .and_then(serde_json::Value::as_array)
            .expect("Results document analysisIds must be an array");
        let external_capability = input_authority
            .get("externalCapabilityId")
            .and_then(serde_json::Value::as_str)
            .map_or_else(
                || "None".to_owned(),
                |value| format!("Some({})", rust_string(value)),
            );
        let group = viewer_group_variant(
            canonical
                .get("group")
                .and_then(serde_json::Value::as_str)
                .expect("Results document group must be a string"),
        );
        let art = viewer_art_variant(
            canonical
                .get("art")
                .and_then(serde_json::Value::as_str)
                .expect("Results document art must be a string"),
        );
        let release = viewer_release_variant(
            capability
                .get("classification")
                .and_then(serde_json::Value::as_str)
                .expect("Results document classification must be a string"),
        );
        generated.push_str(&format!(
            "    ViewerDocumentDefinition {{\n\
             \x20       id: {},\n\
             \x20       group: ViewerGroup::{group},\n\
             \x20       title: {},\n\
             \x20       domain: {},\n\
             \x20       x_axis: {},\n\
             \x20       y_axis: {},\n\
             \x20       art: ViewerArt::{art},\n\
             \x20       analysis_ids: {},\n\
             \x20       external_capability: {external_capability},\n\
             \x20       release: ViewerReleaseClass::{release},\n\
             \x20   }},\n",
            rust_string(&id),
            rust_string(
                canonical
                    .get("title")
                    .and_then(serde_json::Value::as_str)
                    .expect("Results document title must be a string")
            ),
            rust_string(
                canonical
                    .get("domain")
                    .and_then(serde_json::Value::as_str)
                    .expect("Results document domain must be a string")
            ),
            rust_string(
                canonical
                    .get("x")
                    .and_then(serde_json::Value::as_str)
                    .expect("Results document x axis must be a string")
            ),
            rust_string(
                canonical
                    .get("y")
                    .and_then(serde_json::Value::as_str)
                    .expect("Results document y axis must be a string")
            ),
            rust_string_slice(analysis_ids, "analysisIds"),
        ));
    }
    generated.push_str("];\n\n");

    let creation_families = contract
        .get("creationFamilies")
        .and_then(serde_json::Value::as_object)
        .expect("Results contract creationFamilies must be an object");
    let declared_family_count = contract
        .pointer("/counts/creationFamilies")
        .and_then(serde_json::Value::as_u64)
        .expect("Results contract counts.creationFamilies must be an integer");
    assert_eq!(
        usize::try_from(declared_family_count).expect("family count must fit usize"),
        creation_families.len(),
        "Results contract family count does not match creationFamilies"
    );
    generated.push_str(&format!(
        "pub const CANONICAL_CREATION_FAMILY_COUNT: usize = {};\n\n",
        creation_families.len()
    ));
    generated
        .push_str("pub const RESULT_CREATION_FAMILIES: &[ResultCreationFamilyDefinition] = &[\n");
    for (id, family) in creation_families {
        let viewer_ids = family
            .get("viewerIds")
            .and_then(serde_json::Value::as_array)
            .expect("Results creation-family viewerIds must be an array");
        let quick_mode_ids = family
            .get("quickModeIds")
            .and_then(serde_json::Value::as_array)
            .expect("Results creation-family quickModeIds must be an array");
        let default_viewer_id = family
            .get("defaultViewerId")
            .and_then(serde_json::Value::as_str)
            .map_or_else(
                || "None".to_owned(),
                |value| format!("Some({})", rust_string(value)),
            );
        generated.push_str(&format!(
            "    ResultCreationFamilyDefinition {{ id: {}, label: {}, description: {}, default_viewer_id: {default_viewer_id}, viewer_ids: {}, quick_mode_ids: {} }},\n",
            rust_string(id),
            rust_string(&contract_string(family, "label")),
            rust_string(&contract_string(family, "description")),
            rust_string_slice(viewer_ids, "viewerIds"),
            rust_string_slice(quick_mode_ids, "quickModeIds"),
        ));
    }
    generated.push_str("];\n");
    fs::write(out_dir.join("results_contract.rs"), generated)
        .expect("generated Results contract should be writable");
}

/// The desktop entry point runs the whole application — eframe's event loop,
/// the app constructor, every frame — on the process main thread. Linux and
/// macOS give that thread 8 MiB; the MSVC linker gives it 1 MiB. `AppState`
/// is a few hundred kilobytes of inline state, and startup holds several
/// copies of it on the stack at once (the `Box::new` temporary of the app,
/// `RSpiceApp::new`'s local, the RON deserializer's partial struct, and the
/// defaults it falls back to), so the optimized frame chain needs about
/// 1.2 MiB and the release executable died at startup with
/// `STATUS_STACK_OVERFLOW`; the debug executable, whose frames are far
/// larger, never started unpatched. The reserve is address space, not memory
/// (pages commit on touch), so it is set well clear of both profiles rather
/// than to the day's measured need. Only the bin targets get it: tests run on
/// threads Rust already sizes itself.
fn reserve_main_thread_stack() {
    if env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        const MAIN_THREAD_STACK_RESERVE_BYTES: u64 = 64 << 20;
        println!("cargo:rustc-link-arg-bins=/STACK:{MAIN_THREAD_STACK_RESERVE_BYTES}");
    }
}

fn main() {
    println!(
        "cargo:rustc-env=RSPICE_BUILD_TARGET={}",
        env::var("TARGET").expect("Cargo must provide TARGET")
    );
    println!(
        "cargo:rustc-env=RSPICE_BUILD_ARCH={}",
        env::var("CARGO_CFG_TARGET_ARCH").expect("Cargo must provide CARGO_CFG_TARGET_ARCH")
    );
    println!("cargo:rerun-if-env-changed=RSPICE_AUTOMATION_RUNTIME_KEY_ID");
    println!("cargo:rerun-if-env-changed=RSPICE_AUTOMATION_RUNTIME_PUBLIC_KEY_HEX");
    let runtime_key_id = env::var("RSPICE_AUTOMATION_RUNTIME_KEY_ID").unwrap_or_default();
    let runtime_public_key =
        env::var("RSPICE_AUTOMATION_RUNTIME_PUBLIC_KEY_HEX").unwrap_or_default();
    if runtime_key_id.is_empty() != runtime_public_key.is_empty() {
        panic!(
            "RSPICE_AUTOMATION_RUNTIME_KEY_ID and RSPICE_AUTOMATION_RUNTIME_PUBLIC_KEY_HEX must be supplied together"
        );
    }
    if !runtime_public_key.is_empty()
        && (runtime_public_key.len() != 64
            || !runtime_public_key
                .bytes()
                .all(|byte| byte.is_ascii_hexdigit()))
    {
        panic!(
            "RSPICE_AUTOMATION_RUNTIME_PUBLIC_KEY_HEX must contain exactly 64 hexadecimal digits"
        );
    }
    println!("cargo:rustc-env=RSPICE_AUTOMATION_RUNTIME_KEY_ID={runtime_key_id}");
    println!("cargo:rustc-env=RSPICE_AUTOMATION_RUNTIME_PUBLIC_KEY_HEX={runtime_public_key}");

    // Development license material is an explicit build-profile capability,
    // not a side effect of `debug_assertions` (which can be enabled for a
    // release profile). Standard debug builds retain the signed sample-key
    // workflow; every release and custom profile fails closed unless backed by
    // a production ceremony key compiled into the application.
    println!("cargo:rustc-check-cfg=cfg(rspice_development_build)");
    if env::var("PROFILE").as_deref() == Ok("debug") {
        println!("cargo:rustc-cfg=rspice_development_build");
    }

    let manifest_dir =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR must be set"));

    // Short commit hash for About / Copy diagnostics; "unknown" outside a
    // git checkout (release tarballs).
    let build_hash = std::process::Command::new("git")
        .args(["rev-parse", "--short=9", "HEAD"])
        .current_dir(&manifest_dir)
        .output()
        .ok()
        .filter(|out| out.status.success())
        .and_then(|out| String::from_utf8(out.stdout).ok())
        .map(|hash| hash.trim().to_owned())
        .filter(|hash| !hash.is_empty())
        .unwrap_or_else(|| "unknown".to_owned());
    println!("cargo:rustc-env=RSPICE_BUILD_HASH={build_hash}");
    let git_head = manifest_dir.join("..").join("..").join(".git").join("HEAD");
    if git_head.exists() {
        println!("cargo:rerun-if-changed={}", git_head.display());
    }

    let assets_dir = manifest_dir.join("assets").join("component_symbols");

    println!("cargo:rerun-if-changed={}", assets_dir.display());

    let mut asset_paths: Vec<_> = fs::read_dir(&assets_dir)
        .expect("component symbol asset directory must exist")
        .filter_map(|entry| {
            let path = entry.ok()?.path();
            (path.extension().and_then(|ext| ext.to_str()) == Some("svg")).then_some(path)
        })
        .collect();
    asset_paths.sort();

    let mut generated = String::from("pub static EMBEDDED_SYMBOLS: &[(&str, &str)] = &[\n");
    for path in asset_paths {
        let filename = path
            .file_name()
            .and_then(|name| name.to_str())
            .expect("asset filename must be valid UTF-8");
        generated.push_str(&format!(
            "    ({:?}, include_str!(r#\"{}\"#)),\n",
            filename,
            path.display()
        ));
    }
    generated.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR must be set"));
    generate_results_contract(&manifest_dir, &out_dir);
    let generated_path = out_dir.join("embedded_symbols.rs");
    fs::write(generated_path, generated).expect("embedded symbol table should be writable");

    reserve_main_thread_stack();

    // Embed the brand icon as the Windows .exe resource (what Explorer shows).
    // The `#[cfg(windows)]` gate is on the *host* (where winresource is a
    // build-dep); the TARGET_OS check ensures we only emit MSVC resource link
    // args when actually building a Windows binary — never when this same
    // Windows host cross-compiles to wasm. Non-fatal: a missing resource
    // compiler degrades to a warning so SDK-less environments still build.
    #[cfg(windows)]
    {
        let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
        if target_os == "windows" {
            let icon = manifest_dir
                .join("..")
                .join("..")
                .join("assets")
                .join("brand")
                .join("rspice.ico");
            println!("cargo:rerun-if-changed={}", icon.display());
            match icon.to_str() {
                Some(path) => {
                    let mut res = winresource::WindowsResource::new();
                    res.set_icon(path);
                    if let Err(e) = res.compile() {
                        println!("cargo:warning=rspice-ui: could not embed Windows .exe icon: {e}");
                    }
                }
                None => {
                    println!("cargo:warning=rspice-ui: icon path is not valid UTF-8, skipping")
                }
            }
        }
    }
}
