use std::env;
use std::fs;
use std::path::PathBuf;

fn contract_string(value: &serde_json::Value, field: &str) -> String {
    value
        .get(field)
        .and_then(serde_json::Value::as_str)
        .unwrap_or_else(|| panic!("Results contract field {field:?} must be a string"))
        .to_owned()
}

