    fn sample_dataset() -> WaveformDataset {
        let mut dataset = WaveformDataset::new("Transient");

        let mut time = WaveformSignal::new("time", SignalType::Time);
        time.data = vec![0.0, 1e-6];
        dataset.set_x(time);

        let mut voltage = WaveformSignal::new("V(out)", SignalType::Voltage);
        voltage.data = vec![0.0, 1.25];
        dataset.add_signal(voltage);

        let mut current = WaveformSignal::new("I(R1)", SignalType::Current);
        current.data = vec![0.001, 0.002];
        dataset.add_signal(current);

        dataset
    }

    fn sample_touchstone_dataset() -> WaveformDataset {
        let mut dataset = WaveformDataset::new("S-Parameters");
        dataset.analysis = "S-Parameter".to_string();
        dataset
            .metadata
            .insert("touchstone_version".to_string(), "2".to_string());
        dataset.metadata.insert("z0".to_string(), "50".to_string());
        dataset
            .metadata
            .insert("z0_ports".to_string(), "50,75".to_string());

        let mut frequency = WaveformSignal::new("frequency", SignalType::Frequency);
        frequency.data = vec![1.0e6, 2.0e6];
        dataset.set_x(frequency);

        for (name, values) in [
            ("S11_RE", vec![0.1, 0.2]),
            ("S11_IM", vec![0.0, 0.0]),
            ("S21_RE", vec![0.3, 0.4]),
            ("S21_IM", vec![0.01, 0.02]),
            ("S12_RE", vec![0.5, 0.6]),
            ("S12_IM", vec![0.03, 0.04]),
            ("S22_RE", vec![0.7, 0.8]),
            ("S22_IM", vec![0.05, 0.06]),
        ] {
            let mut signal = WaveformSignal::new(name, SignalType::SParameter);
            signal.data = values;
            dataset.add_signal(signal);
        }

        dataset
    }

    /// An N-port export whose every entry names its own position: `S<row><col>`
    /// carries `0.<row><col>` as its real part and zero imaginary part, so the
    /// written element order is readable straight off the file.
    fn positional_touchstone_dataset(num_ports: usize, version: u32) -> WaveformDataset {
        let mut dataset = WaveformDataset::new("S-Parameters");
        dataset.analysis = "S-Parameter".to_string();
        dataset
            .metadata
            .insert("touchstone_version".to_string(), version.to_string());
        dataset.metadata.insert("z0".to_string(), "50".to_string());

        let mut frequency = WaveformSignal::new("frequency", SignalType::Frequency);
        frequency.data = vec![1.0e6];
        dataset.set_x(frequency);

        for row in 1..=num_ports {
            for column in 1..=num_ports {
                let value = (row * 10 + column) as f64 / 100.0;
                let mut real =
                    WaveformSignal::new(format!("S{row}_{column}_RE"), SignalType::SParameter);
                real.data = vec![value];
                dataset.add_signal(real);
                let mut imag =
                    WaveformSignal::new(format!("S{row}_{column}_IM"), SignalType::SParameter);
                imag.data = vec![0.0];
                dataset.add_signal(imag);
            }
        }

        dataset
    }

    /// Touchstone writes every network of three ports and above row-wise, one
    /// matrix row per line group (Touchstone 2.0 specification, "3-port and
    /// 4-port Networks"). Column-major output transposes the network for every
    /// tool that reads it.
    #[test]
    fn touchstone_text_export_writes_three_port_rows_row_wise() {
        let text = WaveformWriter::new(WaveformFormat::Touchstone)
            .write_text(&positional_touchstone_dataset(3, 1))
            .expect("touchstone text serializes");

        assert_eq!(
            text,
            concat!(
                "! Generated by rspice-ui\n",
                "# Hz S RI R 50\n",
                "1e6 1.1e-1 0e0 1.2e-1 0e0 1.3e-1 0e0\n",
                "2.1e-1 0e0 2.2e-1 0e0 2.3e-1 0e0\n",
                "3.1e-1 0e0 3.2e-1 0e0 3.3e-1 0e0\n",
            )
        );
    }

    /// Touchstone v1 allows at most four parameter pairs on a data line, and a
    /// matrix row that overruns that continues on the following line while the
    /// next row still starts one of its own (Touchstone 2.0 specification,
    /// "5-port and Above Networks").
    #[test]
    fn touchstone_text_export_wraps_wide_rows_at_four_pairs() {
        let text = WaveformWriter::new(WaveformFormat::Touchstone)
            .write_text(&positional_touchstone_dataset(5, 1))
            .expect("touchstone text serializes");

        let data_lines = text
            .lines()
            .filter(|line| !line.starts_with('!') && !line.starts_with('#'))
            .collect::<Vec<_>>();
        let pairs_per_line = data_lines
            .iter()
            .enumerate()
            .map(|(index, line)| {
                let tokens = line.split_whitespace().count();
                // The frequency leads the first line of the record.
                if index == 0 {
                    (tokens - 1) / 2
                } else {
                    tokens / 2
                }
            })
            .collect::<Vec<_>>();

        // Five rows of five pairs, each split four then one.
        assert_eq!(pairs_per_line, vec![4, 1, 4, 1, 4, 1, 4, 1, 4, 1], "{text}");

        let reopened =
            crate::io::waveform_io::read_touchstone_bytes("wrapped.s5p", text.as_bytes())
                .expect("the wrapped export reopens");
        for row in 1..=5 {
            for column in 1..=5 {
                assert_eq!(
                    reopened
                        .get_signal(&format!("S{row}{column}_RE"))
                        .unwrap_or_else(|| panic!("S{row}{column}_RE is missing"))
                        .data[0],
                    (row * 10 + column) as f64 / 100.0,
                    "S{row}{column}"
                );
            }
        }
    }

    /// What is written comes back unchanged, element for element.
    #[test]
    fn touchstone_text_export_round_trips_a_three_port_matrix() {
        let text = WaveformWriter::new(WaveformFormat::Touchstone)
            .write_text(&positional_touchstone_dataset(3, 2))
            .expect("touchstone text serializes");
        let reopened =
            crate::io::waveform_io::read_touchstone_bytes("roundtrip.ts", text.as_bytes())
                .expect("the export reopens");

        for row in 1..=3 {
            for column in 1..=3 {
                assert_eq!(
                    reopened
                        .get_signal(&format!("S{row}{column}_RE"))
                        .unwrap_or_else(|| panic!("S{row}{column}_RE is missing"))
                        .data[0],
                    (row * 10 + column) as f64 / 100.0,
                    "S{row}{column}"
                );
            }
        }
    }

    #[test]
    fn csv_text_uses_same_delimited_shape_as_file_export() {
        let csv = WaveformWriter::new(WaveformFormat::Csv)
            .write_text(&sample_dataset())
            .expect("csv text serializes");

        assert_eq!(csv, "time,V(out),I(R1)\n0,0,0.001\n0.000001,1.25,0.002\n");
    }

    #[test]
    fn non_writable_formats_report_the_export_contract() {
        for format in [
            WaveformFormat::Psf,
            WaveformFormat::Nutmeg,
            WaveformFormat::AsciiRaw,
            WaveformFormat::BinaryRaw,
        ] {
            assert!(!format.can_write());
            let error = WaveformWriter::new(format)
                .write_text(&sample_dataset())
                .expect_err("non-writable formats must reject export");
            assert!(error.contains("read-only or unsupported for export"));
            assert!(error.contains("Csv, Tsv, and Touchstone"));
            assert!(!error.contains("not implemented"));
        }
    }

    #[test]
    fn delimited_text_quotes_headers_that_contain_delimiters_or_quotes() {
        let mut dataset = WaveformDataset::new("quoted");

        let mut x = WaveformSignal::new("time,sec", SignalType::Time);
        x.data = vec![0.0];
        dataset.set_x(x);

        let mut signal = WaveformSignal::new("V(out,\"ref\")", SignalType::Voltage);
        signal.data = vec![1.25];
        dataset.add_signal(signal);

        let csv = WaveformWriter::new(WaveformFormat::Csv)
            .write_text(&dataset)
            .expect("csv text serializes");
        assert_eq!(csv, "\"time,sec\",\"V(out,\"\"ref\"\")\"\n0,1.25\n");

        let mut tsv_dataset = WaveformDataset::new("quoted-tsv");
        let mut tx = WaveformSignal::new("time\tsec", SignalType::Time);
        tx.data = vec![0.0];
        tsv_dataset.set_x(tx);
        let mut tsig = WaveformSignal::new("I(\"R1\")", SignalType::Current);
        tsig.data = vec![0.002];
        tsv_dataset.add_signal(tsig);

        let tsv = WaveformWriter::new(WaveformFormat::Tsv)
            .write_text(&tsv_dataset)
            .expect("tsv text serializes");
        assert_eq!(tsv, "\"time\tsec\"\t\"I(\"\"R1\"\")\"\n0\t0.002\n");
    }

