//! Waveform writers.

use super::*;

// =============================================================================
// Waveform Writer
// =============================================================================

/// Waveform file writer
pub struct WaveformWriter {
    format: WaveformFormat,
}

impl WaveformWriter {
    /// Create writer for format
    pub fn new(format: WaveformFormat) -> Self {
        Self { format }
    }

    /// Serialize dataset to a text-based waveform format.
    pub fn write_text(&self, dataset: &WaveformDataset) -> Result<String, String> {
        match self.format {
            WaveformFormat::Csv => Ok(Self::delimited_text(dataset, ',')),
            WaveformFormat::Tsv => Ok(Self::delimited_text(dataset, '\t')),
            WaveformFormat::Touchstone => Self::touchstone_text(dataset),
            _ => Err(format!(
                "Format {:?} is read-only or unsupported for export; writable waveform formats are Csv, Tsv, and Touchstone",
                self.format
            )),
        }
    }

    /// Port count encoded by a Touchstone-compatible result dataset.
    /// Callers should use this only after `write_text` has validated the full
    /// matrix; it is provided so save workflows can choose the required
    /// `.sNp` extension without re-materializing the matrix.
    pub(crate) fn touchstone_port_count(dataset: &WaveformDataset) -> Option<usize> {
        dataset
            .signals
            .iter()
            .filter_map(|signal| Self::parse_touchstone_signal_name(&signal.name))
            .map(|(row, column, _)| row.max(column))
            .max()
    }

    fn touchstone_text(dataset: &WaveformDataset) -> Result<String, String> {
        let (frequencies, matrix) = Self::extract_touchstone_matrix(dataset)?;
        let num_ports = matrix.len();
        let z0_by_port = Self::touchstone_reference_values_for_write(dataset, num_ports)?;
        let z0 = z0_by_port[0];
        let uniform_reference = z0_by_port.iter().all(|value| (*value - z0).abs() <= 1e-18);
        let version = dataset
            .metadata
            .get("touchstone_version")
            .and_then(|v| v.parse::<u32>().ok())
            .unwrap_or(1);
        if version < 2 && !uniform_reference {
            return Err(
                "Touchstone v1 does not support per-port reference impedance; use version 2"
                    .to_string(),
            );
        }

        let mut contents = String::new();
        contents.push_str("! Generated by rspice-ui\n");
        if version >= 2 {
            contents.push_str("[Version] 2.0\n");
            contents.push_str(&format!("[Number of Ports] {}\n", num_ports));
            contents.push_str(&format!("[Number of Frequencies] {}\n", frequencies.len()));
            contents.push_str(&format!("# Hz S RI R {}\n", z0));
            if !uniform_reference {
                contents.push_str(&format!(
                    "[Reference] {}",
                    z0_by_port
                        .iter()
                        .map(|value| format!("{value:e}"))
                        .collect::<Vec<_>>()
                        .join(" ")
                ));
                contents.push('\n');
            }
            contents.push_str("[Network Data]\n");
        } else {
            contents.push_str(&format!("# Hz S RI R {}\n", z0));
        }

        for idx in 0..frequencies.len() {
            Self::push_touchstone_record(&mut contents, frequencies[idx], &matrix, idx);
        }

        if version >= 2 {
            contents.push_str("[End]\n");
        }

        Ok(contents)
    }

    /// Touchstone v1 permits at most four complex pairs on one data line.
    const TOUCHSTONE_PAIRS_PER_LINE: usize = 4;

    /// Write one frequency's network data in the element order the format
    /// fixes.
    ///
    /// A full two-port matrix is the format's one documented exception, and
    /// carries S11 S21 S12 S22 on a single line. Every other port count is
    /// written row-wise — every element of matrix row *r* before any element
    /// of row *r+1* — with each row starting a new line and continuing on the
    /// next once four pairs are on the current one (Touchstone 2.0
    /// specification, "3-port and 4-port Networks" and "5-port and Above
    /// Networks"). The frequency leads the first line of the record only.
    fn push_touchstone_record(
        contents: &mut String,
        frequency: f64,
        matrix: &[Vec<Vec<(f64, f64)>>],
        idx: usize,
    ) {
        let num_ports = matrix.len();
        contents.push_str(&format!("{frequency:e}"));
        if num_ports == 2 {
            for (row, column) in [(0, 0), (1, 0), (0, 1), (1, 1)] {
                let (re, im) = matrix[row][column][idx];
                contents.push_str(&format!(" {re:e} {im:e}"));
            }
            contents.push('\n');
            return;
        }

        // The frequency already occupies the first line of the record.
        let mut line_has_content = true;
        let mut pairs_on_line = 0usize;
        for (row_index, row) in matrix.iter().enumerate() {
            if row_index > 0 {
                contents.push('\n');
                line_has_content = false;
                pairs_on_line = 0;
            }
            for series in row {
                if pairs_on_line == Self::TOUCHSTONE_PAIRS_PER_LINE {
                    contents.push('\n');
                    line_has_content = false;
                    pairs_on_line = 0;
                }
                let (re, im) = series[idx];
                if line_has_content {
                    contents.push(' ');
                }
                contents.push_str(&format!("{re:e} {im:e}"));
                line_has_content = true;
                pairs_on_line += 1;
            }
        }
        contents.push('\n');
    }

    fn touchstone_reference_values_for_write(
        dataset: &WaveformDataset,
        num_ports: usize,
    ) -> Result<Vec<f64>, String> {
        let default_z0 = dataset
            .metadata
            .get("z0")
            .and_then(|v| v.parse::<f64>().ok())
            .filter(|v| v.is_finite() && *v > 0.0)
            .unwrap_or(50.0);

        let values = match dataset.metadata.get("z0_ports") {
            Some(raw) => {
                let parsed: Vec<f64> = raw
                    .split(|ch: char| ch == ',' || ch.is_whitespace())
                    .filter(|token| !token.trim().is_empty())
                    .map(|token| {
                        token.trim().parse::<f64>().map_err(|_| {
                            format!("Invalid Touchstone z0_ports entry '{}'", token.trim())
                        })
                    })
                    .collect::<Result<Vec<_>, _>>()?;
                if parsed.is_empty() {
                    vec![default_z0; num_ports]
                } else if parsed.len() == 1 {
                    vec![parsed[0]; num_ports]
                } else if parsed.len() == num_ports {
                    parsed
                } else {
                    return Err(format!(
                        "Touchstone z0_ports count {} does not match {} ports",
                        parsed.len(),
                        num_ports
                    ));
                }
            }
            None => vec![default_z0; num_ports],
        };

        for (idx, value) in values.iter().enumerate() {
            if !value.is_finite() || *value <= 0.0 {
                return Err(format!(
                    "Touchstone reference impedance for port {} must be positive",
                    idx + 1
                ));
            }
        }

        Ok(values)
    }

    fn extract_touchstone_matrix(
        dataset: &WaveformDataset,
    ) -> Result<(Vec<f64>, Vec<Vec<Vec<(f64, f64)>>>), String> {
        let x = dataset
            .x_signal
            .as_ref()
            .ok_or_else(|| "Touchstone export requires an X-axis frequency signal".to_string())?;
        if x.data.is_empty() {
            return Err("Touchstone export requires at least one frequency point".to_string());
        }
        let expected_len = x.data.len();
        for (idx, frequency) in x.data.iter().enumerate() {
            if !frequency.is_finite() || *frequency <= 0.0 {
                return Err(format!(
                    "Touchstone frequency point {} must be finite and positive (found {})",
                    idx, frequency
                ));
            }
        }

        let mut real_signals: HashMap<(usize, usize), &WaveformSignal> = HashMap::new();
        let mut imag_signals: HashMap<(usize, usize), &WaveformSignal> = HashMap::new();
        let mut max_port = 0usize;

        for signal in &dataset.signals {
            let Some((row, col, is_imag)) = Self::parse_touchstone_signal_name(&signal.name) else {
                continue;
            };
            max_port = max_port.max(row).max(col);
            let key = (row, col);
            if is_imag {
                if imag_signals.insert(key, signal).is_some() {
                    return Err(format!(
                        "Duplicate Touchstone imag component for S{}{}",
                        row, col
                    ));
                }
            } else if real_signals.insert(key, signal).is_some() {
                return Err(format!(
                    "Duplicate Touchstone real component for S{}{}",
                    row, col
                ));
            }
        }

        if max_port < 2 {
            return Err(
                "Touchstone export requires at least a 2-port S-parameter matrix".to_string(),
            );
        }

        let mut matrix = vec![vec![vec![(0.0, 0.0); expected_len]; max_port]; max_port];
        for row in 1..=max_port {
            for col in 1..=max_port {
                let key = (row, col);
                let real = real_signals.get(&key).ok_or_else(|| {
                    format!("Missing Touchstone real component for S{}{}", row, col)
                })?;
                let imag = imag_signals.get(&key).ok_or_else(|| {
                    format!("Missing Touchstone imag component for S{}{}", row, col)
                })?;
                if real.data.len() != expected_len || imag.data.len() != expected_len {
                    return Err(format!(
                        "Touchstone signal length mismatch for S{}{} (freq={}, real={}, imag={})",
                        row,
                        col,
                        expected_len,
                        real.data.len(),
                        imag.data.len()
                    ));
                }
                let mut samples = Vec::with_capacity(expected_len);
                for (idx, (re, im)) in real.data.iter().zip(imag.data.iter()).enumerate() {
                    if !re.is_finite() || !im.is_finite() {
                        return Err(format!(
                            "Touchstone S{}{} sample {} must be finite (real={}, imag={})",
                            row, col, idx, re, im
                        ));
                    }
                    samples.push((*re, *im));
                }
                matrix[row - 1][col - 1] = samples;
            }
        }

        Ok((x.data.clone(), matrix))
    }

    fn parse_touchstone_signal_name(name: &str) -> Option<(usize, usize, bool)> {
        let normalized = name.trim().to_ascii_uppercase().replace(' ', "");
        if let Some(base) = normalized
            .strip_prefix("RE(")
            .and_then(|value| value.strip_suffix(')'))
            && let Some((row, col)) = Self::parse_touchstone_base_name(base)
        {
            return Some((row, col, false));
        }
        if let Some(base) = normalized
            .strip_prefix("IM(")
            .and_then(|value| value.strip_suffix(')'))
            && let Some((row, col)) = Self::parse_touchstone_base_name(base)
        {
            return Some((row, col, true));
        }
        // Prefer longest suffix matches first.
        let suffixes = [
            ("_IMAG", true),
            ("IMAG", true),
            ("_REAL", false),
            ("REAL", false),
            ("_IM", true),
            ("IM", true),
            ("_RE", false),
            ("RE", false),
            ("_I", true),
            ("I", true),
            ("_R", false),
            ("R", false),
        ];
        for (suffix, is_imag) in suffixes {
            if let Some(base) = normalized.strip_suffix(suffix)
                && let Some((row, col)) = Self::parse_touchstone_base_name(base)
            {
                return Some((row, col, is_imag));
            }
        }
        None
    }

    fn parse_touchstone_base_name(name: &str) -> Option<(usize, usize)> {
        let rest = name.strip_prefix('S')?;
        if let Some(inner) = rest.strip_prefix('(').and_then(|v| v.strip_suffix(')')) {
            let (row, col) = inner.split_once(',')?;
            let row = row.trim().parse::<usize>().ok()?;
            let col = col.trim().parse::<usize>().ok()?;
            return (row > 0 && col > 0).then_some((row, col));
        }
        if let Some((row, col)) = rest.split_once('_') {
            let row = row.trim().parse::<usize>().ok()?;
            let col = col.trim().parse::<usize>().ok()?;
            return (row > 0 && col > 0).then_some((row, col));
        }
        if rest.len() == 2 && rest.chars().all(|ch| ch.is_ascii_digit()) {
            let row = rest[0..1].parse::<usize>().ok()?;
            let col = rest[1..2].parse::<usize>().ok()?;
            return Some((row, col));
        }
        None
    }

    fn delimited_text(dataset: &WaveformDataset, delimiter: char) -> String {
        let separator = delimiter.to_string();
        let mut contents = String::new();
        let mut headers = Vec::new();
        if let Some(ref x) = dataset.x_signal {
            headers.push(x.name.as_str());
        }
        for sig in &dataset.signals {
            headers.push(sig.name.as_str());
        }
        let escaped_headers = headers
            .iter()
            .map(|header| Self::escape_delimited_header(header, delimiter))
            .collect::<Vec<_>>();
        contents.push_str(&escaped_headers.join(&separator));
        contents.push('\n');

        let num_points = dataset.point_count();
        for i in 0..num_points {
            let mut values = Vec::new();

            if let Some(ref x) = dataset.x_signal {
                values.push(x.get(i).map(|v| v.to_string()).unwrap_or_default());
            }
            for sig in &dataset.signals {
                values.push(sig.get(i).map(|v| v.to_string()).unwrap_or_default());
            }

            contents.push_str(&values.join(&separator));
            contents.push('\n');
        }

        contents
    }

    fn escape_delimited_header(header: &str, delimiter: char) -> String {
        if header.contains(delimiter)
            || header.contains('"')
            || header.contains('\n')
            || header.contains('\r')
        {
            format!("\"{}\"", header.replace('"', "\"\""))
        } else {
            header.to_string()
        }
    }
}

