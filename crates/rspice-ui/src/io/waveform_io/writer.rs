use super::*;

// =============================================================================
// Waveform Writer
// =============================================================================

/// Waveform file writer
pub struct WaveformWriter {
    format: WaveformFormat,
}

impl WaveformWriter {
    /// Create writer for format
    pub fn new(format: WaveformFormat) -> Self {
        Self { format }
    }

    /// Write dataset to file
    pub fn write(&self, dataset: &WaveformDataset, path: &Path) -> Result<(), String> {
        let contents = self.write_text(dataset)?;

        #[cfg(not(target_arch = "wasm32"))]
        {
            // Direct writer callers have no earlier picker authorization, but
            // still receive a complete-byte, crash-consistent CAS instead of
            // a partial or unconditional filesystem write.
            let expected = crate::io::durable_file::observe_expected_content(path)
                .map_err(|error| error.to_string())?;
            crate::io::durable_file::compare_exchange_bytes(path, expected, contents.as_bytes())
                .map_err(|error| error.to_string())
        }

        #[cfg(target_arch = "wasm32")]
        {
            let _ = (contents, path);
            Err("direct filesystem waveform writes are unavailable in the browser; use the download export workflow".to_string())
        }
    }

    /// Serialize dataset to a text-based waveform format.
    pub fn write_text(&self, dataset: &WaveformDataset) -> Result<String, String> {
        match self.format {
            WaveformFormat::Csv => Ok(Self::delimited_text(dataset, ',')),
            WaveformFormat::Tsv => Ok(Self::delimited_text(dataset, '\t')),
            WaveformFormat::Touchstone => Self::touchstone_text(dataset),
            _ => Err(format!(
                "Format {:?} is read-only or unsupported for export; writable waveform formats are Csv, Tsv, and Touchstone",
                self.format
            )),
        }
    }

    /// Port count encoded by a Touchstone-compatible result dataset.
    /// Callers should use this only after `write_text` has validated the full
    /// matrix; it is provided so save workflows can choose the required
    /// `.sNp` extension without re-materializing the matrix.
    pub(crate) fn touchstone_port_count(dataset: &WaveformDataset) -> Option<usize> {
        dataset
            .signals
            .iter()
            .filter_map(|signal| Self::parse_touchstone_signal_name(&signal.name))
            .map(|(row, column, _)| row.max(column))
            .max()
    }

    fn touchstone_text(dataset: &WaveformDataset) -> Result<String, String> {
        let (frequencies, matrix) = Self::extract_touchstone_matrix(dataset)?;
        let num_ports = matrix.len();
        let z0_by_port = Self::touchstone_reference_values_for_write(dataset, num_ports)?;
        let z0 = z0_by_port[0];
        let uniform_reference = z0_by_port.iter().all(|value| (*value - z0).abs() <= 1e-18);
        let version = dataset
            .metadata
            .get("touchstone_version")
            .and_then(|v| v.parse::<u32>().ok())
            .unwrap_or(1);
        if version < 2 && !uniform_reference {
            return Err(
                "Touchstone v1 does not support per-port reference impedance; use version 2"
                    .to_string(),
            );
        }

        let mut contents = String::new();
        contents.push_str("! Generated by rspice-ui\n");
        if version >= 2 {
            contents.push_str("[Version] 2.0\n");
            contents.push_str(&format!("[Number of Ports] {}\n", num_ports));
            contents.push_str(&format!("[Number of Frequencies] {}\n", frequencies.len()));
            contents.push_str(&format!("# Hz S RI R {}\n", z0));
            if !uniform_reference {
                contents.push_str(&format!(
                    "[Reference] {}",
                    z0_by_port
                        .iter()
                        .map(|value| format!("{:.12e}", value))
                        .collect::<Vec<_>>()
                        .join(" ")
                ));
                contents.push('\n');
            }
            contents.push_str("[Network Data]\n");
        } else {
            contents.push_str(&format!("# Hz S RI R {}\n", z0));
        }

        for idx in 0..frequencies.len() {
            contents.push_str(&format!("{:.12e}", frequencies[idx]));
            // Touchstone matrix order: S11 S21 ... SN1 S12 S22 ... SN2 ... SNN.
            for col in 0..num_ports {
                for row in 0..num_ports {
                    let (re, im) = matrix[row][col][idx];
                    contents.push_str(&format!(" {:.12e} {:.12e}", re, im));
                }
            }
            contents.push('\n');
        }

        if version >= 2 {
            contents.push_str("[End]\n");
        }

        Ok(contents)
    }

    fn touchstone_reference_values_for_write(
        dataset: &WaveformDataset,
        num_ports: usize,
    ) -> Result<Vec<f64>, String> {
        let default_z0 = dataset
            .metadata
            .get("z0")
            .and_then(|v| v.parse::<f64>().ok())
            .filter(|v| v.is_finite() && *v > 0.0)
            .unwrap_or(50.0);

        let values = match dataset.metadata.get("z0_ports") {
            Some(raw) => {
                let parsed: Vec<f64> = raw
                    .split(|ch: char| ch == ',' || ch.is_whitespace())
                    .filter(|token| !token.trim().is_empty())
                    .map(|token| {
                        token.trim().parse::<f64>().map_err(|_| {
                            format!("Invalid Touchstone z0_ports entry '{}'", token.trim())
                        })
                    })
                    .collect::<Result<Vec<_>, _>>()?;
                if parsed.is_empty() {
                    vec![default_z0; num_ports]
                } else if parsed.len() == 1 {
                    vec![parsed[0]; num_ports]
                } else if parsed.len() == num_ports {
                    parsed
                } else {
                    return Err(format!(
                        "Touchstone z0_ports count {} does not match {} ports",
                        parsed.len(),
                        num_ports
                    ));
                }
            }
            None => vec![default_z0; num_ports],
        };

        for (idx, value) in values.iter().enumerate() {
            if !value.is_finite() || *value <= 0.0 {
                return Err(format!(
                    "Touchstone reference impedance for port {} must be positive",
                    idx + 1
                ));
            }
        }

        Ok(values)
    }

    fn extract_touchstone_matrix(
        dataset: &WaveformDataset,
    ) -> Result<(Vec<f64>, Vec<Vec<Vec<(f64, f64)>>>), String> {
        let x = dataset
            .x_signal
            .as_ref()
            .ok_or_else(|| "Touchstone export requires an X-axis frequency signal".to_string())?;
        if x.data.is_empty() {
            return Err("Touchstone export requires at least one frequency point".to_string());
        }
        let expected_len = x.data.len();
        for (idx, frequency) in x.data.iter().enumerate() {
            if !frequency.is_finite() || *frequency <= 0.0 {
                return Err(format!(
                    "Touchstone frequency point {} must be finite and positive (found {})",
                    idx, frequency
                ));
            }
        }

        let mut real_signals: HashMap<(usize, usize), &WaveformSignal> = HashMap::new();
        let mut imag_signals: HashMap<(usize, usize), &WaveformSignal> = HashMap::new();
        let mut max_port = 0usize;

        for signal in &dataset.signals {
            let Some((row, col, is_imag)) = Self::parse_touchstone_signal_name(&signal.name) else {
                continue;
            };
            max_port = max_port.max(row).max(col);
            let key = (row, col);
            if is_imag {
                if imag_signals.insert(key, signal).is_some() {
                    return Err(format!(
                        "Duplicate Touchstone imag component for S{}{}",
                        row, col
                    ));
                }
            } else if real_signals.insert(key, signal).is_some() {
                return Err(format!(
                    "Duplicate Touchstone real component for S{}{}",
                    row, col
                ));
            }
        }

        if max_port < 2 {
            return Err(
                "Touchstone export requires at least a 2-port S-parameter matrix".to_string(),
            );
        }

        let mut matrix = vec![vec![vec![(0.0, 0.0); expected_len]; max_port]; max_port];
        for row in 1..=max_port {
            for col in 1..=max_port {
                let key = (row, col);
                let real = real_signals.get(&key).ok_or_else(|| {
                    format!("Missing Touchstone real component for S{}{}", row, col)
                })?;
                let imag = imag_signals.get(&key).ok_or_else(|| {
                    format!("Missing Touchstone imag component for S{}{}", row, col)
                })?;
                if real.data.len() != expected_len || imag.data.len() != expected_len {
                    return Err(format!(
                        "Touchstone signal length mismatch for S{}{} (freq={}, real={}, imag={})",
                        row,
                        col,
                        expected_len,
                        real.data.len(),
                        imag.data.len()
                    ));
                }
                let mut samples = Vec::with_capacity(expected_len);
                for (idx, (re, im)) in real.data.iter().zip(imag.data.iter()).enumerate() {
                    if !re.is_finite() || !im.is_finite() {
                        return Err(format!(
                            "Touchstone S{}{} sample {} must be finite (real={}, imag={})",
                            row, col, idx, re, im
                        ));
                    }
                    samples.push((*re, *im));
                }
                matrix[row - 1][col - 1] = samples;
            }
        }

        Ok((x.data.clone(), matrix))
    }

    fn parse_touchstone_signal_name(name: &str) -> Option<(usize, usize, bool)> {
        let normalized = name.trim().to_ascii_uppercase().replace(' ', "");
        if let Some(base) = normalized
            .strip_prefix("RE(")
            .and_then(|value| value.strip_suffix(')'))
            && let Some((row, col)) = Self::parse_touchstone_base_name(base)
        {
            return Some((row, col, false));
        }
        if let Some(base) = normalized
            .strip_prefix("IM(")
            .and_then(|value| value.strip_suffix(')'))
            && let Some((row, col)) = Self::parse_touchstone_base_name(base)
        {
            return Some((row, col, true));
        }
        // Prefer longest suffix matches first.
        let suffixes = [
            ("_IMAG", true),
            ("IMAG", true),
            ("_REAL", false),
            ("REAL", false),
            ("_IM", true),
            ("IM", true),
            ("_RE", false),
            ("RE", false),
            ("_I", true),
            ("I", true),
            ("_R", false),
            ("R", false),
        ];
        for (suffix, is_imag) in suffixes {
            if let Some(base) = normalized.strip_suffix(suffix)
                && let Some((row, col)) = Self::parse_touchstone_base_name(base)
            {
                return Some((row, col, is_imag));
            }
        }
        None
    }

    fn parse_touchstone_base_name(name: &str) -> Option<(usize, usize)> {
        let rest = name.strip_prefix('S')?;
        if let Some(inner) = rest.strip_prefix('(').and_then(|v| v.strip_suffix(')')) {
            let (row, col) = inner.split_once(',')?;
            let row = row.trim().parse::<usize>().ok()?;
            let col = col.trim().parse::<usize>().ok()?;
            return (row > 0 && col > 0).then_some((row, col));
        }
        if let Some((row, col)) = rest.split_once('_') {
            let row = row.trim().parse::<usize>().ok()?;
            let col = col.trim().parse::<usize>().ok()?;
            return (row > 0 && col > 0).then_some((row, col));
        }
        if rest.len() == 2 && rest.chars().all(|ch| ch.is_ascii_digit()) {
            let row = rest[0..1].parse::<usize>().ok()?;
            let col = rest[1..2].parse::<usize>().ok()?;
            return Some((row, col));
        }
        None
    }

    fn delimited_text(dataset: &WaveformDataset, delimiter: char) -> String {
        let separator = delimiter.to_string();
        let mut contents = String::new();
        let mut headers = Vec::new();
        if let Some(ref x) = dataset.x_signal {
            headers.push(x.name.as_str());
        }
        for sig in &dataset.signals {
            headers.push(sig.name.as_str());
        }
        let escaped_headers = headers
            .iter()
            .map(|header| Self::escape_delimited_header(header, delimiter))
            .collect::<Vec<_>>();
        contents.push_str(&escaped_headers.join(&separator));
        contents.push('\n');

        let num_points = dataset.point_count();
        for i in 0..num_points {
            let mut values = Vec::new();

            if let Some(ref x) = dataset.x_signal {
                values.push(x.get(i).map(|v| v.to_string()).unwrap_or_default());
            }
            for sig in &dataset.signals {
                values.push(sig.get(i).map(|v| v.to_string()).unwrap_or_default());
            }

            contents.push_str(&values.join(&separator));
            contents.push('\n');
        }

        contents
    }

    fn escape_delimited_header(header: &str, delimiter: char) -> String {
        if header.contains(delimiter)
            || header.contains('"')
            || header.contains('\n')
            || header.contains('\r')
        {
            format!("\"{}\"", header.replace('"', "\"\""))
        } else {
            header.to_string()
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_dataset() -> WaveformDataset {
        let mut dataset = WaveformDataset::new("Transient");

        let mut time = WaveformSignal::new("time", SignalType::Time);
        time.data = vec![0.0, 1e-6];
        dataset.set_x(time);

        let mut voltage = WaveformSignal::new("V(out)", SignalType::Voltage);
        voltage.data = vec![0.0, 1.25];
        dataset.add_signal(voltage);

        let mut current = WaveformSignal::new("I(R1)", SignalType::Current);
        current.data = vec![0.001, 0.002];
        dataset.add_signal(current);

        dataset
    }

    fn sample_touchstone_dataset() -> WaveformDataset {
        let mut dataset = WaveformDataset::new("S-Parameters");
        dataset.analysis = "S-Parameter".to_string();
        dataset
            .metadata
            .insert("touchstone_version".to_string(), "2".to_string());
        dataset.metadata.insert("z0".to_string(), "50".to_string());
        dataset
            .metadata
            .insert("z0_ports".to_string(), "50,75".to_string());

        let mut frequency = WaveformSignal::new("frequency", SignalType::Frequency);
        frequency.data = vec![1.0e6, 2.0e6];
        dataset.set_x(frequency);

        for (name, values) in [
            ("S11_RE", vec![0.1, 0.2]),
            ("S11_IM", vec![0.0, 0.0]),
            ("S21_RE", vec![0.3, 0.4]),
            ("S21_IM", vec![0.01, 0.02]),
            ("S12_RE", vec![0.5, 0.6]),
            ("S12_IM", vec![0.03, 0.04]),
            ("S22_RE", vec![0.7, 0.8]),
            ("S22_IM", vec![0.05, 0.06]),
        ] {
            let mut signal = WaveformSignal::new(name, SignalType::SParameter);
            signal.data = values;
            dataset.add_signal(signal);
        }

        dataset
    }

    #[test]
    fn csv_text_uses_same_delimited_shape_as_file_export() {
        let csv = WaveformWriter::new(WaveformFormat::Csv)
            .write_text(&sample_dataset())
            .expect("csv text serializes");

        assert_eq!(csv, "time,V(out),I(R1)\n0,0,0.001\n0.000001,1.25,0.002\n");
    }

    #[test]
    fn non_writable_formats_report_the_export_contract() {
        for format in [
            WaveformFormat::Psf,
            WaveformFormat::Nutmeg,
            WaveformFormat::AsciiRaw,
            WaveformFormat::BinaryRaw,
        ] {
            assert!(!format.can_write());
            let error = WaveformWriter::new(format)
                .write_text(&sample_dataset())
                .expect_err("non-writable formats must reject export");
            assert!(error.contains("read-only or unsupported for export"));
            assert!(error.contains("Csv, Tsv, and Touchstone"));
            assert!(!error.contains("not implemented"));
        }
    }

    #[test]
    fn delimited_text_quotes_headers_that_contain_delimiters_or_quotes() {
        let mut dataset = WaveformDataset::new("quoted");

        let mut x = WaveformSignal::new("time,sec", SignalType::Time);
        x.data = vec![0.0];
        dataset.set_x(x);

        let mut signal = WaveformSignal::new("V(out,\"ref\")", SignalType::Voltage);
        signal.data = vec![1.25];
        dataset.add_signal(signal);

        let csv = WaveformWriter::new(WaveformFormat::Csv)
            .write_text(&dataset)
            .expect("csv text serializes");
        assert_eq!(csv, "\"time,sec\",\"V(out,\"\"ref\"\")\"\n0,1.25\n");

        let mut tsv_dataset = WaveformDataset::new("quoted-tsv");
        let mut tx = WaveformSignal::new("time\tsec", SignalType::Time);
        tx.data = vec![0.0];
        tsv_dataset.set_x(tx);
        let mut tsig = WaveformSignal::new("I(\"R1\")", SignalType::Current);
        tsig.data = vec![0.002];
        tsv_dataset.add_signal(tsig);

        let tsv = WaveformWriter::new(WaveformFormat::Tsv)
            .write_text(&tsv_dataset)
            .expect("tsv text serializes");
        assert_eq!(tsv, "\"time\tsec\"\t\"I(\"\"R1\"\")\"\n0\t0.002\n");
    }

    #[test]
    fn touchstone_text_export_uses_ri_matrix_order() {
        let text = WaveformWriter::new(WaveformFormat::Touchstone)
            .write_text(&sample_touchstone_dataset())
            .expect("touchstone text serializes");

        assert_eq!(
            text,
            concat!(
                "! Generated by rspice-ui\n",
                "[Version] 2.0\n",
                "[Number of Ports] 2\n",
                "[Number of Frequencies] 2\n",
                "# Hz S RI R 50\n",
                "[Reference] 5.000000000000e1 7.500000000000e1\n",
                "[Network Data]\n",
                "1.000000000000e6 1.000000000000e-1 0.000000000000e0 3.000000000000e-1 1.000000000000e-2 5.000000000000e-1 3.000000000000e-2 7.000000000000e-1 5.000000000000e-2\n",
                "2.000000000000e6 2.000000000000e-1 0.000000000000e0 4.000000000000e-1 2.000000000000e-2 6.000000000000e-1 4.000000000000e-2 8.000000000000e-1 6.000000000000e-2\n",
                "[End]\n",
            )
        );
    }

    #[test]
    fn touchstone_text_export_rejects_invalid_frequency_values() {
        let mut dataset = sample_touchstone_dataset();
        dataset.x_signal.as_mut().expect("frequency axis").data[0] = 0.0;

        let err = WaveformWriter::new(WaveformFormat::Touchstone)
            .write_text(&dataset)
            .expect_err("Touchstone export must reject non-positive frequencies");

        assert!(
            err.contains("frequency") && err.contains("positive"),
            "unexpected error: {err}"
        );
    }

    #[test]
    fn touchstone_text_export_rejects_nonfinite_sparameter_values() {
        let mut dataset = sample_touchstone_dataset();
        dataset.signals[0].data[1] = f64::NAN;

        let err = WaveformWriter::new(WaveformFormat::Touchstone)
            .write_text(&dataset)
            .expect_err("Touchstone export must reject non-finite S-parameters");

        assert!(
            err.contains("S11") && err.contains("finite"),
            "unexpected error: {err}"
        );
    }
}
