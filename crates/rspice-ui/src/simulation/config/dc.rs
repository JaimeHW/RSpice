//! DC sweep configuration: the swept source, its range, any nested second
//! sweep, and whether the sweep retraces.

// DC Sweep Configuration
//=============================================================================

/// DC sweep analysis configuration
#[derive(Debug, Clone)]
pub struct DcSweepConfig {
    /// Source to sweep (e.g., "Vin")
    pub source: String,
    /// Start value
    pub start: f64,
    /// Stop value
    pub stop: f64,
    /// Step size
    pub step: f64,
    /// Secondary sweep source (optional)
    pub source2: Option<String>,
    /// Secondary start value
    pub start2: Option<f64>,
    /// Secondary stop value
    pub stop2: Option<f64>,
    /// Secondary step size
    pub step2: Option<f64>,
    /// Sweep to `stop` and then back to `start`, as one continued solve.
    ///
    /// This is what makes a hysteresis measurement a measurement rather than
    /// two runs: a circuit with a latch, a switch or a saturable core settles
    /// on a different branch depending on where it came from, so the reverse
    /// branch is only meaningful if it starts from the state the forward branch
    /// finished in.
    pub hysteresis: bool,
}

impl Default for DcSweepConfig {
    fn default() -> Self {
        Self {
            source: "Vin".to_string(),
            start: 0.0,
            stop: 5.0,
            step: 0.1,
            source2: None,
            start2: None,
            stop2: None,
            step2: None,
            hysteresis: false,
        }
    }
}

impl DcSweepConfig {
    /// The values the forward branch visits.
    ///
    /// Generated by the engine's own sweep spec rather than by arithmetic
    /// here, so the deck this writes names exactly the points the solver will
    /// step through — including how it treats a range the step does not divide
    /// evenly. `config/ac.rs` derives its frequency axis the same way.
    #[must_use]
    pub fn forward_points(&self) -> Vec<f64> {
        rspice_core::netlist::DcSweepSpec::linear(self.start, self.stop, self.step).points()
    }

    /// Every value a retracing sweep visits, forward then back.
    ///
    /// The turnaround is visited once, not twice: `stop` is the last forward
    /// point and the reverse branch continues from it rather than re-solving
    /// it. Re-solving would add a duplicate x with an identical y to both
    /// branches and tell the reader nothing.
    #[must_use]
    pub fn retrace_points(&self) -> Vec<f64> {
        let forward = self.forward_points();
        let mut values = forward.clone();
        values.extend(forward.iter().rev().skip(1).copied());
        values
    }

    /// Where the reverse branch begins in [`Self::retrace_points`].
    ///
    /// The turnaround point belongs to both branches — it is where one ends and
    /// the other starts — so the reverse branch is drawn from it, and the two
    /// traces meet instead of leaving a gap the width of one step.
    #[must_use]
    pub fn retrace_turnaround(&self) -> usize {
        self.forward_points().len().saturating_sub(1)
    }

    /// Generate SPICE .dc command
    ///
    /// A retracing sweep is written as an explicit `LIST` of every value in the
    /// order the solver visits them, which is the only spelling that says the
    /// sweep goes out and comes back. It is long, and that is the honest cost:
    /// a deck exported with `.dc SRC 0 5 0.1` would run a different analysis
    /// than the one configured here.
    pub fn to_spice(&self) -> String {
        let mut cmd = if self.hysteresis {
            let mut cmd = format!(".dc {} LIST", self.source);
            for value in self.retrace_points() {
                cmd.push_str(&format!(" {value}"));
            }
            cmd
        } else {
            format!(
                ".dc {} {} {} {}",
                self.source, self.start, self.stop, self.step
            )
        };
        if let (Some(src2), Some(start2), Some(stop2), Some(step2)) =
            (&self.source2, self.start2, self.stop2, self.step2)
        {
            cmd.push_str(&format!(" {} {} {} {}", src2, start2, stop2, step2));
        }
        cmd
    }

    /// Validate configuration
    pub fn validate(&self) -> Result<(), Vec<String>> {
        let mut errors = Vec::new();

        if self.source.is_empty() {
            errors.push("Source name is required".to_string());
        }
        if self.step == 0.0 {
            errors.push("Step size cannot be zero".to_string());
        }
        if (self.stop - self.start).signum() != self.step.signum() {
            errors.push("Step direction must match sweep direction".to_string());
        }

        match (&self.source2, self.start2, self.stop2, self.step2) {
            (None, None, None, None) => {}
            (Some(source2), Some(start2), Some(stop2), Some(step2)) => {
                if source2.trim().is_empty() {
                    errors.push("Secondary source name is required".to_string());
                }
                if source2.eq_ignore_ascii_case(&self.source) {
                    errors.push("Secondary source must differ from primary source".to_string());
                }
                if step2 == 0.0 {
                    errors.push("Secondary step size cannot be zero".to_string());
                }
                if (stop2 - start2).signum() != step2.signum() {
                    errors.push("Secondary step direction must match sweep direction".to_string());
                }
            }
            _ => errors
                .push("Secondary sweep requires source2/start2/stop2/step2 values".to_string()),
        }

        // A nested sweep is a family of curves, and "retrace" does not say
        // which axis retraces or whether the outer source rewinds between
        // branches. Rather than pick one silently, refuse the pair: the
        // measurement an engineer means by this is a single swept source.
        if self.hysteresis && self.source2.is_some() {
            errors.push(
                "Bidirectional sweep applies to a single swept source; disable the nested sweep \
                 or the retrace"
                    .to_string(),
            );
        }
        if self.hysteresis && self.forward_points().len() < 2 {
            errors.push(
                "Bidirectional sweep needs at least two points to have a direction".to_string(),
            );
        }
        if self.hysteresis && !sweeps_an_independent_source(&self.source) {
            errors.push(format!(
                "Bidirectional sweep carries the forward branch's final state into the reverse \
                 branch, and only an independent voltage or current source does that; sweeping \
                 '{}' re-solves a fresh operating point at every value, so the two branches \
                 cannot disagree. Sweep a V or I instance, or turn the retrace off.",
                self.source.trim()
            ));
        }

        if errors.is_empty() {
            Ok(())
        } else {
            Err(errors)
        }
    }
}

/// Whether the engine will resolve this sweep source to an independent source.
///
/// The distinction matters only to a retrace, and it is not cosmetic. The engine
/// dispatches a `.dc` source by precedence
/// (`rspice-core/src/engine/dc.rs:915-960`): `TEMP`/`TEMPER` first, then a
/// netlist `.param`, then an R/C/L device parameter, and only then the voltage
/// and current source tables. The first three clone the netlist and call
/// `run_dc_op` per point (`dc.rs:915-940` and `dc.rs:1187-1217`), so each point
/// starts cold and a reverse branch is bit-identical to the forward one. Only
/// the source path mutates one built circuit in place and seeds each solve with
/// the previous solution (`dc.rs:1027-1050`), which is the whole content of the
/// word "hysteresis".
///
/// Judged from the name alone, because this configuration has no netlist:
/// `TEMP`/`TEMPER` and the `device:parameter` spellings are refused outright,
/// and an independent source must carry the `V` or `I` prefix its netlist line
/// requires. What that cannot catch is a `.param` *named* like a source, which
/// takes precedence over the source table; the deck-level refusal for that lives
/// with the run, and this one keeps the form's own note honest for everything a
/// reader can author here.
fn sweeps_an_independent_source(source: &str) -> bool {
    let name = source.trim();
    !name.is_empty()
        && !name.eq_ignore_ascii_case("TEMP")
        && !name.eq_ignore_ascii_case("TEMPER")
        && !name.contains([':', '@', '[', ']'])
        && name.starts_with(['V', 'v', 'I', 'i'])
}

#[cfg(test)]
mod tests {
    use super::*;

    fn retracing() -> DcSweepConfig {
        DcSweepConfig {
            source: "VIN".to_owned(),
            start: 0.0,
            stop: 1.0,
            step: 0.5,
            hysteresis: true,
            ..DcSweepConfig::default()
        }
    }

    /// The reverse branch retraces the forward one and shares its turnaround,
    /// so the pair is a closed path rather than two disjoint runs.
    #[test]
    fn a_retracing_sweep_goes_out_and_comes_back_through_one_turnaround() {
        let config = retracing();
        assert_eq!(config.forward_points(), [0.0, 0.5, 1.0]);
        assert_eq!(config.retrace_points(), [0.0, 0.5, 1.0, 0.5, 0.0]);
        // The turnaround indexes the last forward point, which is also the
        // first reverse one.
        assert_eq!(config.retrace_turnaround(), 2);
        assert_eq!(config.retrace_points()[config.retrace_turnaround()], 1.0);
    }

    /// The deck has to name every point in visiting order, because that order
    /// is the analysis. `.dc VIN 0 1 0.5` would run something else.
    #[test]
    fn a_retracing_sweep_is_written_as_the_values_it_visits() {
        assert_eq!(retracing().to_spice(), ".dc VIN LIST 0 0.5 1 0.5 0");
    }

    /// The studio writes this line into the executable deck, so the engine has
    /// to read it back as the same analysis. A directive the parser refuses
    /// fails preparation for the whole plan, which is the defect
    /// `directive_parse_ratchet` exists to catch for default drafts; retracing
    /// is not a default, so it is pinned here.
    #[test]
    fn the_retracing_directive_is_one_the_engine_reads_back() {
        let config = retracing();
        let deck = format!(
            "retrace\nVIN in 0 0\nR1 in 0 1k\n{}\n.end\n",
            config.to_spice()
        );
        let netlist = rspice_core::netlist::parse_netlist(&deck)
            .unwrap_or_else(|error| panic!("the retrace directive must parse: {error}\n{deck}"));

        let [rspice_core::netlist::AnalysisCommand::Dc { source, mode, .. }] =
            netlist.analyses.as_slice()
        else {
            panic!(
                "a retracing plan writes one .DC card: {:?}",
                netlist.analyses
            );
        };
        assert_eq!(source, "VIN");
        // Read back as the exact visiting order, out and back, not as a range
        // the parser re-derived or re-sorted.
        let rspice_core::netlist::DcSweepMode::List(values) = mode else {
            panic!("a retrace is an explicit value list, got {mode:?}");
        };
        assert_eq!(values, &config.retrace_points());
    }

    #[test]
    fn a_one_way_sweep_is_still_written_as_a_range() {
        let mut config = retracing();
        config.hysteresis = false;
        assert_eq!(config.to_spice(), ".dc VIN 0 1 0.5");
    }

    /// Nothing here invents a direction for the outer source of a nested
    /// sweep, so the combination is refused rather than resolved silently.
    #[test]
    fn retracing_a_nested_sweep_is_refused_rather_than_guessed() {
        let mut config = retracing();
        config.source2 = Some("VBIAS".to_owned());
        config.start2 = Some(0.0);
        config.stop2 = Some(1.0);
        config.step2 = Some(1.0);

        let errors = config.validate().expect_err("the pair is refused");
        assert!(
            errors
                .iter()
                .any(|error| error.contains("single swept source")),
            "{errors:?}"
        );
    }

    #[test]
    fn a_one_way_sweep_accepts_a_nested_sweep_as_before() {
        let mut config = retracing();
        config.hysteresis = false;
        config.source2 = Some("VBIAS".to_owned());
        config.start2 = Some(0.0);
        config.stop2 = Some(1.0);
        config.step2 = Some(1.0);
        config.validate().expect("a nested one-way sweep is valid");
    }

    /// A temperature, `.param` or device-parameter sweep re-solves a cold
    /// operating point per point, so its two branches are bit-identical and the
    /// form's promise of a continued solve would be false.
    #[test]
    fn a_retrace_is_refused_for_a_source_that_carries_no_state() {
        for source in ["TEMP", "temper", "R1:R", "@M1[w]"] {
            let mut config = retracing();
            config.source = source.to_owned();
            let errors = config
                .validate()
                .expect_err("only an independent source retraces");
            assert!(
                errors.iter().any(
                    |error| error.contains("independent voltage or current source")
                        && error.contains(source.trim())
                ),
                "{source}: {errors:?}"
            );
        }
    }

    /// A current source retraces exactly as a voltage source does, and the
    /// one-way form of every refused sweep is still accepted.
    #[test]
    fn a_retrace_accepts_the_sources_that_do_carry_state() {
        for source in ["VIN", "vin", "I1"] {
            let mut config = retracing();
            config.source = source.to_owned();
            config
                .validate()
                .unwrap_or_else(|errors| panic!("{source} retraces: {errors:?}"));
        }
        let mut one_way = retracing();
        one_way.source = "TEMP".to_owned();
        one_way.hysteresis = false;
        one_way
            .validate()
            .expect("a one-way temperature sweep is unaffected");
    }
}
