//! Deterministic generation of the synthetic benchmark decks.
//!
//! The parametric RC-ladder and MOS-array decks are generated; the remaining
//! decks in `benchmarks/circuits/` are hand-written and checked in directly.
//! The generator is byte-deterministic (fixed formatting, `\n` newlines, no
//! timestamps) so `rspice-bench gen` always reproduces the checked-in files
//! exactly, and reviewers can diff regenerated output against the repo.

use crate::error::BenchError;
use clap::Args;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

/// Arguments for the `gen` subcommand.
#[derive(Args, Debug)]
pub struct GenArgs {
    /// Directory the generated decks are written into.
    #[arg(long, default_value = "benchmarks/circuits", value_name = "DIR")]
    pub dir: PathBuf,
}

/// Parameters of one generated RC-ladder deck.
///
/// The ladder is a chain of identical series-R / shunt-C sections driven by a
/// PULSE source; the far-end node is the observed output. All values are kept
/// as literal SPICE strings so the emitted deck is byte-stable.
struct LadderSpec {
    /// Output file name inside the target directory.
    file_name: &'static str,
    /// Number of RC sections (and therefore internal nodes).
    sections: usize,
    /// Series resistance per section (SPICE literal).
    resistance: &'static str,
    /// Shunt capacitance per section (SPICE literal).
    capacitance: &'static str,
    /// PULSE source specification (SPICE literal, without the keyword).
    pulse: &'static str,
    /// `.tran` output step (SPICE literal).
    tstep: &'static str,
    /// `.tran` stop time (SPICE literal).
    tstop: &'static str,
}

/// The generated deck set. Both ladders use the same per-section R/C values;
/// the analysis windows are scaled so each run covers five full input cycles
/// with ~10k output timepoints.
const LADDERS: &[LadderSpec] = &[
    LadderSpec {
        file_name: "rc_ladder_100.cir",
        sections: 100,
        resistance: "100",
        capacitance: "1p",
        pulse: "0 1 0 1n 1n 99n 200n",
        tstep: "100p",
        tstop: "1u",
    },
    LadderSpec {
        file_name: "rc_ladder_1000.cir",
        sections: 1000,
        resistance: "100",
        capacitance: "1p",
        pulse: "0 1 0 1n 1n 1.999u 4u",
        tstep: "2n",
        tstop: "20u",
    },
    // Scale tier (M3.4): a 10k-node matrix with a deliberately short
    // window (~1k timepoints) so factorization/solve dominates and a
    // benchmark run stays in seconds, not minutes.
    LadderSpec {
        file_name: "rc_ladder_10000.cir",
        sections: 10_000,
        resistance: "100",
        capacitance: "1p",
        pulse: "0 1 0 1n 1n 0.999m 2m",
        tstep: "2u",
        tstop: "2m",
    },
];

/// Parameters of one generated MOS-array deck.
///
/// The array is `stages` independent common-source NMOS stages sharing one
/// VDD rail and one SIN gate drive that sweeps every device through cutoff,
/// saturation, and triode each cycle. The matrix stays arrow-sparse (each
/// drain couples only to itself and the rail), so wall-clock is dominated by
/// per-iteration device evaluation — the workload the parallel device-eval
/// engine work (M3.2) must move.
struct MosArraySpec {
    /// Output file name inside the target directory.
    file_name: &'static str,
    /// Number of common-source stages (one NMOS + load R + load C each).
    stages: usize,
    /// Drain load resistance to VDD (SPICE literal).
    load_resistance: &'static str,
    /// Drain load capacitance to ground (SPICE literal).
    load_capacitance: &'static str,
    /// SIN gate drive specification (SPICE literal, without the keyword).
    sin: &'static str,
    /// `.tran` output step (SPICE literal).
    tstep: &'static str,
    /// `.tran` stop time (SPICE literal).
    tstop: &'static str,
}

/// Device-evaluation tier (M3.2): enough level-1 MOSFETs that Newton spends
/// its time in model code rather than in factorization, over two drive
/// cycles (~1k output timepoints).
const MOS_ARRAYS: &[MosArraySpec] = &[MosArraySpec {
    file_name: "mos_array_4096.cir",
    stages: 4096,
    load_resistance: "3.3k",
    load_capacitance: "100f",
    sin: "1.5 0.8 1MEG",
    tstep: "2n",
    tstop: "2u",
}];

/// Renders one MOS-array deck as SPICE netlist text. Same shared-dialect
/// constraint as the ladders (SIN source, level-1 `.model`, R, C, `.tran`).
fn mos_array_deck(spec: &MosArraySpec) -> String {
    let mut deck = String::new();
    let _ = writeln!(
        deck,
        "* {} -- {}-stage common-source NMOS array, device-eval transient benchmark",
        spec.file_name.trim_end_matches(".cir"),
        spec.stages
    );
    deck.push_str(
        "* GENERATED by `rspice-bench gen`; do not edit by hand -- regenerate instead.\n",
    );
    deck.push_str("VDD vdd 0 DC 3.3\n");
    let _ = writeln!(deck, "VIN g 0 DC 1.5 SIN({})", spec.sin);
    for stage in 1..=spec.stages {
        let _ = writeln!(deck, "M{stage} d{stage} g 0 0 NCH W=10u L=1u");
        let _ = writeln!(deck, "RD{stage} vdd d{stage} {}", spec.load_resistance);
        let _ = writeln!(deck, "CL{stage} d{stage} 0 {}", spec.load_capacitance);
    }
    deck.push_str(".model NCH NMOS(LEVEL=1 VTO=0.7 KP=110u LAMBDA=0.04 GAMMA=0.45 PHI=0.7)\n");
    deck.push_str(".options noacct\n");
    let _ = writeln!(deck, ".tran {} {}", spec.tstep, spec.tstop);
    deck.push_str(".print tran v(d1)\n");
    deck.push_str(".end\n");
    deck
}

/// Renders one RC-ladder deck as SPICE netlist text.
///
/// The deck is self-contained and uses only the dialect subset shared by
/// RSpice and ngspice (PULSE source, R, C, `.tran`, `.options`, `.print`,
/// `.end`), so the identical file runs on both simulators.
fn ladder_deck(spec: &LadderSpec) -> String {
    let mut deck = String::new();
    let _ = writeln!(
        deck,
        "* {} -- {}-section RC ladder, PULSE-driven transient benchmark",
        spec.file_name.trim_end_matches(".cir"),
        spec.sections
    );
    deck.push_str(
        "* GENERATED by `rspice-bench gen`; do not edit by hand -- regenerate instead.\n",
    );
    let _ = writeln!(deck, "VIN in 0 DC 0 PULSE({})", spec.pulse);
    let mut prev = String::from("in");
    for section in 1..=spec.sections {
        let node = format!("n{section}");
        let _ = writeln!(deck, "R{section} {prev} {node} {}", spec.resistance);
        let _ = writeln!(deck, "C{section} {node} 0 {}", spec.capacitance);
        prev = node;
    }
    deck.push_str(".options noacct\n");
    let _ = writeln!(deck, ".tran {} {}", spec.tstep, spec.tstop);
    let _ = writeln!(deck, ".print tran v({prev})");
    deck.push_str(".end\n");
    deck
}

/// Entry point of the `gen` subcommand: writes every generated deck into
/// `args.dir`, creating the directory if needed.
pub fn generate(args: &GenArgs) -> Result<(), BenchError> {
    fs::create_dir_all(&args.dir).map_err(|err| {
        BenchError::io(
            format!("failed to create deck directory `{}`", args.dir.display()),
            err,
        )
    })?;
    for spec in LADDERS {
        let path = args.dir.join(spec.file_name);
        let deck = ladder_deck(spec);
        fs::write(&path, deck).map_err(|err| {
            BenchError::io(
                format!("failed to write generated deck `{}`", path.display()),
                err,
            )
        })?;
        println!("wrote {}", path.display());
    }
    for spec in MOS_ARRAYS {
        let path = args.dir.join(spec.file_name);
        let deck = mos_array_deck(spec);
        fs::write(&path, deck).map_err(|err| {
            BenchError::io(
                format!("failed to write generated deck `{}`", path.display()),
                err,
            )
        })?;
        println!("wrote {}", path.display());
    }
    Ok(())
}
