type StatementKey = (u32, u32, u32, u32);
type LoopKey = (u32, u32, u32);

const MAX_NOISE_HELPER_SOURCE_LINES: usize = 512;

#[derive(Default)]
struct NoiseScheduleSelection {
    assignments: HashSet<StatementKey>,
    loops: HashSet<LoopKey>,
}

#[derive(Default)]
struct MergedNoiseSchedule {
    assignments: HashMap<StatementKey, Vec<usize>>,
    loops: HashMap<LoopKey, Vec<usize>>,
}

struct NoiseLivenessIndex {
    variable_ids: HashMap<String, u32>,
    expr_dependencies: HashMap<ExprId, HashSet<u32>>,
    loop_assignments: HashMap<LoopKey, HashSet<u32>>,
    expression_walks: usize,
}

impl NoiseLivenessIndex {
    fn new(artifact: &CanonicalIrArtifact) -> Self {
        Self {
            variable_ids: artifact
                .hir
                .variables
                .iter()
                .map(|variable| (variable.name.to_string(), variable.id.index()))
                .collect(),
            expr_dependencies: HashMap::new(),
            loop_assignments: HashMap::new(),
            expression_walks: 0,
        }
    }

    fn extend_expr_dependencies(
        &mut self,
        artifact: &CanonicalIrArtifact,
        root: ExprId,
        dependencies: &mut HashSet<u32>,
    ) {
        if let Some(cached) = self.expr_dependencies.get(&root) {
            dependencies.extend(cached.iter().copied());
            return;
        }
        self.expression_walks += 1;
        let mut found = HashSet::new();
        collect_expr_variable_ids(artifact, root, &self.variable_ids, &mut found);
        dependencies.extend(found.iter().copied());
        self.expr_dependencies.insert(root, found);
    }

    fn assigned_variables(&mut self, loop_statement: &HirLoop) -> HashSet<u32> {
        let key = loop_key(loop_statement);
        if let Some(cached) = self.loop_assignments.get(&key) {
            return cached.clone();
        }
        let mut assigned = HashSet::new();
        collect_assigned_variable_ids(&loop_statement.body, &mut assigned);
        self.loop_assignments.insert(key, assigned.clone());
        assigned
    }
}

impl MergedNoiseSchedule {
    fn insert(&mut self, source_index: usize, selection: &NoiseScheduleSelection) {
        for &key in &selection.assignments {
            self.assignments.entry(key).or_default().push(source_index);
        }
        for &key in &selection.loops {
            self.loops.entry(key).or_default().push(source_index);
        }
    }
}

pub(super) fn generate_noise_file(
    artifact: &CanonicalIrArtifact,
    options: &RustTranspileOptions,
) -> Result<GeneratedRustFile, RustBackendError> {
    let parameter_fields = parameter_field_names(artifact);
    let variables = noise_variables(artifact);
    let branch_unknowns = noise_branch_unknowns(artifact);
    let guarded_replay_safety = guarded_assignment_replay_safety(artifact);
    let mut liveness = NoiseLivenessIndex::new(artifact);
    let mut helper_methods = String::new();
    let mut out = String::new();
    // Noise schedules conservatively initialize every replayed Verilog-A variable before
    // source-specific control flow. Some source paths provably overwrite those values before
    // reading them, but retaining the initialization is required for the other paths.
    out.push_str(
        "// @generated by rspice-veriloga; do not edit.\n#![allow(dead_code, non_snake_case, unused_assignments, unused_parens, unused_variables)]\n\n",
    );
    out.push_str("use super::state::Instance;\n");
    writeln!(
        out,
        "use {}::GeneratedEvalContext;\npub use {}::{{GeneratedNoiseComplex, GeneratedNoiseDescriptor, GeneratedNoiseEndpoint, GeneratedNoiseEvaluation, GeneratedNoiseEvaluationError, GeneratedNoiseEvaluationRef, GeneratedNoiseInjectionDescriptor, GeneratedNoiseInjectionEvaluation, GeneratedNoiseKind, GeneratedNoiseProcessDescriptor, GeneratedNoiseProcessEvaluationRef, GeneratedNoiseProcessVisitor, GeneratedNoiseVisitor}};\n",
        options.runtime_path, options.runtime_path
    )
    .expect("write generated noise imports");
    out.push_str("const LIMEXP_MAX: f64 = 5.54062238439351e34;\n");
    out.push_str("const THERMAL_VOLTAGE_PER_K: f64 = 1.380649e-23 / 1.602176634e-19;\n\n");

    out.push_str(&descriptor_table(artifact));
    out.push_str("\nimpl Instance {\n");
    if artifact.noise_sources.sources.is_empty() {
        out.push_str(
            "    pub fn evaluate_noise_sources(&self, _ctx: &GeneratedEvalContext<'_>, _visitor: &mut dyn GeneratedNoiseVisitor) -> Result<(), GeneratedNoiseEvaluationError> {\n\
             \x20       Ok(())\n\
             \x20   }\n\
             }\n",
        );
        out.push_str(&grouped_noise_extension(artifact, options)?);
        return Ok(GeneratedRustFile {
            relative_path: "noise.rs".to_string(),
            contents: out,
        });
    }
    out.push_str(
        "    pub fn evaluate_noise_sources(&self, ctx: &GeneratedEvalContext<'_>, visitor: &mut dyn GeneratedNoiseVisitor) -> Result<(), GeneratedNoiseEvaluationError> {\n\
         \x20       if !self.multiplicity.is_finite() || self.multiplicity <= 0.0 {\n\
         \x20           return Err(GeneratedNoiseEvaluationError::InvalidMultiplicity { value: self.multiplicity });\n\
         \x20       }\n\
         \x20       let params = &*self.params;\n",
    );
    writeln!(
        out,
        "        let mut w = [0.0; {}];",
        artifact.hir.variables.len()
    )
    .expect("write noise workspace");
    emit_event_state_seed(&mut out, artifact);
    let mut activation_schedule = MergedNoiseSchedule::default();
    let mut metadata_schedule = MergedNoiseSchedule::default();
    for (index, source) in artifact.noise_sources.sources.iter().enumerate() {
        let activation_roots: Vec<_> = source
            .activation
            .iter()
            .map(|activation| activation.id)
            .collect();
        activation_schedule.insert(
            index,
            &noise_schedule_selection(artifact, &mut liveness, &activation_roots),
        );
        let mut metadata_roots = vec![source.psd.id];
        metadata_roots.extend(source.exponent.iter().map(|exponent| exponent.id));
        if let Some(table) = &source.table {
            metadata_roots.extend(table.operands.iter().map(|operand| operand.id));
        }
        metadata_schedule.insert(
            index,
            &noise_schedule_selection(artifact, &mut liveness, &metadata_roots),
        );
    }
    debug_assert!(liveness.expression_walks <= artifact.hir.expressions.len());
    emit_partitioned_noise_schedule(
        &mut out,
        &mut helper_methods,
        artifact,
        &parameter_fields,
        &variables,
        &branch_unknowns,
        &activation_schedule,
        &guarded_replay_safety,
        "noise_activation_schedule",
        None,
    )?;
    let mut activation_values = Vec::with_capacity(artifact.noise_sources.sources.len());
    for (index, source) in artifact.noise_sources.sources.iter().enumerate() {
        writeln!(out, "        let noise_source_{index}_active = {{")
            .expect("write noise activation");
        if let Some(activation) = &source.activation {
            let activation = lower_noise_value_expr(
                artifact,
                activation.id,
                &format!("noise_{index}_activation"),
                &parameter_fields,
                &variables,
                &branch_unknowns,
            )?;
            emit_lines(&mut out, &activation.lines, 12);
            writeln!(out, "            {} != 0.0", activation.value)
                .expect("write noise activation value");
        } else {
            out.push_str("            true\n");
        }
        out.push_str("        };\n");
        activation_values.push(format!("noise_source_{index}_active"));
    }
    writeln!(
        out,
        "        let noise_source_active = [{}];",
        activation_values.join(", ")
    )
    .expect("write noise activation array");
    let active_mask_chunks = activation_values
        .chunks(128)
        .map(|values| {
            values
                .iter()
                .enumerate()
                .map(|(bit, value)| {
                    if bit == 0 {
                        format!("({value} as u128)")
                    } else {
                        format!("(({value} as u128) << {bit})")
                    }
                })
                .collect::<Vec<_>>()
                .join(" | ")
        })
        .collect::<Vec<_>>();
    writeln!(
        out,
        "        let noise_source_active_mask = [{}];",
        active_mask_chunks.join(", ")
    )
    .expect("write packed noise activation mask");
    out.push_str("        w.fill(0.0);\n");
    emit_event_state_seed(&mut out, artifact);
    emit_partitioned_noise_schedule(
        &mut out,
        &mut helper_methods,
        artifact,
        &parameter_fields,
        &variables,
        &branch_unknowns,
        &metadata_schedule,
        &guarded_replay_safety,
        "noise_metadata_schedule",
        Some("noise_source_active_mask"),
    )?;
    for (index, source) in artifact.noise_sources.sources.iter().enumerate() {
        writeln!(
            out,
            "        if !noise_source_active[{index}] {{\n\
             \x20           if !visitor.visit({index}, GeneratedNoiseEvaluationRef {{ active: false, psd: 0.0, exponent: None, table_operands: &[] }}) {{ return Ok(()); }}\n\
             \x20       }} else {{"
        )
        .expect("write inactive noise result");
        let psd = lower_noise_value_expr(
            artifact,
            source.psd.id,
            &format!("noise_{index}_psd"),
            &parameter_fields,
            &variables,
            &branch_unknowns,
        )?;
        emit_lines(&mut out, &psd.lines, 12);
        let exponent = if let Some(exponent) = &source.exponent {
            let exponent = lower_noise_value_expr(
                artifact,
                exponent.id,
                &format!("noise_{index}_exponent"),
                &parameter_fields,
                &variables,
                &branch_unknowns,
            )?;
            emit_lines(&mut out, &exponent.lines, 12);
            format!("Some({})", exponent.value)
        } else {
            "None".to_string()
        };
        writeln!(out, "            let psd = {};", psd.value).expect("write noise PSD evaluation");
        emit_finite_check(&mut out, index, "psd", "psd", 12);
        // The magnitude is the spectral density; see the note on the same line in
        // `canonical.rs`. PSP104 contributes `sigVds * ... * S_fl` with `sigVds`
        // at -1.0 in reverse, and rejecting that failed four models outright.
        writeln!(out, "            let psd = psd.abs();").expect("write PSD magnitude");
        writeln!(out, "            let exponent: Option<f64> = {exponent};")
            .expect("write noise exponent evaluation");
        emit_optional_finite_check(&mut out, index, "exponent", "exponent", 12);
        let mut table_values = Vec::new();
        if let Some(table) = &source.table {
            for (operand_index, operand) in table.operands.iter().enumerate() {
                let value = lower_noise_value_expr(
                    artifact,
                    operand.id,
                    &format!("noise_{index}_table_{operand_index}"),
                    &parameter_fields,
                    &variables,
                    &branch_unknowns,
                )?;
                emit_lines(&mut out, &value.lines, 12);
                let local = format!("noise_table_operand_{operand_index}");
                writeln!(out, "            let {local} = {};", value.value)
                    .expect("write noise table operand");
                emit_finite_check(
                    &mut out,
                    index,
                    &format!("table operand {operand_index}"),
                    &local,
                    12,
                );
                table_values.push(local);
            }
        }
        writeln!(
            out,
            "            let table_operands = [{}];",
            table_values.join(", ")
        )
        .expect("write stack noise table operands");
        let scaled_psd = if source.is_current {
            "psd * self.multiplicity"
        } else {
            "psd / self.multiplicity"
        };
        writeln!(out, "            let psd = {scaled_psd};").expect("write multiplicity scaling");
        emit_finite_check(&mut out, index, "scaled psd", "psd", 12);
        writeln!(
            out,
            "            if !visitor.visit({index}, GeneratedNoiseEvaluationRef {{ active: true, psd, exponent, table_operands: &table_operands }}) {{ return Ok(()); }}"
        )
        .expect("write active noise visitor");
        out.push_str("        }\n");
    }
    out.push_str("        Ok(())\n    }\n");
    out.push_str(&helper_methods);
    out.push_str("}\n");
    out.push_str(&grouped_noise_extension(artifact, options)?);

    Ok(GeneratedRustFile {
        relative_path: "noise.rs".to_string(),
        contents: out,
    })
}

fn emit_event_state_seed(out: &mut String, artifact: &CanonicalIrArtifact) {
    for (slot, variable) in artifact
        .hir
        .variables
        .iter()
        .filter(|variable| variable.is_state)
        .enumerate()
    {
        writeln!(
            out,
            "        w[{}] = self.event_state_accepted[{slot}];",
            variable.id.index()
        )
        .expect("write accepted event-state noise seed");
    }
}

/// The static descriptor per noise source: where it injects, and how the
/// analysis is to read the magnitudes that come back with it.
///
/// Metadata only — nothing here is evaluated — which is why it is shared with
/// the canonical emitter rather than written twice. Where the magnitudes come
/// from is exactly what the two disagree about.
pub(super) fn descriptor_table(artifact: &CanonicalIrArtifact) -> String {
    let mut out = String::new();
    let potential_leaders = potential_branch_leaders(artifact);
    writeln!(
        out,
        "pub static NOISE_SOURCES: [GeneratedNoiseDescriptor; {}] = [",
        artifact.noise_sources.sources.len()
    )
    .expect("write noise descriptor header");
    for source in &artifact.noise_sources.sources {
        let table = source.table.as_ref();
        let branch_ordinal = if source.is_current {
            source.branch_ordinal.map(|ordinal| ordinal.index())
        } else {
            potential_leaders
                .get(source.equation.index() as usize)
                .copied()
                .flatten()
                .or_else(|| source.branch_ordinal.map(|ordinal| ordinal.index()))
        };
        writeln!(
            out,
            "    GeneratedNoiseDescriptor {{ mechanism: {:?}, label: {}, kind: GeneratedNoiseKind::{}, equation: {}, is_current: {}, branch_ordinal: {}, pos: {}, neg: {}, table_len: {}, table_log_interp: {} }},",
            source.mechanism.as_str(),
            option_str(source.label.as_deref()),
            noise_kind(source.kind),
            source.equation.index(),
            source.is_current,
            option_usize(branch_ordinal),
            endpoint_literal(source.pos.node, &source.pos.name, source.pos.is_internal),
            endpoint_literal(source.neg.node, &source.neg.name, source.neg.is_internal),
            table.map_or(0, |table| table.operands.len()),
            table.is_some_and(|table| table.log_interp),
        )
        .expect("write noise descriptor");
    }
    out.push_str("];\n");
    out
}

#[derive(Debug)]
struct GroupedNoiseProcessPlan {
    process_id: usize,
    label: Option<String>,
    kind: CanonicalNoiseSourceKind,
    table_log_interp: bool,
    active: usize,
    psd: usize,
    exponent: Option<usize>,
    table: Vec<usize>,
    injections: Vec<GroupedNoiseInjectionPlan>,
}

#[derive(Debug)]
struct GroupedNoiseInjectionPlan {
    descriptor: usize,
    real: Option<usize>,
    reactive: Option<usize>,
}

#[derive(Debug)]
struct GroupedNoisePlan {
    function: CfgFunction,
    outputs: Vec<ValueId>,
    processes: Vec<GroupedNoiseProcessPlan>,
    descriptors: Vec<(usize, usize)>,
}

/// Emit the additive grouped-noise ABI implemented by newly generated model
/// crates. The scalar descriptor/evaluator above deliberately remains intact:
/// checked-in artifacts generated before this capability continue to compile,
/// and a registry can select this path only when the new tables are present.
pub(super) fn grouped_noise_extension(
    artifact: &CanonicalIrArtifact,
    options: &RustTranspileOptions,
) -> Result<String, RustBackendError> {
    let Some(plan) = plan_grouped_noise(artifact)? else {
        return Ok(
            "\npub static GROUPED_NOISE_PROCESSES: [GeneratedNoiseProcessDescriptor; 0] = [];\n\
             pub static GROUPED_NOISE_INJECTIONS: [GeneratedNoiseInjectionDescriptor; 0] = [];\n\n\
             impl Instance {\n\
             \x20   pub fn evaluate_noise_processes_at_frequency(&self, _ctx: &GeneratedEvalContext<'_>, frequency_hz: f64, _visitor: &mut dyn GeneratedNoiseProcessVisitor) -> Result<(), GeneratedNoiseEvaluationError> {\n\
             \x20       if !frequency_hz.is_finite() || frequency_hz < 0.0 { return Err(GeneratedNoiseEvaluationError::InvalidFrequency { value: frequency_hz }); }\n\
             \x20       Ok(())\n\
             \x20   }\n\
             }\n"
                .to_string(),
        );
    };
    let mut out = String::new();
    let lane_types = lane_runtime_types(&plan.function);
    if !lane_types.is_empty() {
        writeln!(
            out,
            "\nuse {}::{{{}}};",
            options.runtime_path,
            lane_types.into_iter().collect::<Vec<_>>().join(", ")
        )
        .expect("write grouped lane imports");
    }
    let potential_leaders = potential_branch_leaders(artifact);
    writeln!(
        out,
        "\npub static GROUPED_NOISE_PROCESSES: [GeneratedNoiseProcessDescriptor; {}] = [",
        plan.processes.len()
    )
    .expect("write grouped noise process header");
    for process in &plan.processes {
        writeln!(
            out,
            "    GeneratedNoiseProcessDescriptor {{ process_id: {}, label: {}, kind: GeneratedNoiseKind::{}, table_len: {}, table_log_interp: {} }},",
            process.process_id,
            option_str(process.label.as_deref()),
            noise_kind(process.kind),
            process.table.len(),
            process.table_log_interp,
        )
        .expect("write grouped process descriptor");
    }
    out.push_str("];\n");
    writeln!(
        out,
        "pub static GROUPED_NOISE_INJECTIONS: [GeneratedNoiseInjectionDescriptor; {}] = [",
        plan.descriptors.len()
    )
    .expect("write grouped injection header");
    for &(process, equation_index) in &plan.descriptors {
        let equation = &artifact.mir.equations[equation_index];
        let is_current = equation.kind == MirEquationKind::Current;
        let branch_ordinal = if is_current {
            None
        } else {
            potential_leaders.get(equation_index).copied().flatten()
        };
        let pos = equation.branch.pos_node;
        let neg = equation.branch.neg_node;
        let pos_name = pos.map_or("0", |node| {
            artifact.mir.nodes[usize::from(node)].name.as_str()
        });
        let neg_name = neg.map_or("0", |node| {
            artifact.mir.nodes[usize::from(node)].name.as_str()
        });
        let pos_internal =
            pos.is_some_and(|node| !artifact.mir.nodes[usize::from(node)].is_external);
        let neg_internal =
            neg.is_some_and(|node| !artifact.mir.nodes[usize::from(node)].is_external);
        writeln!(
            out,
            "    GeneratedNoiseInjectionDescriptor {{ process_id: {process}, equation: {equation_index}, is_current: {is_current}, branch_ordinal: {}, pos: {}, neg: {} }},",
            option_usize(branch_ordinal),
            endpoint_literal(pos, pos_name, pos_internal),
            endpoint_literal(neg, neg_name, neg_internal),
        )
        .expect("write grouped injection descriptor");
    }
    out.push_str("];\n\nimpl Instance {\n");
    out.push_str(
        "    pub fn evaluate_noise_processes_at_frequency(&self, ctx: &GeneratedEvalContext<'_>, frequency_hz: f64, visitor: &mut dyn GeneratedNoiseProcessVisitor) -> Result<(), GeneratedNoiseEvaluationError> {\n\
         \x20       if !frequency_hz.is_finite() || frequency_hz < 0.0 {\n\
         \x20           return Err(GeneratedNoiseEvaluationError::InvalidFrequency { value: frequency_hz });\n\
         \x20       }\n\
         \x20       if !self.multiplicity.is_finite() || self.multiplicity <= 0.0 {\n\
         \x20           return Err(GeneratedNoiseEvaluationError::InvalidMultiplicity { value: self.multiplicity });\n\
         \x20       }\n\
         \x20       let parameters = &self.params.values;\n\
         \x20       let parameter_given = &*self.param_given;\n\
         \x20       let temperature = ctx.temperature();\n\
         \x20       let thermal_voltage = ctx.thermal_voltage();\n\
         \x20       let multiplicity = self.multiplicity;\n\
         \x20       let time = self.time;\n",
    );
    if plan
        .function
        .values
        .iter()
        .any(|value| matches!(value.kind, CfgValueKind::EventState(_)))
    {
        out.push_str("        let event_state = &*self.event_state_accepted;\n");
    }
    writeln!(
        out,
        "        let node_potentials: [f64; {}] = [{}];",
        artifact.mir.nodes.len(),
        (0..artifact.mir.nodes.len())
            .map(|index| format!("ctx.node_voltage(self.nodes[{index}])"))
            .collect::<Vec<_>>()
            .join(", ")
    )
    .expect("write grouped node potentials");
    out.push_str("        let branch_flows: [f64; 0] = [];\n");
    writeln!(
        out,
        "        let branch_unknown_flows: [f64; {}] = [{}];",
        artifact.mir.branch_unknowns.len(),
        (0..artifact.mir.branch_unknowns.len())
            .map(|index| format!("ctx.branch_current(self.branches[{index}])"))
            .collect::<Vec<_>>()
            .join(", ")
    )
    .expect("write grouped branch flows");
    let mut bindings = EmitBindings {
        analysis: "ctx.analysis".into(),
        simparam: "ctx.simparam_or".into(),
        ..EmitBindings::default()
    };
    // The grouped slice rejects dynamic state below; these names make any
    // accidental reintroduction a generated compile error instead of silently
    // binding transient history during a noise sweep.
    bindings.ddt = "grouped_noise_ddt_is_unsupported".into();
    bindings.idt = "grouped_noise_idt_is_unsupported".into();
    let (body, values) = emit_body(&plan.function, &plan.outputs, &bindings)
        .map_err(|error| unsupported(artifact, format!("grouped noise body: {error}")))?;
    emit_lines(
        &mut out,
        &body.lines().map(str::to_owned).collect::<Vec<_>>(),
        8,
    );
    out.push_str("        let omega = core::f64::consts::TAU * frequency_hz;\n");
    for (process_index, process) in plan.processes.iter().enumerate() {
        let active = &values[process.active];
        let psd = &values[process.psd];
        writeln!(
            out,
            "        let process_{process_index}_active = {active} != 0.0;"
        )
        .expect("write grouped activation");
        writeln!(
            out,
            "        let process_{process_index}_psd = ({psd}).abs();"
        )
        .expect("write grouped psd");
        emit_finite_check(
            &mut out,
            process_index,
            "psd",
            &format!("process_{process_index}_psd"),
            8,
        );
        let exponent = process
            .exponent
            .map(|position| values[position].clone())
            .map_or_else(|| "None".to_string(), |value| format!("Some({value})"));
        writeln!(
            out,
            "        let process_{process_index}_exponent: Option<f64> = {exponent};"
        )
        .expect("write grouped exponent");
        emit_optional_finite_check(
            &mut out,
            process_index,
            "exponent",
            &format!("process_{process_index}_exponent"),
            8,
        );
        let table = process
            .table
            .iter()
            .map(|position| values[*position].clone())
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            out,
            "        let process_{process_index}_table = [{table}];"
        )
        .expect("write grouped table");
        for (local, injection) in process.injections.iter().enumerate() {
            let real = injection
                .real
                .map(|position| values[position].as_str())
                .unwrap_or("0.0");
            let reactive = injection
                .reactive
                .map(|position| values[position].as_str())
                .unwrap_or("0.0");
            let equation_index = plan.descriptors[injection.descriptor].1;
            let equation_kind = artifact.mir.equations[equation_index].kind;
            let rhs_sign = noise_rhs_sign(equation_kind);
            let multiplicity_scale = if equation_kind == MirEquationKind::Current {
                "self.multiplicity.sqrt()"
            } else {
                "self.multiplicity.sqrt().recip()"
            };
            writeln!(
                out,
                "        let process_{process_index}_gain_{local} = GeneratedNoiseComplex {{ re: ({real}) * {rhs_sign:.1} * {multiplicity_scale}, im: omega * ({reactive}) * {rhs_sign:.1} * {multiplicity_scale} }};"
            )
            .expect("write grouped gain");
            writeln!(
                out,
                "        if !process_{process_index}_gain_{local}.is_finite() {{ return Err(GeneratedNoiseEvaluationError::NonFiniteGain {{ process: {process_index}, injection: {local}, re: process_{process_index}_gain_{local}.re, im: process_{process_index}_gain_{local}.im }}); }}"
            )
            .expect("write grouped gain validation");
        }
        let injections = process
            .injections
            .iter()
            .enumerate()
            .map(|(local, injection)| {
                format!(
                    "GeneratedNoiseInjectionEvaluation {{ descriptor: {}, gain: process_{process_index}_gain_{local} }}",
                    injection.descriptor
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            out,
            "        let process_{process_index}_injections = [{injections}];"
        )
        .expect("write grouped injections");
        writeln!(
            out,
            "        if !visitor.visit_process({process_index}, GeneratedNoiseProcessEvaluationRef {{ active: process_{process_index}_active, psd: process_{process_index}_psd, exponent: process_{process_index}_exponent, table_operands: &process_{process_index}_table, injections: &process_{process_index}_injections }}) {{ return Ok(()); }}"
        )
        .expect("write grouped visitor");
    }
    out.push_str("        Ok(())\n    }\n}\n");
    Ok(out)
}

fn plan_grouped_noise(
    artifact: &CanonicalIrArtifact,
) -> Result<Option<GroupedNoisePlan>, RustBackendError> {
    let mut cfg = crate::canonical_ir::CfgModel::from_hir(&artifact.hir, &artifact.mir).map_err(
        |diagnostics| unsupported(artifact, format!("grouped noise CFG: {diagnostics:?}")),
    )?;
    if cfg.noise_processes.is_empty() {
        return Ok(None);
    }
    if artifact
        .mir
        .equations
        .iter()
        .any(|equation| equation.kind == MirEquationKind::Indirect)
    {
        return Err(unsupported(
            artifact,
            "grouped noise routed through an indirect contribution",
        ));
    }
    if cfg
        .function
        .values
        .iter()
        .any(|value| matches!(value.kind, CfgValueKind::BranchFlow(_)))
    {
        return Err(unsupported(
            artifact,
            "grouped noise depending on an unresolved flow probe",
        ));
    }
    for (expected, process) in cfg.noise_processes.iter().enumerate() {
        if process.process_id as usize != expected {
            return Err(unsupported(
                artifact,
                format!(
                    "grouped noise process IDs are not dense: expected {expected}, found {}",
                    process.process_id
                ),
            ));
        }
    }
    let seeds = cfg
        .noise_processes
        .iter()
        .map(|process| AdSeed::NoiseProcess(process.process_id))
        .collect::<Vec<_>>();
    validate_linear_noise_routing(artifact, &cfg.function, &seeds)?;
    let residuals = artifact
        .mir
        .equations
        .iter()
        .map(|equation| cfg.residuals[usize::from(equation.contribution)])
        .collect::<Vec<_>>();
    let charges = super::canonical::stored_charges(&mut cfg.function, &residuals);
    let mut differentiated = differentiate(&cfg.function, &seeds).map_err(|error| {
        unsupported(artifact, format!("grouped noise differentiation: {error}"))
    })?;
    let conduction_rows = residuals
        .iter()
        .map(|residual| differentiated.derivative_row(*residual))
        .collect::<Vec<_>>();
    let reactive_rows = charges
        .iter()
        .map(|charge| charge.map_or_else(Vec::new, |charge| differentiated.derivative_row(charge)))
        .collect::<Vec<_>>();

    let mut wanted = Vec::new();
    let mut processes = Vec::with_capacity(cfg.noise_processes.len());
    let mut descriptors = Vec::new();
    let mut place = |value: ValueId| {
        wanted.push(value);
        wanted.len() - 1
    };
    for (process_index, process) in cfg.noise_processes.iter().enumerate() {
        let active = place(process.active);
        let psd = place(process.psd);
        let exponent = process.exponent.map(&mut place);
        let table = process.table.iter().copied().map(&mut place).collect();
        let mut injections = Vec::new();
        for equation in 0..residuals.len() {
            // A pure ddt contribution belongs entirely to the reactive lane;
            // using its transient companion derivative as a real gain here
            // would make noise depend on the last timestep.
            let real = if charges[equation].is_some() {
                None
            } else {
                conduction_rows[equation][process_index]
            };
            let reactive = reactive_rows[equation]
                .get(process_index)
                .copied()
                .flatten();
            let nonzero = |value: Option<ValueId>| {
                value.filter(|value| {
                    !matches!(
                        differentiated.function.value(*value).kind,
                        CfgValueKind::RealConstant(constant) if constant == 0.0
                    )
                })
            };
            let real = nonzero(real);
            let reactive = nonzero(reactive);
            if real.is_none() && reactive.is_none() {
                continue;
            }
            let descriptor = descriptors.len();
            descriptors.push((process_index, equation));
            injections.push(GroupedNoiseInjectionPlan {
                descriptor,
                real: real.map(&mut place),
                reactive: reactive.map(&mut place),
            });
        }
        processes.push(GroupedNoiseProcessPlan {
            process_id: process.process_id as usize,
            label: process.label.as_ref().map(ToString::to_string),
            kind: process.kind,
            table_log_interp: process.log_interp,
            active,
            psd,
            exponent,
            table,
            injections,
        });
    }
    let (function, outputs) = crate::canonical_ir::optimize_cfg(&differentiated.function, &wanted);
    Ok(Some(GroupedNoisePlan {
        function,
        outputs,
        processes,
        descriptors,
    }))
}

fn validate_linear_noise_routing(
    artifact: &CanonicalIrArtifact,
    function: &CfgFunction,
    seeds: &[AdSeed],
) -> Result<(), RustBackendError> {
    let live = lane_liveness(function, seeds);
    let depends = |value: ValueId| !live[usize::from(value)].is_empty();
    for block in &function.blocks {
        if let CfgTerminator::Branch { condition, .. } = block.terminator
            && depends(condition)
        {
            return Err(unsupported(
                artifact,
                "a noise process used as control flow in generated Rust",
            ));
        }
    }
    for value in &function.values {
        if !depends(value.id) {
            continue;
        }
        let valid = match &value.kind {
            CfgValueKind::NoiseProcess(_)
            | CfgValueKind::BlockParameter
            | CfgValueKind::Ddt { .. }
            | CfgValueKind::LaneSplat(_)
            | CfgValueKind::LaneWiden { .. }
            | CfgValueKind::LaneBinary { .. }
            | CfgValueKind::LaneScalar { .. }
            | CfgValueKind::LaneExtract { .. } => true,
            CfgValueKind::Unary {
                op: CfgUnaryOp::Neg,
                ..
            } => true,
            CfgValueKind::Binary { op, left, right }
                if matches!(op, CfgBinaryOp::Add | CfgBinaryOp::Sub) =>
            {
                let _ = (left, right);
                true
            }
            CfgValueKind::Binary {
                op: CfgBinaryOp::Mul,
                left,
                right,
            } => !(depends(*left) && depends(*right)),
            CfgValueKind::Binary {
                op: CfgBinaryOp::Div,
                right,
                ..
            } => !depends(*right),
            _ => false,
        };
        if !valid {
            return Err(unsupported(
                artifact,
                format!(
                    "nonlinear or stateful generated-Rust routing of noise process at CFG value {} ({:?})",
                    value.id, value.kind
                ),
            ));
        }
    }
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn emit_partitioned_noise_schedule(
    out: &mut String,
    helper_methods: &mut String,
    artifact: &CanonicalIrArtifact,
    parameter_fields: &HashMap<String, String>,
    variables: &HashMap<String, LoweredVariable>,
    branch_unknowns: &HashMap<String, BranchCurrentSlot>,
    schedule: &MergedNoiseSchedule,
    guarded_replay_safety: &HashMap<StatementKey, bool>,
    prefix: &str,
    active_sources: Option<&str>,
) -> Result<(), RustBackendError> {
    let mut helper_bodies = Vec::new();
    let mut body = String::new();
    let mut body_lines = 0usize;
    for (index, statement) in artifact.hir.statements.iter().enumerate() {
        let mut fragment = String::new();
        emit_noise_statements(
            &mut fragment,
            artifact,
            std::slice::from_ref(statement),
            parameter_fields,
            variables,
            branch_unknowns,
            schedule,
            guarded_replay_safety,
            8,
            &format!("{prefix}_{index}"),
            active_sources.map(|_| "active"),
        )?;
        if fragment.is_empty() {
            continue;
        }
        // Schedule fragments are hoisted into unit-returning helpers, so a
        // `return` inside one either fails to compile or silently skips the
        // rest of the schedule. Control flow that has to escape a statement
        // must record itself on the eval context instead. Catch it here, where
        // the offending statement is still identifiable, rather than in rustc
        // against a multi-megabyte generated file.
        if fragment_contains_return(&fragment) {
            return Err(RustBackendError::internal(
                artifact.metadata.source_package.as_str(),
                artifact.mir.module_name.as_str(),
                format!(
                    "noise schedule statement {index} emits `return` into the unit-returning \
                     helper `{prefix}`; report the condition on the eval context instead"
                ),
            ));
        }
        let fragment_lines = fragment.lines().count();
        if !body.is_empty() && body_lines + fragment_lines > MAX_NOISE_HELPER_SOURCE_LINES {
            helper_bodies.push(std::mem::take(&mut body));
            body_lines = 0;
        }
        body.push_str(&fragment);
        body_lines += fragment_lines;
    }
    if !body.is_empty() {
        helper_bodies.push(body);
    }

    let variable_count = artifact.hir.variables.len();
    let active_mask_chunks = artifact.noise_sources.sources.len().div_ceil(128);
    for (index, body) in helper_bodies.into_iter().enumerate() {
        let helper_name = format!("{prefix}_part_{index}");
        write!(out, "        self.{helper_name}(ctx, &mut w").expect("write noise helper call");
        if active_sources.is_some() {
            out.push_str(", &noise_source_active_mask");
        }
        out.push_str(");\n");

        writeln!(helper_methods, "\n    #[inline(never)]")
            .expect("write noise helper inline policy");
        write!(
            helper_methods,
            "    fn {helper_name}(&self, ctx: &GeneratedEvalContext<'_>, w: &mut [f64; {variable_count}]"
        )
        .expect("write noise helper signature");
        if active_sources.is_some() {
            write!(helper_methods, ", active: &[u128; {active_mask_chunks}]")
                .expect("write noise helper activity parameter");
        }
        helper_methods.push_str(") {\n        let params = &*self.params;\n");
        helper_methods.push_str(&body);
        helper_methods.push_str("    }\n");
    }
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn emit_noise_statements(
    out: &mut String,
    artifact: &CanonicalIrArtifact,
    statements: &[HirStatement],
    parameter_fields: &HashMap<String, String>,
    variables: &HashMap<String, LoweredVariable>,
    branch_unknowns: &HashMap<String, BranchCurrentSlot>,
    schedule: &MergedNoiseSchedule,
    guarded_replay_safety: &HashMap<StatementKey, bool>,
    indentation: usize,
    prefix: &str,
    active_sources: Option<&str>,
) -> Result<(), RustBackendError> {
    let padding = " ".repeat(indentation);
    for (index, statement) in statements.iter().enumerate() {
        let statement_prefix = format!("{prefix}_{index}");
        match statement {
            HirStatement::Assignment(assignment) => {
                let Some(sources) = schedule.assignments.get(&assignment_key(assignment)) else {
                    continue;
                };
                if assignment.index.is_some() {
                    return Err(unsupported(
                        artifact,
                        "array assignment in generated noise evaluation",
                    ));
                }
                if assignment.unfiltered_initial_step_guard.is_some()
                    && !guarded_replay_safety
                        .get(&assignment_key(assignment))
                        .copied()
                        .unwrap_or(false)
                {
                    return Err(unsupported(
                        artifact,
                        &format!(
                            "initial-step guarded noise dependency '{}' at {}..{} is not instance-static and requires persisted generated state",
                            assignment.target_name, assignment.span.start, assignment.span.end
                        ),
                    ));
                }
                // Canonical lowering treats an unfiltered initial-step assignment
                // as the instance-static initializer for its target. Replaying
                // the selected initializer here reconstructs that persisted
                // value without spuriously leaving the local at zero.
                let lowered = lower_noise_value_expr(
                    artifact,
                    assignment.expr.id,
                    &statement_prefix,
                    parameter_fields,
                    variables,
                    branch_unknowns,
                )?;
                if let Some(active_sources) = active_sources {
                    writeln!(
                        out,
                        "{padding}if {} {{",
                        active_source_expr(active_sources, sources)
                    )
                    .expect("write noise assignment activity guard");
                }
                let body_indentation = indentation + usize::from(active_sources.is_some()) * 4;
                emit_lines(out, &lowered.lines, body_indentation);
                writeln!(
                    out,
                    "{}w[{}] = {};",
                    " ".repeat(body_indentation),
                    assignment.target.index(),
                    lowered.value
                )
                .expect("write noise assignment");
                if active_sources.is_some() {
                    writeln!(out, "{padding}}}")
                        .expect("write noise assignment activity guard end");
                }
            }
            HirStatement::Loop(loop_statement) => {
                let Some(sources) = schedule.loops.get(&loop_key(loop_statement)) else {
                    continue;
                };
                if let Some(active_sources) = active_sources {
                    writeln!(
                        out,
                        "{padding}if {} {{",
                        active_source_expr(active_sources, sources)
                    )
                    .expect("write noise loop activity guard");
                }
                let body_indentation = indentation + usize::from(active_sources.is_some()) * 4;
                let body_padding = " ".repeat(body_indentation);
                writeln!(
                    out,
                    "{body_padding}let mut {statement_prefix}_iterations = 0usize;"
                )
                .expect("write noise loop counter");
                writeln!(out, "{body_padding}loop {{").expect("write noise loop");
                let condition = lower_noise_value_expr(
                    artifact,
                    loop_statement.condition.id,
                    &format!("{statement_prefix}_condition"),
                    parameter_fields,
                    variables,
                    branch_unknowns,
                )?;
                emit_lines(out, &condition.lines, body_indentation + 4);
                writeln!(
                    out,
                    "{body_padding}    if {} == 0.0 {{ break; }}",
                    condition.value
                )
                .expect("write noise loop condition");
                emit_noise_statements(
                    out,
                    artifact,
                    &loop_statement.body,
                    parameter_fields,
                    variables,
                    branch_unknowns,
                    schedule,
                    guarded_replay_safety,
                    body_indentation + 4,
                    &format!("{statement_prefix}_body"),
                    active_sources,
                )?;
                writeln!(out, "{body_padding}    {statement_prefix}_iterations += 1;")
                    .expect("write noise loop increment");
                writeln!(
                    out,
                    "{body_padding}    if {statement_prefix}_iterations > Self::MAX_ANALOG_LOOP_ITERATIONS {{ ctx.report_analog_loop_limit(\"noise\", {statement_prefix}_iterations, Self::MAX_ANALOG_LOOP_ITERATIONS); break; }}"
                )
                .expect("write noise loop bound");
                writeln!(out, "{body_padding}}}").expect("write noise loop end");
                if active_sources.is_some() {
                    writeln!(out, "{padding}}}").expect("write noise loop activity guard end");
                }
            }
        }
    }
    Ok(())
}

/// Whether emitted Rust contains a `return` keyword outside a string literal.
///
/// Deliberately conservative: it matches the bare keyword only, so identifiers
/// like `returned_value` and the text of a `&str` operand do not trip it.
fn fragment_contains_return(fragment: &str) -> bool {
    let bytes = fragment.as_bytes();
    let mut index = 0usize;
    let mut in_string = false;
    while index < bytes.len() {
        match bytes[index] {
            b'\\' if in_string => {
                index += 2;
                continue;
            }
            b'"' => in_string = !in_string,
            b'r' if !in_string && fragment[index..].starts_with("return") => {
                let before_is_boundary = index == 0
                    || !(bytes[index - 1].is_ascii_alphanumeric() || bytes[index - 1] == b'_');
                let after = bytes.get(index + "return".len());
                let after_is_boundary =
                    after.is_none_or(|byte| !(byte.is_ascii_alphanumeric() || *byte == b'_'));
                if before_is_boundary && after_is_boundary {
                    return true;
                }
            }
            _ => {}
        }
        index += 1;
    }
    false
}

fn noise_schedule_selection(
    artifact: &CanonicalIrArtifact,
    liveness: &mut NoiseLivenessIndex,
    roots: &[ExprId],
) -> NoiseScheduleSelection {
    let mut live = HashSet::new();
    for &root in roots {
        liveness.extend_expr_dependencies(artifact, root, &mut live);
    }
    let mut selection = NoiseScheduleSelection::default();
    select_statements_backward(
        artifact,
        liveness,
        &artifact.hir.statements,
        &mut live,
        &mut selection,
    );
    selection
}

#[cfg(test)]
pub(super) fn noise_liveness_expression_walks(artifact: &CanonicalIrArtifact) -> usize {
    let mut liveness = NoiseLivenessIndex::new(artifact);
    for source in &artifact.noise_sources.sources {
        let activation_roots: Vec<_> = source
            .activation
            .iter()
            .map(|activation| activation.id)
            .collect();
        let _ = noise_schedule_selection(artifact, &mut liveness, &activation_roots);
        let mut metadata_roots = vec![source.psd.id];
        metadata_roots.extend(source.exponent.iter().map(|exponent| exponent.id));
        if let Some(table) = &source.table {
            metadata_roots.extend(table.operands.iter().map(|operand| operand.id));
        }
        let _ = noise_schedule_selection(artifact, &mut liveness, &metadata_roots);
    }
    liveness.expression_walks
}

fn select_statements_backward(
    artifact: &CanonicalIrArtifact,
    liveness: &mut NoiseLivenessIndex,
    statements: &[HirStatement],
    live: &mut HashSet<u32>,
    selection: &mut NoiseScheduleSelection,
) {
    for statement in statements.iter().rev() {
        match statement {
            HirStatement::Assignment(assignment) if live.contains(&assignment.target.index()) => {
                selection.assignments.insert(assignment_key(assignment));
                live.remove(&assignment.target.index());
                liveness.extend_expr_dependencies(artifact, assignment.expr.id, live);
                if let Some(index) = &assignment.index {
                    liveness.extend_expr_dependencies(artifact, index.id, live);
                }
            }
            HirStatement::Assignment(_) => {}
            HirStatement::Loop(loop_statement) => {
                let assigned = liveness.assigned_variables(loop_statement);
                if assigned.iter().any(|variable| live.contains(variable)) {
                    selection.loops.insert(loop_key(loop_statement));
                    let exit_live = live.clone();
                    let mut loop_live = exit_live.clone();
                    loop {
                        let mut body_live = loop_live.clone();
                        select_statements_backward(
                            artifact,
                            liveness,
                            &loop_statement.body,
                            &mut body_live,
                            selection,
                        );
                        liveness.extend_expr_dependencies(
                            artifact,
                            loop_statement.condition.id,
                            &mut body_live,
                        );
                        body_live.extend(exit_live.iter().cloned());
                        let before = loop_live.len();
                        loop_live.extend(body_live);
                        if loop_live.len() == before {
                            break;
                        }
                    }
                    *live = loop_live;
                }
            }
        }
    }
}

fn collect_assigned_variable_ids(statements: &[HirStatement], assigned: &mut HashSet<u32>) {
    for statement in statements {
        match statement {
            HirStatement::Assignment(assignment) => {
                assigned.insert(assignment.target.index());
            }
            HirStatement::Loop(loop_statement) => {
                collect_assigned_variable_ids(&loop_statement.body, assigned);
            }
        }
    }
}

fn assigned_variables(statements: &[HirStatement]) -> HashSet<String> {
    let mut assigned = HashSet::new();
    for statement in statements {
        match statement {
            HirStatement::Assignment(assignment) => {
                assigned.insert(assignment.target_name.to_string());
            }
            HirStatement::Loop(loop_statement) => {
                assigned.extend(assigned_variables(&loop_statement.body));
            }
        }
    }
    assigned
}

fn assignment_key(assignment: &HirAssignment) -> StatementKey {
    (
        assignment.span.source_file_id,
        assignment.span.start,
        assignment.span.end,
        assignment.target.index(),
    )
}

fn loop_key(loop_statement: &HirLoop) -> LoopKey {
    (
        loop_statement.span.source_file_id,
        loop_statement.span.start,
        loop_statement.span.end,
    )
}

fn collect_expr_variable_ids(
    artifact: &CanonicalIrArtifact,
    root: ExprId,
    variable_ids: &HashMap<String, u32>,
    dependencies: &mut HashSet<u32>,
) {
    let mut stack = vec![root];
    let mut visited = HashSet::new();
    while let Some(expr) = stack.pop() {
        if !visited.insert(expr) {
            continue;
        }
        match &artifact.hir.expressions[usize::from(expr)].kind {
            HirExprKind::Identifier { name } => {
                if let Some(&variable) = variable_ids.get(name.as_str()) {
                    dependencies.insert(variable);
                }
            }
            HirExprKind::Binary { left, right, .. } => stack.extend([*left, *right]),
            HirExprKind::Unary { operand, .. } => stack.push(*operand),
            HirExprKind::Conditional {
                condition,
                then_expr,
                else_expr,
            } => {
                stack.extend([*condition, *then_expr, *else_expr]);
            }
            HirExprKind::Call { args, .. }
            | HirExprKind::SystemFunction { args, .. }
            | HirExprKind::ArrayLiteral { elements: args, .. } => {
                stack.extend(args.iter().copied())
            }
            HirExprKind::ArrayAccess { index, .. } => stack.push(*index),
            HirExprKind::AnalogOperator { op } => push_analog_children(op, &mut stack),
            HirExprKind::Laplace { expr, .. } => stack.push(*expr),
            HirExprKind::Zi {
                expr,
                kind,
                period,
                transition,
                first_transition,
            } => {
                stack.extend([*expr, *period]);
                stack.extend(transition.iter().copied());
                stack.extend(first_transition.iter().copied());
                push_zi_children(kind, &mut stack);
            }
            HirExprKind::NoiseSource { operands, .. } => stack.extend(operands.iter().copied()),
            HirExprKind::NullArgument
            | HirExprKind::Number { .. }
            | HirExprKind::StringLiteral { .. }
            | HirExprKind::BranchAccess { .. }
            | HirExprKind::NamedBranchAccess { .. } => {}
        }
    }
}

fn push_zi_children(kind: &crate::canonical_ir::HirZiKind, stack: &mut Vec<ExprId>) {
    match kind {
        crate::canonical_ir::HirZiKind::ZeroPole { zeros, poles } => {
            stack.extend(zeros.iter().copied());
            stack.extend(poles.iter().copied());
        }
        crate::canonical_ir::HirZiKind::ZeroDenominator { zeros, denominator } => {
            stack.extend(zeros.iter().copied());
            stack.extend(denominator.iter().copied());
        }
        crate::canonical_ir::HirZiKind::NumeratorPole { numerator, poles } => {
            stack.extend(numerator.iter().copied());
            stack.extend(poles.iter().copied());
        }
        crate::canonical_ir::HirZiKind::NumeratorDenominator {
            numerator,
            denominator,
        } => {
            stack.extend(numerator.iter().copied());
            stack.extend(denominator.iter().copied());
        }
    }
}

fn push_analog_children(op: &HirAnalogOperator, stack: &mut Vec<ExprId>) {
    match op {
        HirAnalogOperator::Limit {
            proposed,
            candidate,
            type_metadata,
            ..
        } => {
            stack.extend([*proposed, *candidate]);
            stack.extend(type_metadata.iter().copied());
        }
        HirAnalogOperator::LimiterArgument { .. } => {}
        HirAnalogOperator::Ddt { expr, abstol } => {
            stack.push(*expr);
            stack.extend(abstol.iter().copied());
        }
        HirAnalogOperator::Idt {
            expr,
            ic,
            assert,
            abstol,
        } => {
            stack.push(*expr);
            stack.extend(ic.iter().chain(assert).chain(abstol).copied());
        }
        HirAnalogOperator::IdtMod {
            expr,
            ic,
            modulus,
            offset,
            abstol,
        } => {
            stack.push(*expr);
            stack.extend(
                ic.iter()
                    .chain(modulus)
                    .chain(offset)
                    .chain(abstol)
                    .copied(),
            );
        }
        HirAnalogOperator::Ddx { expr, probe } => stack.extend([*expr, *probe]),
        HirAnalogOperator::Limexp { expr } | HirAnalogOperator::LastCrossing { expr, .. } => {
            stack.push(*expr);
        }
        HirAnalogOperator::Absdelay {
            expr,
            delay,
            max_delay,
        } => {
            stack.extend([*expr, *delay]);
            stack.extend(max_delay.iter().copied());
        }
        HirAnalogOperator::Transition {
            expr,
            delay,
            rise,
            fall,
            tolerance,
            ..
        } => {
            stack.push(*expr);
            stack.extend(
                delay
                    .iter()
                    .chain(rise)
                    .chain(fall)
                    .chain(tolerance)
                    .copied(),
            );
        }
        HirAnalogOperator::TransitionDerivative {
            input,
            input_derivative,
            delay,
            rise,
            fall,
            ..
        } => {
            stack.extend([*input, *input_derivative]);
            stack.extend(delay.iter().chain(rise).chain(fall).copied());
        }
        HirAnalogOperator::Slew {
            expr,
            max_rise,
            max_fall,
        } => {
            stack.push(*expr);
            stack.extend(max_rise.iter().chain(max_fall).copied());
        }
    }
}

fn guarded_assignment_replay_safety(artifact: &CanonicalIrArtifact) -> HashMap<StatementKey, bool> {
    let variable_names: HashSet<_> = artifact
        .hir
        .variables
        .iter()
        .map(|variable| variable.name.to_string())
        .collect();
    let mut variable_safety = HashMap::new();
    let mut assignment_safety = HashMap::new();
    classify_statement_replay_safety(
        artifact,
        &artifact.hir.statements,
        &variable_names,
        &mut variable_safety,
        &mut assignment_safety,
    );
    assignment_safety
}

fn classify_statement_replay_safety(
    artifact: &CanonicalIrArtifact,
    statements: &[HirStatement],
    variable_names: &HashSet<String>,
    variable_safety: &mut HashMap<String, bool>,
    assignment_safety: &mut HashMap<StatementKey, bool>,
) {
    for statement in statements {
        match statement {
            HirStatement::Assignment(assignment) => {
                let safe = assignment.index.is_none()
                    && expr_is_instance_static(
                        artifact,
                        assignment.expr.id,
                        assignment.target_name.as_str(),
                        variable_names,
                        variable_safety,
                    );
                variable_safety.insert(assignment.target_name.to_string(), safe);
                assignment_safety.insert(assignment_key(assignment), safe);
            }
            HirStatement::Loop(loop_statement) => {
                classify_statement_replay_safety(
                    artifact,
                    &loop_statement.body,
                    variable_names,
                    variable_safety,
                    assignment_safety,
                );
                for variable in assigned_variables(&loop_statement.body) {
                    variable_safety.insert(variable, false);
                }
            }
        }
    }
}

fn expr_is_instance_static(
    artifact: &CanonicalIrArtifact,
    root: ExprId,
    current_target: &str,
    variable_names: &HashSet<String>,
    variable_safety: &HashMap<String, bool>,
) -> bool {
    let mut stack = vec![root];
    let mut visited = HashSet::new();
    while let Some(expr) = stack.pop() {
        if !visited.insert(expr) {
            continue;
        }
        match &artifact.hir.expressions[usize::from(expr)].kind {
            HirExprKind::Identifier { name } => {
                if variable_names.contains(name.as_str())
                    && name.as_str() != current_target
                    && !variable_safety.get(name.as_str()).copied().unwrap_or(false)
                {
                    return false;
                }
            }
            HirExprKind::Binary { left, right, .. } => stack.extend([*left, *right]),
            HirExprKind::Unary { operand, .. } => stack.push(*operand),
            HirExprKind::Conditional {
                condition,
                then_expr,
                else_expr,
            } => stack.extend([*condition, *then_expr, *else_expr]),
            HirExprKind::Call { args, .. } => stack.extend(args.iter().copied()),
            HirExprKind::SystemFunction { name, args } => {
                if matches!(
                    name.trim_start_matches('$'),
                    "abstime"
                        | "realtime"
                        | "initial_step"
                        | "final_step"
                        | "analysis"
                        | "frequency"
                ) {
                    return false;
                }
                stack.extend(args.iter().copied());
            }
            HirExprKind::ArrayLiteral { elements, .. } => stack.extend(elements.iter().copied()),
            HirExprKind::ArrayAccess { .. }
            | HirExprKind::AnalogOperator { .. }
            | HirExprKind::Laplace { .. }
            | HirExprKind::Zi { .. }
            | HirExprKind::BranchAccess { .. }
            | HirExprKind::NamedBranchAccess { .. } => return false,
            HirExprKind::NoiseSource { operands, .. } => stack.extend(operands.iter().copied()),
            HirExprKind::NullArgument
            | HirExprKind::Number { .. }
            | HirExprKind::StringLiteral { .. } => {}
        }
    }
    true
}

