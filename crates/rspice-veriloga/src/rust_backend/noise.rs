fn noise_branch_unknowns(artifact: &CanonicalIrArtifact) -> HashMap<String, BranchCurrentSlot> {
    let mut slots = HashMap::new();
    for unknown in &artifact.mir.branch_unknowns {
        let slot = unknown.id.index() as usize;
        if let Some(name) = &unknown.declared_name {
            slots
                .entry(name.to_string())
                .or_insert_with(|| BranchCurrentSlot::forward(slot));
        }
        let pos = unknown.pos_node.map(|node| node.index() as usize);
        let neg = unknown.neg_node.map(|node| node.index() as usize);
        slots
            .entry(branch_pair_key(pos, neg))
            .or_insert_with(|| BranchCurrentSlot::forward(slot));
        slots
            .entry(branch_pair_key(neg, pos))
            .or_insert_with(|| BranchCurrentSlot::reverse(slot));
    }
    slots
}

fn potential_branch_leaders(artifact: &CanonicalIrArtifact) -> Vec<Option<u32>> {
    let mut leaders = vec![None; artifact.mir.equations.len()];
    let mut physical: Vec<(Option<NodeId>, Option<NodeId>, u32)> = Vec::new();
    for (equation_index, equation) in artifact.mir.equations.iter().enumerate() {
        if equation.kind != crate::canonical_ir::MirEquationKind::Potential {
            continue;
        }
        let Some(branch) = artifact
            .mir
            .branch_unknowns
            .iter()
            .find(|unknown| unknown.equation == equation.id)
            .map(|unknown| unknown.id.index())
        else {
            continue;
        };
        let leader = physical
            .iter()
            .find(|(pos, neg, _)| {
                (*pos == equation.branch.pos_node && *neg == equation.branch.neg_node)
                    || (*pos == equation.branch.neg_node && *neg == equation.branch.pos_node)
            })
            .map(|(_, _, leader)| *leader)
            .unwrap_or_else(|| {
                physical.push((equation.branch.pos_node, equation.branch.neg_node, branch));
                branch
            });
        leaders[equation_index] = Some(leader);
    }
    leaders
}

fn emit_lines(out: &mut String, lines: &[String], indentation: usize) {
    let padding = " ".repeat(indentation);
    for line in lines {
        writeln!(out, "{padding}{line}").expect("write lowered noise expression");
    }
}

fn active_source_expr(active_sources: &str, sources: &[usize]) -> String {
    let mut chunk_masks = Vec::<(usize, u128)>::new();
    for &source in sources {
        let chunk = source / 128;
        let bit = source % 128;
        match chunk_masks.last_mut() {
            Some((last_chunk, mask)) if *last_chunk == chunk => *mask |= 1u128 << bit,
            _ => chunk_masks.push((chunk, 1u128 << bit)),
        }
    }
    chunk_masks
        .into_iter()
        .map(|(chunk, mask)| format!("({active_sources}[{chunk}] & 0x{mask:x}) != 0"))
        .collect::<Vec<_>>()
        .join(" || ")
}

fn emit_finite_check(
    out: &mut String,
    index: usize,
    quantity: &str,
    value: &str,
    indentation: usize,
) {
    let padding = " ".repeat(indentation);
    writeln!(
        out,
        "{padding}if !{value}.is_finite() {{ return Err(GeneratedNoiseEvaluationError::NonFinite {{ index: {index}, quantity: {quantity:?}, value: {value} }}); }}"
    )
    .expect("write finite noise value validation");
}

fn emit_optional_finite_check(
    out: &mut String,
    index: usize,
    quantity: &str,
    value: &str,
    indentation: usize,
) {
    let padding = " ".repeat(indentation);
    writeln!(
        out,
        "{padding}if let Some(value) = {value} {{ if !value.is_finite() {{ return Err(GeneratedNoiseEvaluationError::NonFinite {{ index: {index}, quantity: {quantity:?}, value }}); }} }}"
    )
    .expect("write finite optional noise value validation");
}

fn noise_kind(kind: CanonicalNoiseSourceKind) -> &'static str {
    match kind {
        CanonicalNoiseSourceKind::White => "White",
        CanonicalNoiseSourceKind::Flicker => "Flicker",
        CanonicalNoiseSourceKind::Table => "Table",
    }
}

#[inline]
fn noise_rhs_sign(kind: MirEquationKind) -> f64 {
    match kind {
        MirEquationKind::Current => -1.0,
        MirEquationKind::Potential => 1.0,
        // Planning rejects indirect equations before emission because their
        // engine-neutral generated topology is not representable yet.
        MirEquationKind::Indirect => -1.0,
    }
}

fn endpoint_literal(node: Option<NodeId>, name: &str, is_internal: bool) -> String {
    format!(
        "GeneratedNoiseEndpoint {{ local_node: {}, name: {:?}, is_internal: {} }}",
        option_usize(node.map(NodeId::index)),
        name,
        is_internal
    )
}

fn option_str(value: Option<&str>) -> String {
    value.map_or_else(|| "None".to_string(), |value| format!("Some({value:?})"))
}

fn option_usize(value: Option<u32>) -> String {
    value.map_or_else(|| "None".to_string(), |value| format!("Some({value})"))
}

#[cfg(test)]
mod tests {
    use super::fragment_contains_return;

    #[test]
    fn bare_return_keyword_is_detected() {
        assert!(fragment_contains_return("    return;\n"));
        assert!(fragment_contains_return("if x > 1.0 { return Err(e); }"));
        assert!(fragment_contains_return("return"));
    }

    #[test]
    fn identifiers_containing_return_are_not_detected() {
        assert!(!fragment_contains_return("let returned_value = 1.0;"));
        assert!(!fragment_contains_return("let x = early_return + 2.0;"));
        assert!(!fragment_contains_return("w[3] = noreturn_flag;"));
    }

    #[test]
    fn return_inside_a_string_literal_is_not_detected() {
        assert!(!fragment_contains_return(
            "ctx.report_analog_loop_limit(\"return\", n, limit);"
        ));
        assert!(!fragment_contains_return(
            "let q: &str = \"a return b\"; let y = 1.0;"
        ));
    }

    #[test]
    fn escaped_quote_does_not_unbalance_string_tracking() {
        // The escaped quote must not close the literal, or the `return` that
        // follows inside it would be misread as live code.
        assert!(!fragment_contains_return("let s = \"a \\\" return b\";"));
        // ...and a real return after a literal containing an escape is found.
        assert!(fragment_contains_return("let s = \"a \\\" b\"; return;"));
    }

    #[test]
    fn the_emitted_loop_limit_report_is_accepted() {
        // Exactly what emit_noise_statements writes for an analog loop bound.
        assert!(!fragment_contains_return(
            "    if p_iterations > Self::MAX_ANALOG_LOOP_ITERATIONS \
             { ctx.report_analog_loop_limit(\"noise\", p_iterations, \
             Self::MAX_ANALOG_LOOP_ITERATIONS); break; }"
        ));
    }

    #[test]
    fn fallback_noise_seeds_event_state_for_both_replay_schedules() {
        let artifact = crate::VerilogACompiler::default()
            .compile_canonical_ir(
                r#"
module fallback_event_noise(p, n);
    inout p, n;
    electrical p, n;
    real count;
    analog begin
        @(initial_step("noise")) count = count + 1.0;
        if (count > 0.0)
            I(p, n) <+ white_noise(count, "count");
    end
endmodule
"#,
            )
            .expect("event-state fallback-noise fixture compiles");
        let count = artifact
            .hir
            .variables
            .iter()
            .find(|variable| variable.name == "count")
            .expect("count variable");
        assert!(count.is_state, "event-written variable must be stateful");

        let generated = super::generate_noise_file(
            &artifact,
            &crate::rust_backend::RustTranspileOptions::default(),
        )
        .expect("fallback noise emission succeeds")
        .contents;
        let seed = format!("w[{}] = self.event_state_accepted[0];", count.id.index());
        assert_eq!(generated.matches(&seed).count(), 2, "{generated}");
        let reset = generated.find("w.fill(0.0);").expect("metadata reset");
        assert!(
            generated[reset..].contains(&seed),
            "metadata replay must be reseeded after clearing its workspace"
        );
    }
}

