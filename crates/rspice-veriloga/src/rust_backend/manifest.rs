//! The `manifest.txt` recording what was generated and from what.
//!
//! The manifest is the record `check-builtins` reads to decide whether the
//! checked-in output is current: it pairs a digest of the model sources with
//! the generator's own source digest, so a change to either side is detected.
//! It also lists every emitted file and what each device costs in workspace
//! footprint, which is what makes a size regression visible in review.
//!
//! Rendering and parsing are both here and both exact — an unparseable
//! manifest is treated as stale rather than guessed at.

/// Schema 5 records the stable Cargo feature and package that own each model.
/// This makes the manifest authenticate both generated source and its reusable
/// compilation-artifact boundary.
pub const GENERATED_BUILTIN_MANIFEST_SCHEMA_VERSION: u32 = 5;

#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct GeneratedBuiltinManifestFile {
    pub relative_path: String,
    pub bytes: u64,
    pub blake3: String,
}

#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct GeneratedBuiltinManifestDevice {
    pub module_name: String,
    pub public_model_name: String,
    pub folder_name: String,
    pub feature_name: String,
    pub package_name: String,
    pub file_count: usize,
    pub source_bytes: u64,
    pub workspace: GeneratedBuiltinWorkspaceResources,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct GeneratedBuiltinWorkspaceResources {
    pub abi_version: u32,
    pub variable_count: usize,
    pub node_count: usize,
    pub branch_count: usize,
    pub transient_active_node_rows: usize,
    pub transient_active_branch_rows: usize,
    pub reactive_active_node_rows: usize,
    pub reactive_active_branch_rows: usize,
    pub retained_workspace_bytes_per_instance: u64,
    pub pooled_workspace_payload_bytes_per_thread: u64,
    pub legacy_dense_workspace_payload_bytes_per_instance: u64,
    pub stamp_state_payload_bytes_per_instance: u64,
    pub stamp_state_heap_allocations_per_instance: u64,
    pub stamp_state_pointer_slots_per_instance: u64,
    pub legacy_stamp_state_heap_allocations_per_instance: u64,
    pub legacy_stamp_state_pointer_slots_per_instance: u64,
}

#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct GeneratedBuiltinManifest {
    pub schema_version: u32,
    pub source_tree_digest: String,
    pub generator_digest: String,
    pub bundle_digest: String,
    pub device_count: usize,
    pub file_count: usize,
    pub source_bytes: u64,
    pub devices: Vec<GeneratedBuiltinManifestDevice>,
    pub files: Vec<GeneratedBuiltinManifestFile>,
}

pub fn render_generated_builtin_manifest(manifest: &GeneratedBuiltinManifest) -> String {
    let json =
        serde_json::to_string_pretty(manifest).expect("generated built-in manifest must serialize");
    format!("# Generated by RSpice Verilog-A built-in generation. Do not edit.\n{json}\n")
}

pub fn parse_generated_builtin_manifest(text: &str) -> Option<GeneratedBuiltinManifest> {
    let json_start = text.find('{')?;
    let manifest: GeneratedBuiltinManifest = serde_json::from_str(&text[json_start..]).ok()?;
    (manifest.schema_version == GENERATED_BUILTIN_MANIFEST_SCHEMA_VERSION).then_some(manifest)
}
