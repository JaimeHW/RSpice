/// How many packed scratch workspaces a generated device keeps pooled.
pub(super) const MAX_CACHED_SCRATCH_WORKSPACES: usize = 2;

fn unsupported(artifact: &CanonicalIrArtifact, feature: impl Into<String>) -> RustBackendError {
    RustBackendError::unsupported(
        artifact.metadata.source_package.as_str(),
        artifact.mir.module_name.as_str(),
        feature,
    )
}

pub(super) fn generate_mod_file() -> String {
    [
        "// @generated by rspice-veriloga; do not edit.",
        "#[cfg(feature = \"veriloga-builtins-noise\")]",
        "pub mod noise;",
        "pub mod state;",
        "mod stamp;",
        "",
        "#[cfg(feature = \"veriloga-builtins-noise\")]",
        "pub use noise::{GeneratedNoiseComplex, GeneratedNoiseDescriptor, GeneratedNoiseEndpoint, GeneratedNoiseEvaluation, GeneratedNoiseEvaluationError, GeneratedNoiseEvaluationRef, GeneratedNoiseInjectionDescriptor, GeneratedNoiseInjectionEvaluation, GeneratedNoiseKind, GeneratedNoiseProcessDescriptor, GeneratedNoiseProcessEvaluationRef, GeneratedNoiseProcessVisitor, GeneratedNoiseVisitor, GROUPED_NOISE_INJECTIONS, GROUPED_NOISE_PROCESSES, NOISE_SOURCES};",
        "pub use state::{Instance, Parameters};",
        "",
    ]
    .join("\n")
}

#[derive(Debug, Clone)]
pub(super) struct StateFileExtensions {
    /// Whether generated state uses accepted/candidate `cross` or `above`
    /// detector records and therefore needs their runtime helpers imported.
    pub uses_cross_event_state: bool,
    pub params_visibility: &'static str,
    pub support_types: String,
    pub instance_fields: String,
    pub clone_fields: String,
    pub new_initializers: String,
    pub after_new: String,
    pub set_parameter_hook: String,
    pub set_multiplicity_hook: String,
    pub impl_methods: String,
    pub limiter_converged_expr: String,
    pub rollback_value_count: usize,
    pub rollback_flag_count: usize,
    pub rollback_capture_values: String,
    pub rollback_capture_flags: String,
    pub rollback_restore_fields: String,
    pub checkpoint_capture_fields: String,
    pub checkpoint_shape_checks: String,
    pub checkpoint_restore_fields: String,
    /// Additional scalar lanes appended to `event_variables` after ordinary
    /// procedural event state. This keeps the public checkpoint envelope
    /// stable while generated event operators retain accepted history.
    pub persistent_event_lane_count: usize,
    pub checkpoint_event_capture: String,
    pub checkpoint_event_validate: String,
    pub checkpoint_event_restore: String,
    pub begin_event_state_evaluation: String,
    pub validate_advance_state: String,
    pub apply_advance_state: String,
}

