pub fn generate_generated_builtin_subset_with_progress_and_jobs(
    model_root: &Path,
    generated_root: &Path,
    filter: &str,
    progress: bool,
    jobs: Option<usize>,
) -> BuiltinResult<BuiltinSubsetGenerationReport> {
    reject_debug_preprocessor_output()?;
    validate_model_root(model_root)?;

    let (devices, _, kernel_structures) = generate_devices_with_stack(
        model_root.to_path_buf(),
        Some(filter.to_string()),
        progress,
        jobs,
    )?;
    if devices.is_empty() {
        return Err(format!(
            "Verilog-A built-ins source directory '{}' does not contain any modules matching filter '{filter}'",
            model_root.display()
        )
        .into());
    }

    reject_legacy_ad_runtime(&devices)?;
    remove_obsolete_generated_runtime_files(generated_root)?;
    write_device_subset(generated_root, &devices)?;

    Ok(BuiltinSubsetGenerationReport {
        device_count: devices.len(),
        kernel_structures,
    })
}

pub fn validate_generated_builtins(
    model_root: &Path,
    generated_root: &Path,
    generator_root: &Path,
    emit_cargo_rerun: bool,
) -> BuiltinResult<GeneratedBuiltinManifest> {
    reject_debug_preprocessor_output()?;
    validate_model_root(model_root)?;

    let source_tree_digest = tree_digest(model_root, emit_cargo_rerun)?;
    let generator_digest = generator_digest(generator_root, emit_cargo_rerun)?;
    if let Some(manifest) =
        read_generated_manifest(generated_root, &source_tree_digest, &generator_digest)
    {
        validate_generated_manifest_outputs(generated_root, &manifest)?;
        reject_legacy_ad_runtime_files(generated_root)?;
        return Ok(manifest);
    }

    Err(
        stale_generated_builtins_error(generated_root, &source_tree_digest, &generator_digest)
            .into(),
    )
}

fn reject_debug_preprocessor_output() -> BuiltinResult<()> {
    reject_debug_preprocessor_output_if(env::var_os(DEBUG_PREPROCESSOR_ENV).is_some())
}

fn reject_debug_preprocessor_output_if(debug_output_requested: bool) -> BuiltinResult<()> {
    if debug_output_requested {
        return Err(format!(
            "{DEBUG_PREPROCESSOR_ENV} must be unset during Verilog-A built-in generation and validation because it writes .pp.va files into the model source tree; unset it and retry"
        )
        .into());
    }
    Ok(())
}

fn verify_generation_inputs_unchanged(
    model_root: &Path,
    generator_root: &Path,
    source_tree_digest_before: &str,
    generator_digest_before: &str,
) -> BuiltinResult<()> {
    let source_tree_digest_after = tree_digest(model_root, false)?;
    let generator_digest_after = generator_digest(generator_root, false)?;
    ensure_generation_inputs_unchanged(
        source_tree_digest_before,
        generator_digest_before,
        &source_tree_digest_after,
        &generator_digest_after,
    )
}

fn ensure_generation_inputs_unchanged(
    source_tree_digest_before: &str,
    generator_digest_before: &str,
    source_tree_digest_after: &str,
    generator_digest_after: &str,
) -> BuiltinResult<()> {
    let mut changed = Vec::new();
    if source_tree_digest_before != source_tree_digest_after {
        changed.push(format!(
            "model sources changed (before={source_tree_digest_before}, after={source_tree_digest_after})"
        ));
    }
    if generator_digest_before != generator_digest_after {
        changed.push(format!(
            "generator inputs changed (before={generator_digest_before}, after={generator_digest_after})"
        ));
    }
    if changed.is_empty() {
        return Ok(());
    }

    Err(format!(
        "Verilog-A built-in generation inputs changed during generation: {}; generated output was not published; retry from stable model and generator source trees",
        changed.join("; ")
    )
    .into())
}

fn validate_model_root(model_root: &Path) -> BuiltinResult<()> {
    if !model_root.exists() {
        return Err(format!(
            "Verilog-A built-ins source directory '{}' does not exist",
            model_root.display()
        )
        .into());
    }
    if !model_root.is_dir() {
        return Err(format!(
            "Verilog-A built-ins source path '{}' is not a directory",
            model_root.display()
        )
        .into());
    }
    Ok(())
}

fn stale_generated_builtins_error(
    generated_root: &Path,
    source_tree_digest: &str,
    generator_digest: &str,
) -> String {
    let manifest_path = generated_root.join(GENERATED_BUILTIN_MANIFEST_FILE_NAME);
    let current = fs::read_to_string(&manifest_path)
        .ok()
        .and_then(|text| parse_generated_builtin_manifest(&text))
        .map(|manifest| {
            format!(
                "current manifest has schema_version={}, source_tree_digest={}, generator_digest={}, bundle_digest={}, device_count={}, file_count={}, source_bytes={}",
                manifest.schema_version,
                manifest.source_tree_digest,
                manifest.generator_digest,
                manifest.bundle_digest,
                manifest.device_count,
                manifest.file_count,
                manifest.source_bytes,
            )
        })
        .unwrap_or_else(|| "current manifest is missing or invalid".to_string());

    format!(
        "generated Verilog-A built-ins are stale; expected source_tree_digest={source_tree_digest}, generator_digest={generator_digest}; {current}. Run `{REGENERATE_BUILTINS_COMMAND}` before building rspice-core with the veriloga-builtins feature."
    )
}

fn generator_digest(generator_root: &Path, emit_cargo_rerun: bool) -> BuiltinResult<String> {
    let mut input = String::new();
    for relative in GENERATOR_SOURCE_DIGEST_INPUTS {
        let path = generator_root.join(relative);
        let digest = if path.is_dir() {
            tree_digest(&path, emit_cargo_rerun)?
        } else if path.is_file() {
            if emit_cargo_rerun {
                println!("cargo:rerun-if-changed={}", path.display());
            }
            file_digest(&path)?
        } else {
            return Err(format!(
                "Verilog-A generator digest input '{}' does not exist",
                path.display()
            )
            .into());
        };
        input.push_str(relative);
        input.push('\0');
        input.push_str(&digest);
        input.push('\0');
    }
    Ok(blake3::hash(input.as_bytes()).to_hex().to_string())
}

fn file_digest(path: &Path) -> BuiltinResult<String> {
    let bytes = fs::read(path)?;
    let text = String::from_utf8(bytes)?;
    let normalized = text.replace("\r\n", "\n").replace('\r', "\n");
    let mut input = String::new();
    input.push_str(&normalized.len().to_string());
    input.push('\0');
    input.push_str(&normalized);
    input.push('\0');
    Ok(blake3::hash(input.as_bytes()).to_hex().to_string())
}

fn read_generated_manifest(
    generated_root: &Path,
    source_tree_digest: &str,
    generator_digest: &str,
) -> Option<GeneratedBuiltinManifest> {
    if !generated_root.join("src").join("registry.rs").is_file() {
        return None;
    }
    let manifest_path = generated_root.join(GENERATED_BUILTIN_MANIFEST_FILE_NAME);
    let manifest = parse_generated_builtin_manifest(&fs::read_to_string(manifest_path).ok()?)?;
    (manifest.schema_version == GENERATED_BUILTIN_MANIFEST_SCHEMA_VERSION
        && manifest.source_tree_digest == source_tree_digest
        && manifest.generator_digest == generator_digest
        && manifest.device_count > 0
        && manifest.device_count == manifest.devices.len()
        && manifest.file_count == manifest.files.len())
    .then_some(manifest)
}

fn reject_legacy_ad_runtime(devices: &[GeneratedRustDevice]) -> BuiltinResult<()> {
    const MARKERS: &[&str] = LEGACY_AD_RUNTIME_MARKERS;

    for device in devices {
        for file in &device.files {
            if let Some(marker) = MARKERS
                .iter()
                .copied()
                .find(|marker| file.contents.contains(marker))
            {
                return Err(format!(
                    "{}:{} contains legacy Verilog-A AD marker {marker}",
                    device.folder_name, file.relative_path,
                )
                .into());
            }
        }
    }
    Ok(())
}

fn reject_legacy_ad_runtime_files(generated_root: &Path) -> BuiltinResult<()> {
    if generated_root.join("support.rs").is_file() {
        return Err(format!(
            "generated Verilog-A built-ins contain stale legacy support module '{}'",
            generated_root.join("support.rs").display()
        )
        .into());
    }
    let mut files = Vec::new();
    collect_tree_files(generated_root, &mut files)?;
    for path in files {
        let contents = fs::read_to_string(&path)?;
        if let Some(marker) = LEGACY_AD_RUNTIME_MARKERS
            .iter()
            .copied()
            .find(|marker| contents.contains(marker))
        {
            return Err(format!(
                "generated Verilog-A built-ins contain legacy AD marker {marker} in '{}'",
                path.display()
            )
            .into());
        }
    }
    Ok(())
}

const LEGACY_AD_RUNTIME_MARKERS: &[&str] = &[
    "GenericAdValue",
    "GenericScratch",
    "GenericReactiveScratch",
    "::support::",
];

fn remove_obsolete_generated_runtime_files(generated_root: &Path) -> BuiltinResult<()> {
    // `registry.rs` sat at the catalog root while it was `include!`d into
    // rspice-core. It is a module of the catalog now, so a root copy left by an
    // older generator is stale input the manifest would still fingerprint.
    for file_name in ["kernel_runtime.rs", "support.rs", "registry.rs"] {
        let path = generated_root.join(file_name);
        if path.is_file() {
            fs::remove_file(path)?;
        }
    }
    Ok(())
}

fn write_device_subset(
    generated_root: &Path,
    devices: &[GeneratedRustDevice],
) -> BuiltinResult<()> {
    std::fs::create_dir_all(generated_root)?;
    for device in devices {
        write_generated_device(generated_root, device)?;
    }
    Ok(())
}

const GENERATED_MODEL_PACKAGE_MARKER: &str = ".rspice-veriloga-model-package";
const GENERATED_MODEL_PACKAGE_MARKER_CONTENTS: &str =
    "Generated by RSpice Verilog-A. Safe to remove when this package is stale.\n";

fn write_model_packages(
    generated_root: &Path,
    devices: &[GeneratedRustDevice],
    packages: &[GeneratedModelPackage],
) -> BuiltinResult<()> {
    if devices.len() != packages.len() {
        return Err("generated device and package counts differ".into());
    }

    let models_root = generated_root.join("models");
    cleanup_stale_model_packages(&models_root, packages)?;
    for (device, package) in devices.iter().zip(packages) {
        if device.folder_name != package.folder_name {
            return Err(format!(
                "generated device '{}' does not match package '{}'",
                device.folder_name, package.folder_name
            )
            .into());
        }
        validate_package_slug(&package.package_slug)?;
        let package_root = models_root.join(&package.package_slug);
        let source_root = package_root.join("src");
        fs::create_dir_all(&source_root)?;
        write_text_file_if_changed(
            package_root.join(GENERATED_MODEL_PACKAGE_MARKER),
            GENERATED_MODEL_PACKAGE_MARKER_CONTENTS,
        )?;
        write_text_file_if_changed(
            package_root.join("Cargo.toml"),
            &render_model_package_manifest(package),
        )?;
        write_text_file_if_changed(
            source_root.join("lib.rs"),
            &render_model_package_lib(package),
        )?;
        cleanup_stale_generated_device_folders(
            &source_root,
            std::iter::once(device.folder_name.as_str()),
        )?;
        write_generated_device(&source_root, device)?;
    }

    write_text_file_if_changed(
        generated_root.join("Cargo.toml"),
        &render_model_catalog_manifest(packages),
    )?;
    fs::create_dir_all(generated_root.join("src"))?;
    write_text_file_if_changed(
        generated_root.join("src/lib.rs"),
        &render_model_catalog_lib(packages),
    )?;
    Ok(())
}

fn cleanup_stale_model_packages(
    models_root: &Path,
    packages: &[GeneratedModelPackage],
) -> BuiltinResult<()> {
    fs::create_dir_all(models_root)?;
    let expected = packages
        .iter()
        .map(|package| package.package_slug.as_str())
        .collect::<std::collections::HashSet<_>>();
    for entry in fs::read_dir(models_root)? {
        let entry = entry?;
        if !entry.file_type()?.is_dir() {
            continue;
        }
        let slug = entry.file_name().to_string_lossy().into_owned();
        let path = entry.path();
        if expected.contains(slug.as_str()) || !path.join(GENERATED_MODEL_PACKAGE_MARKER).is_file()
        {
            continue;
        }
        fs::remove_dir_all(path)?;
    }
    Ok(())
}

fn validate_package_slug(slug: &str) -> BuiltinResult<()> {
    if slug.is_empty()
        || slug.starts_with('-')
        || slug.ends_with('-')
        || !slug
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
    {
        return Err(format!("invalid generated model package slug '{slug}'").into());
    }
    Ok(())
}

fn render_model_package_manifest(package: &GeneratedModelPackage) -> String {
    format!(
        "[package]\nname = {:?}\ndescription = \"Precompiled RSpice Verilog-A model artifact\"\nversion.workspace = true\nedition.workspace = true\nauthors.workspace = true\nlicense-file.workspace = true\npublish.workspace = true\nrepository.workspace = true\nrust-version.workspace = true\n\n[features]\ndefault = []\nveriloga-builtins-noise = []\n\n[dependencies]\nrspice-veriloga-runtime.workspace = true\n\n[lib]\ndoctest = false\n\n[lints]\nworkspace = true\n",
        package.package_name
    )
}

fn render_model_package_lib(package: &GeneratedModelPackage) -> String {
    format!(
        "// @generated by rspice-veriloga; do not edit.\n//! Precompiled generated Verilog-A model. Do not edit.\n\n#![allow(clippy::all, unused_assignments)]\n\n#[rustfmt::skip]\n#[allow(non_snake_case)]\n#[path = {:?}]\npub mod {};\n",
        format!("{}/mod.rs", package.folder_name),
        package.folder_name
    )
}

fn render_model_catalog_manifest(packages: &[GeneratedModelPackage]) -> String {
    let mut out = String::from(
        "[package]\nname = \"rspice-veriloga-models\"\ndescription = \"Feature-selectable precompiled Verilog-A model catalog for RSpice\"\nversion.workspace = true\nedition.workspace = true\nauthors.workspace = true\nlicense-file.workspace = true\npublish.workspace = true\nrepository.workspace = true\nrust-version.workspace = true\n\n[features]\ndefault = []\n",
    );
    for package in packages {
        let _ = writeln!(
            out,
            "{} = [\"dep:{}\"]",
            package.feature_name, package.package_name
        );
    }
    out.push_str("veriloga-builtins-noise = [\n");
    for package in packages {
        let _ = writeln!(
            out,
            "    \"{}?/veriloga-builtins-noise\",",
            package.package_name
        );
    }
    out.push_str("]\n\n[dependencies]\nrspice-veriloga-runtime.workspace = true\n");
    for package in packages {
        let _ = writeln!(
            out,
            "{} = {{ path = {:?}, version = \"0.1.0\", optional = true }}",
            package.package_name,
            format!("models/{}", package.package_slug)
        );
    }
    out.push_str("\n[lib]\ndoctest = false\n\n[lints]\nworkspace = true\n");
    out
}

fn render_model_catalog_lib(packages: &[GeneratedModelPackage]) -> String {
    let mut out = String::from(
        "// @generated by rspice-veriloga; do not edit.\n\
         //! Feature-selectable precompiled Verilog-A model catalog. Do not edit.\n\
         \n\
         // `registry` reaches its ABI types through `super::`, so the catalog\n\
         // root is where they have to land.\n\
         pub use rspice_veriloga_runtime::*;\n\
         \n\
         #[rustfmt::skip]\n\
         pub mod registry;\n\n",
    );
    let mut sorted_packages = packages.iter().collect::<Vec<_>>();
    sorted_packages
        .sort_by(|left, right| natural_name_cmp(&left.feature_name, &right.feature_name));
    for package in sorted_packages {
        let crate_name = package.package_name.replace('-', "_");
        let _ = writeln!(
            out,
            "#[cfg(feature = {:?})]\npub use {}::{};",
            package.feature_name, crate_name, package.folder_name
        );
    }
    out
}

fn natural_name_cmp(left: &str, right: &str) -> std::cmp::Ordering {
    let mut left = left.as_bytes();
    let mut right = right.as_bytes();
    while !left.is_empty() && !right.is_empty() {
        if left[0].is_ascii_digit() && right[0].is_ascii_digit() {
            let left_end = left
                .iter()
                .position(|byte| !byte.is_ascii_digit())
                .unwrap_or(left.len());
            let right_end = right
                .iter()
                .position(|byte| !byte.is_ascii_digit())
                .unwrap_or(right.len());
            let left_digits = &left[..left_end];
            let right_digits = &right[..right_end];
            let left_significant = left_digits
                .iter()
                .position(|byte| *byte != b'0')
                .map_or(&left_digits[left_digits.len()..], |start| {
                    &left_digits[start..]
                });
            let right_significant = right_digits
                .iter()
                .position(|byte| *byte != b'0')
                .map_or(&right_digits[right_digits.len()..], |start| {
                    &right_digits[start..]
                });
            let numeric = left_significant
                .len()
                .cmp(&right_significant.len())
                .then_with(|| left_significant.cmp(right_significant))
                .then_with(|| left_digits.len().cmp(&right_digits.len()));
            if numeric != std::cmp::Ordering::Equal {
                return numeric;
            }
            left = &left[left_end..];
            right = &right[right_end..];
            continue;
        }
        let lexical = left[0].cmp(&right[0]);
        if lexical != std::cmp::Ordering::Equal {
            return lexical;
        }
        left = &left[1..];
        right = &right[1..];
    }
    left.len().cmp(&right.len())
}

