/// What a full regeneration produced.
///
/// The manifest is the whole result. This used to also carry per-tier counts
/// and a list of fallbacks; with one emitter there is nothing to count and
/// nothing to fall back to.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BuiltinGenerationReport {
    pub manifest: GeneratedBuiltinManifest,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BuiltinSubsetGenerationReport {
    pub device_count: usize,
    pub kernel_structures: Vec<GeneratedKernelStructureReport>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedKernelStructureReport {
    pub public_model_name: String,
    pub regions: Vec<KernelRegionMetric>,
    pub noise_invalidation_value_count: [u64; 5],
    pub noise_shared_preprocess_value_count: u64,
}

impl GeneratedKernelStructureReport {
    pub fn newton_instruction_count(&self) -> u64 {
        self.regions.iter().fold(0u64, |total, region| {
            total.saturating_add(region.newton_instruction_count)
        })
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct KernelFamilyCoverage {
    pub common_newton_instruction_count: u64,
    pub models: Vec<(String, u64, f64)>,
}

pub fn common_kernel_coverage(reports: &[GeneratedKernelStructureReport]) -> KernelFamilyCoverage {
    let mut common = HashMap::<(String, u64), usize>::new();
    if let Some(first) = reports.first() {
        for region in &first.regions {
            *common
                .entry((region.fingerprint.clone(), region.newton_instruction_count))
                .or_default() += 1;
        }
        for report in &reports[1..] {
            let mut available = HashMap::<(String, u64), usize>::new();
            for region in &report.regions {
                *available
                    .entry((region.fingerprint.clone(), region.newton_instruction_count))
                    .or_default() += 1;
            }
            common.retain(|key, count| {
                *count = (*count).min(available.get(key).copied().unwrap_or(0));
                *count != 0
            });
        }
    }
    let common_newton_instruction_count =
        common
            .iter()
            .fold(0u64, |total, ((_, instructions), occurrences)| {
                total.saturating_add(instructions.saturating_mul(*occurrences as u64))
            });
    let models = reports
        .iter()
        .map(|report| {
            let total = report.newton_instruction_count();
            let coverage = if total == 0 {
                0.0
            } else {
                common_newton_instruction_count as f64 * 100.0 / total as f64
            };
            (report.public_model_name.clone(), total, coverage)
        })
        .collect();
    KernelFamilyCoverage {
        common_newton_instruction_count,
        models,
    }
}

