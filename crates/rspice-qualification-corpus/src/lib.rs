//! Generator for the RSpice simulator-qualification policy and corpus.
//!
//! The corpus is a signed release artifact: at least 250 self-contained
//! SPICE cases whose expected values come from engine-independent oracles
//! (closed-form analysis or reference-simulator data) and whose series
//! identities are captured from the engine itself, so release admission
//! proves both accuracy against independent truth and bit-exact
//! reproducibility of the shipped worker. The cloud's admission tools
//! remain the schema authority; [`contract`] mirrors them so generation
//! fails here instead of there.
//!
//! Series identity is platform-sensitive at the ULP level (libm), so the
//! authoritative corpus is generated by the publishing lane on the
//! qualification platform (linux/amd64) at the same source revision as the
//! attested adapter image. Local runs on other platforms validate structure
//! and oracle math, not final hashes.

