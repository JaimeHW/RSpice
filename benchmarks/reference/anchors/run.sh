#!/usr/bin/env bash
# Measure hand-written compact-model evaluation cost in ngspice.
#
# See README.md for the method. Decks are regenerated on every run so the
# checked-in ones can never drift from the generator that documents them.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ngspice="${RSPICE_BENCH_NGSPICE:-}"
if [[ -z "$ngspice" ]]; then
  echo "RSPICE_BENCH_NGSPICE is not set; point it at an ngspice_con executable" >&2
  exit 2
fi
if [[ ! -x "$ngspice" ]]; then
  echo "not executable: $ngspice" >&2
  exit 2
fi

# Instances of the device under test per loaded deck.
#
# Large enough that per-call overhead and the fixed cost of the sources are
# small next to the model itself; small enough that the matrix stays sparse and
# the run finishes in seconds.
DEVICES=200

# Sweep points. Multiplied by the Newton iterations each point needs, this sets
# how many evaluations the timing averages over.
SWEEP_POINTS=200

emit_vbic() {
  local mode="$1" path="$2"
  {
    echo "* VBIC anchor ($mode): $DEVICES devices, generated by run.sh"
    echo ".options acct"
    echo "vb 1 0 dc 0.8"
    echo "vc 2 0 dc 2.0"
    for ((i = 1; i <= DEVICES; i++)); do
      if [[ "$mode" == loaded ]]; then
        echo "q$i 2 1 0 qmod"
      else
        # Same two terminals, same node count, linear.
        echo "r$i 2 1 1meg"
      fi
    done
    echo ".model qmod npn level=4"
    echo ".dc vb 0.5 0.9 $(awk -v p="$SWEEP_POINTS" 'BEGIN{printf "%.6f", 0.4/p}')"
    echo ".print dc i(vc)"
    echo ".end"
  } > "$path"
}

emit_bsim4() {
  local mode="$1" path="$2"
  {
    echo "* BSIM4 anchor ($mode): $DEVICES devices, generated by run.sh"
    echo ".options acct"
    echo "vg 1 0 dc 1.0"
    echo "vd 2 0 dc 1.0"
    for ((i = 1; i <= DEVICES; i++)); do
      if [[ "$mode" == loaded ]]; then
        echo "m$i 2 1 0 0 nmod w=1u l=45n"
      else
        echo "r$i 2 1 1meg"
      fi
    done
    echo ".model nmod nmos level=14 version=4.8.2"
    echo ".dc vg 0.2 1.0 $(awk -v p="$SWEEP_POINTS" 'BEGIN{printf "%.6f", 0.8/p}')"
    echo ".print dc i(vd)"
    echo ".end"
  } > "$path"
}

# Extract `Matrix load time` and `Total iterations` from an acct run.
#
# Both must be present and the iteration count non-zero; a deck that failed to
# converge reports a load time that means nothing, and silently dividing by it
# would produce a plausible-looking anchor from a broken run.
measure() {
  local deck="$1" out
  out="$("$ngspice" -b "$deck" 2>&1 || true)"
  local load iters
  load="$(printf '%s\n' "$out" | awk -F= '/Matrix load time/ {gsub(/ /,"",$2); print $2; exit}')"
  iters="$(printf '%s\n' "$out" | awk -F= '/^Total iterations/ {gsub(/ /,"",$2); print $2; exit}')"
  if [[ -z "$load" || -z "$iters" || "$iters" == "0" ]]; then
    echo "measurement failed for $deck" >&2
    printf '%s\n' "$out" | tail -20 >&2
    exit 1
  fi
  printf '%s %s\n' "$load" "$iters"
}

anchor() {
  local name="$1" emit="$2"
  "$emit" loaded "$here/${name}_loaded.cir"
  "$emit" empty "$here/${name}_empty.cir"

  read -r loaded_load loaded_iters <<<"$(measure "$here/${name}_loaded.cir")"
  read -r empty_load empty_iters <<<"$(measure "$here/${name}_empty.cir")"

  awk -v n="$name" -v ll="$loaded_load" -v li="$loaded_iters" \
      -v el="$empty_load" -v ei="$empty_iters" -v d="$DEVICES" '
    BEGIN {
      per = (ll / li - el / ei) / d * 1e9
      printf "    {\n"
      printf "      \"model\": \"%s\",\n", n
      printf "      \"devices\": %d,\n", d
      printf "      \"loaded_load_seconds\": %s,\n", ll
      printf "      \"loaded_iterations\": %s,\n", li
      printf "      \"empty_load_seconds\": %s,\n", el
      printf "      \"empty_iterations\": %s,\n", ei
      printf "      \"ns_per_device_per_iteration\": %.1f\n", per
      printf "    }"
    }'
}

{
  echo "{"
  echo "  \"note\": \"ngspice Matrix load time, loaded minus empty, per device per Newton iteration. See README.md.\","
  # `--version` banners the build over several lines and leads with a rule of
  # asterisks; the identifying line is the one naming the program.
  printf '  "ngspice": "%s",\n' \
    "$("$ngspice" --version 2>&1 | awk '/Circuit level simulation/ {gsub(/^\*\* /,""); gsub(/\r/,""); print; exit}')"
  echo "  \"anchors\": ["
  anchor vbic emit_vbic
  echo ","
  anchor bsim4 emit_bsim4
  echo ""
  echo "  ]"
  echo "}"
} > "$here/anchors.json"

cat "$here/anchors.json"
